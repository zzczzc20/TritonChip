#!/usr/bin/env python3
"""
Generate tb/core/progs/t06_alu.s -- randomised differential test of the integer
datapath against a Python model.

It exists mainly to cover `mulh`: the signed high product is derived from the
unsigned one rather than computed by a second multiplier array (see
rtl/core/tnca_scalar_alu.v), and that correction is exactly the kind of
algebraic shortcut that a handful of directed cases can miss.
"""
import os
import random
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
M64 = (1 << 64) - 1
M32 = (1 << 32) - 1


def s64(x):
    x &= M64
    return x - (1 << 64) if x >> 63 else x


def s32(x):
    x &= M32
    return x - (1 << 32) if x >> 31 else x


def clz64(x):
    return 64 if x == 0 else 64 - x.bit_length()


INTERESTING64 = [0, 1, 2, M64, M64 - 1, 1 << 63, (1 << 63) - 1, (1 << 63) + 1,
                 1 << 32, (1 << 32) - 1, 0x5555555555555555, 0xaaaaaaaaaaaaaaaa,
                 3, 0xffffffff00000000, 0x00000000ffffffff]
INTERESTING32 = [0, 1, 2, M32, M32 - 1, 1 << 31, (1 << 31) - 1, (1 << 31) + 1,
                 0x5555aaaa, 0xaaaa5555, 3, 0xffff0000, 0x0000ffff]


def main():
    rng = random.Random(20260918)
    out = []
    w = out.append
    tid = [0]

    def nid():
        tid[0] += 1
        return tid[0]

    def pick64():
        return rng.choice(INTERESTING64) if rng.random() < 0.4 else rng.getrandbits(64)

    def pick32():
        return rng.choice(INTERESTING32) if rng.random() < 0.4 else rng.getrandbits(32)

    w("// t06_alu -- generated by gen_t06_alu.py; do not edit by hand.")
    w("// Randomised integer-datapath check, with the emphasis on mulh.")
    w(".org 0")
    w("start:")

    # ---- scalar -----------------------------------------------------------
    for _ in range(90):
        a, b = pick64(), pick64()
        w(f"    .li s1, #0x{a:016x}")
        w(f"    .li s2, #0x{b:016x}")
        op = rng.choice(['mul', 'mulh.s', 'mulh.u', 'shl', 'lshr', 'ashr',
                         'min.s', 'max.s', 'min.u', 'max.u', 'clz', 'popc',
                         'sub', 'andn'])
        if op == 'mul':
            e = (a * b) & M64
        elif op == 'mulh.s':
            e = ((s64(a) * s64(b)) >> 64) & M64
        elif op == 'mulh.u':
            e = (a * b) >> 64
        elif op == 'shl':
            e = (a << (b & 63)) & M64
        elif op == 'lshr':
            e = a >> (b & 63)
        elif op == 'ashr':
            e = (s64(a) >> (b & 63)) & M64
        elif op == 'min.s':
            e = a if s64(a) < s64(b) else b
        elif op == 'max.s':
            e = b if s64(a) < s64(b) else a
        elif op == 'min.u':
            e = min(a, b)
        elif op == 'max.u':
            e = max(a, b)
        elif op == 'clz':
            e = clz64(a)
        elif op == 'popc':
            e = bin(a).count('1')
        elif op == 'sub':
            e = (a - b) & M64
        else:
            e = a & (~b & M64)

        if op in ('clz', 'popc'):
            w(f"    s.{op} s3, s1")
        else:
            w(f"    s.{op} s3, s1, s2")
        w(f"    .assert_eq s3, #0x{e:016x}, #{nid()}")

    # ---- vector -----------------------------------------------------------
    # Each group loads 16 lanes of a and b from memory and checks four lanes,
    # which keeps the program a sane size while still exercising every lane
    # position across the groups.
    data = []
    for g in range(24):
        av = [pick32() for _ in range(16)]
        bv = [pick32() for _ in range(16)]
        data.append((av, bv))

    w("    .li s10, #vdata")
    for g, (av, bv) in enumerate(data):
        off = g * 128
        w(f"    v.ld.w v1, [s10, #{off}]")
        w(f"    v.ld.w v2, [s10, #{off + 64}]")
        op = ['mul', 'mulh.s', 'mulh.u', 'shl', 'lshr', 'ashr',
              'min.s', 'max.s', 'min.u', 'max.u', 'clz', 'popc'][g % 12]
        if op in ('clz', 'popc'):
            w(f"    v.{op} v3, v1")
        else:
            w(f"    v.{op} v3, v1, v2")
        for lane in rng.sample(range(16), 4):
            a, b = av[lane], bv[lane]
            if op == 'mul':
                e = (a * b) & M32
            elif op == 'mulh.s':
                e = ((s32(a) * s32(b)) >> 32) & M32
            elif op == 'mulh.u':
                e = (a * b) >> 32
            elif op == 'shl':
                e = (a << (b & 31)) & M32
            elif op == 'lshr':
                e = a >> (b & 31)
            elif op == 'ashr':
                e = (s32(a) >> (b & 31)) & M32
            elif op == 'min.s':
                e = a if s32(a) < s32(b) else b
            elif op == 'max.s':
                e = b if s32(a) < s32(b) else a
            elif op == 'min.u':
                e = min(a, b)
            elif op == 'max.u':
                e = max(a, b)
            elif op == 'clz':
                e = 32 if a == 0 else 32 - a.bit_length()
            else:
                e = bin(a).count('1')
            w(f"    .assert_lane v3, #{lane}, #0x{e:08x}, #{nid()}")

    w("    exit")
    w("")
    w(".org 0x8000")
    w("vdata:")
    for av, bv in data:
        for vec in (av, bv):
            for k in range(0, 16, 8):
                w("    .word " + ", ".join(f"0x{v:08x}" for v in vec[k:k + 8]))

    path = os.path.join(HERE, 't06_alu.s')
    with open(path, 'w') as fh:
        fh.write("\n".join(out) + "\n")
    print(f"{tid[0]} checks -> {path}")


if __name__ == '__main__':
    main()
