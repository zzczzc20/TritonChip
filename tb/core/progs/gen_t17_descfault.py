#!/usr/bin/env python3
"""
Generate tb/core/progs/t17_descfault.s -- a geometry the engine must refuse.

ISA sec 9E.2 lists what raises DESCRIPTOR_FAULT rather than being
approximated. This program used to check a 26-byte FP16 row stride: the
engine once returned every row after the first shifted by two bytes and
raised nothing, and the fix was to refuse the stride. Since R38's rank-5
engine assembles a misaligned row from two memory words, that stride is
legal and transferred exactly -- t33_tdesc_load.s checks it lane by lane.

What remains refused is the same class of mistake one level down: a
"contiguous" dimension whose stride is not one element. The engine copies
runs; it does not gather per element. Here the FP16 descriptor's innermost
stride is 4 bytes, so a copy would return every other element -- and must
fault instead. Run with +expectfault=04.
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))

SRC = 0x8000
DESC = 0x9000
LDB = 32            # FP16 elements per row
ROWS = 16


def tensormap(base, e0, e1, s0, s1, b0, b1, rank=2, dtype=0, pad=0):
    w = [0] * 32
    w[0] = base
    w[1] = e0
    w[2] = e1
    w[6] = s0
    w[7] = s1
    w[11] = (b1 << 32) | b0
    w[13] = (pad << 48) | (dtype << 40) | (rank << 32)
    return w


out = []
w = out.append
w("// t17_descfault -- generated by gen_t17_descfault.py; do not edit.")
w("//")
w("// An FP16 descriptor whose innermost stride is 4 bytes: the 'contiguous'")
w("// dimension is every other element. The engine copies runs, so a transfer")
w("// would return the wrong elements; ISA sec 9E.2 makes it DESCRIPTOR_FAULT.")
w(".org 0")
w("start:")
w("    w.def     w0, #32, #8")
w(f"    .li       s1, #{DESC}")
w("    td.load   d0, [s1]")
w("    mb.init   b0")
w("    mb.arm    s2, b0, #0, #1")
w("    .li       s10, #0")
w("    .li       s11, #0")
w("    t.ld.async.h w0, d0, s10, s2      // must raise DESCRIPTOR_FAULT")
w("    mb.wait   s2")
w("    trap      #99                     // must be unreachable")
w("")


def emit(addr, words, label):
    w(f".org {addr:#x}")
    w(f"{label}:")
    for x in words:
        w(f"    .dword 0x{x & ((1 << 64) - 1):016x}")
    w("")


emit(SRC, [0] * (ROWS * LDB // 4 + 4), "src")
emit(DESC, tensormap(SRC, ROWS, LDB // 2, LDB * 2, 4, 16, 16), "desc")

path = os.path.join(HERE, 't17_descfault.s')
open(path, 'w').write('\n'.join(out) + '\n')
print(f"wrote {path}: an innermost stride of 4 bytes on FP16 must fault")
