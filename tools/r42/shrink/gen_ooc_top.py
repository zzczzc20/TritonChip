#!/usr/bin/env python3
"""gen_ooc_top.py FILE MODULE [WRAPPER_NAME] -- an out-of-context wrapper that registers every port of an ANSI-style Verilog module (R42-shrink).

Every input of the wrapper goes through one register before it reaches the module and every output of the module through one register
(reset-free), so every timing path of the unit under test is register to register, as in tools/r42/area/ooc_tops.v. The wrapper has the same
parameters as the module (same names and defaults: the OOC flow passes them as generics). Inputs named clk are the clock, rst_n the reset
(registered too: the module sees a registered reset, like the in-tile reset tree).
"""
import re
import sys


def strip_comments(s):
    s = re.sub(r'/\*.*?\*/', '', s, flags=re.S)
    return re.sub(r'//[^\n]*', '', s)


def split_top(s, sep=','):
    out, depth, cur = [], 0, ''
    for ch in s:
        if ch in '([{':
            depth += 1
        elif ch in ')]}':
            depth -= 1
        if ch == sep and depth == 0:
            out.append(cur)
            cur = ''
        else:
            cur += ch
    if cur.strip():
        out.append(cur)
    return out


def main():
    path, mod = sys.argv[1], sys.argv[2]
    wname = sys.argv[3] if len(sys.argv) > 3 else 'ooc_' + mod
    src = strip_comments(open(path).read())
    m = re.search(r'\bmodule\s+' + re.escape(mod) + r'\b', src)
    i = m.end()
    params, ports = [], []
    rest = src[i:]
    if rest.lstrip().startswith('#'):
        j = rest.index('(')
        depth, k = 0, j
        while True:
            if rest[k] == '(':
                depth += 1
            elif rest[k] == ')':
                depth -= 1
                if depth == 0:
                    break
            k += 1
        params = split_top(rest[j + 1:k])
        rest = rest[k + 1:]
    j = rest.index('(')
    depth, k = 0, j
    while True:
        if rest[k] == '(':
            depth += 1
        elif rest[k] == ')':
            depth -= 1
            if depth == 0:
                break
        k += 1
    portsrc = rest[j + 1:k]
    pnames = []
    for p in params:
        p = p.strip()
        mm = re.match(r'parameter\s*(?:integer\s*)?(\[[^\]]*\]\s*)?(\w+)\s*=', p)
        if not mm:
            mm = re.match(r'parameter\s+(?:integer\s+)?(\w+)', p)
            if not mm:
                raise SystemExit('cannot parse parameter: ' + p)
            pnames.append((None, mm.group(1)))
        else:
            pnames.append((mm.group(1), mm.group(2)))
    cur_dir, cur_rng = None, ''
    for p in split_top(portsrc):
        p = ' '.join(p.split())
        mm = re.match(r'(input|output|inout)\s*(?:wire|reg)?\s*(\[[^\]]*\])?\s*(\w+)$', p)
        if mm:
            cur_dir, cur_rng = mm.group(1), mm.group(2) or ''
            ports.append((cur_dir, cur_rng, mm.group(3)))
        else:
            mm = re.match(r'(\w+)$', p)
            if not mm or cur_dir is None:
                raise SystemExit('cannot parse port: ' + p)
            ports.append((cur_dir, cur_rng, mm.group(1)))
    o = []
    o.append('// generated by tools/r42/shrink/gen_ooc_top.py from %s (module %s); every port registered' % (path, mod))
    o.append('module %s #(' % wname)
    o.append(',\n'.join('    ' + ' '.join(pp.split()) for pp in params))
    o.append(') (')
    pl = ['    input wire clk']
    for d, r, n in ports:
        if n == 'clk':
            continue
        if d == 'input':
            pl.append('    input wire %s i_%s' % (r, n))
        else:
            pl.append('    output reg %s o_%s' % (r, n))
    o.append(',\n'.join(pl))
    o.append(');')
    for d, r, n in ports:
        if n == 'clk':
            continue
        if d == 'input':
            o.append('    reg %s r_%s; always @(posedge clk) r_%s <= i_%s;' % (r, n, n, n))
        else:
            o.append('    wire %s w_%s; always @(posedge clk) o_%s <= w_%s;' % (r, n, n, n))
    o.append('    %s #(' % mod)
    o.append(',\n'.join('        .%s(%s)' % (n, n) for r, n in pnames))
    o.append('    ) dut (')
    conns = []
    for d, r, n in ports:
        if n == 'clk':
            conns.append('        .clk(clk)')
        elif d == 'input':
            conns.append('        .%s(r_%s)' % (n, n))
        else:
            conns.append('        .%s(w_%s)' % (n, n))
    o.append(',\n'.join(conns))
    o.append('    );')
    o.append('endmodule')
    print('\n'.join(o))


if __name__ == '__main__':
    main()
