#!/usr/bin/env python3
"""
Generate tb/core/progs/t12_tensor.s -- TensorMap descriptors, RF windows and
the transfer engine, ending in a tiled GEMM that never touches a scratchpad.

The point of the last phase is the architecture's central claim: a tile reaches
the matrix unit as global memory -> NUCA -> vector registers -> fragment, with
nothing software-addressable in between.
"""
import os
import random
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..', '..'))
sys.path.insert(0, os.path.join(ROOT, 'tools', 'model'))
from fp32 import f32_to_f16_bits, mma_ref, f2b, b2f     # noqa: E402

# Matrices live in memory as FP16, row major.
LDA = 32              # a wider matrix than the tile, so strides matter
LDB = 32
TILE = 16
K = 16

A_BASE  = 0x4000      # 16 x 32 FP16
B_BASE  = 0x5000      # 16 x 32 FP16
DA_BASE = 0x6000      # TensorMap for A
DB_BASE = 0x6100      # TensorMap for B
DE_BASE = 0x6200      # TensorMap that runs off the edge, to test padding

rng = random.Random(20260920)

def rnd_half():
    if rng.random() < 0.6:
        return f32_to_f16_bits(rng.randint(-6, 6))
    return f32_to_f16_bits(rng.randint(-24, 24) / 4.0)

Amat = [[rnd_half() for _ in range(LDA)] for _ in range(TILE)]
Bmat = [[rnd_half() for _ in range(LDB)] for _ in range(TILE)]

out = []
w = out.append
tid = [0]
def nid():
    tid[0] += 1
    return tid[0]


def tensormap(base, e0, e1, s0, s1, b0, b1, rank=2, dtype=0, pad=0):
    """The 256-byte layout of ISA sec 9D.3, as 32 little-endian 64-bit words."""
    words = [0] * 32
    words[0] = base
    words[1] = e0                      # extent[0]
    words[2] = e1                      # extent[1]
    words[6] = s0                      # byte_stride[0]
    words[7] = s1                      # byte_stride[1]
    words[11] = (b1 << 32) | b0        # block_shape[0], block_shape[1]
    words[13] = (pad << 48) | (dtype << 40) | (rank << 32)
    return words


w("// t12_tensor -- generated by gen_t12_tensor.py; do not edit by hand.")
w(".org 0")
w("start:")

# ---- windows and descriptors ----------------------------------------------
w("    // A window names vector registers and nothing else (ISA sec 9D.2).")
w("    w.def     w0, #32, #8          // v32..v39: the A fragment")
w("    w.def     w1, #40, #8          // v40..v47: the B fragment")
w(f"    .li       s1, #{DA_BASE}")
w("    td.load   d0, [s1]")
w(f"    .li       s2, #{DB_BASE}")
w("    td.load   d1, [s2]")
w("")

# ---- phase 1: an in-bounds tile -------------------------------------------
w("    // ---- an aligned, fully in-bounds tile ----")
w("    mb.init   b0")
w("    mb.arm    s3, b0, #0, #2       // two transfers")
w("    .li       s10, #0              // coord0")
w("    .li       s11, #0              // coord1  (consecutive registers)")
w("    t.ld.async.h w0, d0, s10, s3")
w("    t.ld.async.h w1, d1, s10, s3")
w("    mb.wait   s3")
w("")
w("    // the fragment is exactly what the matrix unit expects: no repacking")
w("    m.zero    a0")
w("    mb.arm    s4, b0, #0, #1")
w("    m.mma.async a0, v32, v40, s4")
w("    mb.wait   s4")
w("")

A0 = [Amat[r][c] for r in range(TILE) for c in range(K)]
B0 = [Bmat[r][c] for r in range(K) for c in range(TILE)]
C0 = mma_ref(A0, B0, [f2b(0.0)] * (TILE * TILE), TILE, TILE, K)
for r in (0, 5, 15):
    w(f"    .li       s5, #{r}")
    w("    a.vread   v1, a0, s5")
    for c in (0, 7, 15):
        w(f"    .assert_lane v1, #{c}, #0x{C0[r*TILE+c]:08x}, #{nid()}")
w("")

# ---- phase 2: a tile at a column offset, exercising the stride -------------
w("    // ---- the same descriptor, a tile 16 columns along ----")
w("    mb.arm    s3, b0, #0, #1")
w("    .li       s10, #0")
w("    .li       s11, #16")
w("    t.ld.async.h w0, d0, s10, s3")
w("    mb.wait   s3")
w("    m.zero    a1")
w("    mb.arm    s4, b0, #0, #1")
w("    m.mma.async a1, v32, v40, s4")
w("    mb.wait   s4")
A1 = [Amat[r][16 + c] for r in range(TILE) for c in range(K)]
C1 = mma_ref(A1, B0, [f2b(0.0)] * (TILE * TILE), TILE, TILE, K)
for r in (0, 11):
    w(f"    .li       s5, #{r}")
    w("    a.vread   v1, a1, s5")
    for c in (0, 15):
        w(f"    .assert_lane v1, #{c}, #0x{C1[r*TILE+c]:08x}, #{nid()}")
w("")

# ---- phase 3: out-of-bounds padding ----------------------------------------
w("    // ---- a tile that runs off the edge: padding is the ABSENCE of an")
w("    //      access, not a masked one (ISA sec 9E.1 step 7) ----")
w(f"    .li       s6, #{DE_BASE}")
w("    td.load   d2, [s6]")
w("    v.movi    v48, #-1")
w("    w.def     w2, #48, #8")
w("    mb.arm    s3, b0, #0, #1")
w("    .li       s10, #0")
w("    .li       s11, #24            // only 8 of 16 columns exist")
w("    t.ld.async.h w2, d2, s10, s3")
w("    mb.wait   s3")
w("    // row 0: columns 24..31 are real, 32..39 are zero-filled")
PADROW = [Amat[0][24 + c] if (24 + c) < LDA else 0 for c in range(TILE)]
w("    v.mov     v2, v48")
for lane, (lo, hi) in enumerate(zip(PADROW[0::2], PADROW[1::2])):
    if lane in (0, 3, 4, 7):
        w(f"    .assert_lane v48, #{lane}, #0x{(hi << 16) | lo:08x}, #{nid()}")
w("")

w("    exit")
w("")

# ---- data ------------------------------------------------------------------
def emit_words(addr, words, label):
    w(f".org 0x{addr:x}")
    w(f"{label}:")
    for k in range(0, len(words), 4):
        w("    .dword " + ", ".join(f"0x{v:016x}" for v in words[k:k+4]))


def pack_rows(mat, ld):
    flat = [mat[r][c] for r in range(len(mat)) for c in range(ld)]
    return [sum(flat[i*4 + j] << (16*j) for j in range(4))
            for i in range(len(flat)//4)]


emit_words(A_BASE, pack_rows(Amat, LDA), "a_mat")
emit_words(B_BASE, pack_rows(Bmat, LDB), "b_mat")
emit_words(DA_BASE, tensormap(A_BASE, TILE, LDA, LDA*2, 2, TILE, K), "desc_a")
emit_words(DB_BASE, tensormap(B_BASE, K, LDB, LDB*2, 2, K, TILE), "desc_b")
emit_words(DE_BASE, tensormap(A_BASE, TILE, LDA, LDA*2, 2, TILE, K), "desc_e")

path = os.path.join(HERE, 't12_tensor.s')
with open(path, 'w') as fh:
    fh.write("\n".join(out) + "\n")
print(f"{tid[0]} checks -> {path}")
