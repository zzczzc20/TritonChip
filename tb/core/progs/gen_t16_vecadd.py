#!/usr/bin/env python3
"""
Generate tb/core/progs/t16_vecadd.s -- the shape a Triton vector_add lowers to.

compiler_overview.md sec 15 C1 requires the first real Triton->RTL closure to
cover vector add, masked elementwise and simple control flow, and to run the
compiler's output with no hand-added barrier and no edited assembly.

Before asking a compiler to produce that, the hardware has to be able to run
it. sec 11.1 says the bring-up path exists partly so compiler bugs and machine
encoding bugs can be told apart by comparing against hand-written assembly --
so this is that hand-written assembly, matching:

    @triton.jit
    def add_kernel(x, y, out, n, BLOCK: tl.constexpr):
        pid  = tl.program_id(0)
        offs = pid * BLOCK + tl.arange(0, BLOCK)
        mask = offs < n
        a = tl.load(x + offs, mask=mask, other=0.0)
        b = tl.load(y + offs, mask=mask, other=0.0)
        tl.store(out + offs, a + b, mask=mask)

The interesting part is the tail. n is deliberately not a multiple of BLOCK, so
the last program has a partial mask: lanes past n must not be loaded, must not
be stored, and -- because `other=0.0` is a value and not an absence -- must
read as zero rather than as whatever the register happened to hold. sec 12
names that explicitly: masked load's `other=` needs an explicit passthrough or
select, never a reliance on a stale register.
"""
import os
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..', '..'))
sys.path.insert(0, os.path.join(ROOT, 'tools', 'model'))
from fp32 import f2b  # noqa: E402

BLOCK = 16          # equals VLEN: one vector register per program
N = 40              # 2 full programs + an 8-lane tail
NUM_PROGRAMS = (N + BLOCK - 1) // BLOCK      # 3

X_BASE = 0x4000
Y_BASE = 0x4400
O_BASE = 0x4800


def xval(i):
    return float(i) * 0.5


def yval(i):
    return float(i) * 0.25 + 1.0


out = []
w = out.append

w("// t16_vecadd -- generated by gen_t16_vecadd.py; do not edit by hand.")
w("//")
w("// The instruction sequence a Triton vector_add must lower to, written by")
w(f"// hand first so the compiler has something to be compared against.")
w(f"// n = {N}, BLOCK = {BLOCK}: {NUM_PROGRAMS} programs, the last one masked.")
w("//")
w("// Role 0 runs every program id in a loop, because this bench launches one")
w("// context rather than a grid. The body is what matters.")
w(".org 0")
w("start:")
w(f"    .li       s1, #{N}                  // n")
w(f"    .li       s2, #{X_BASE}             // x")
w(f"    .li       s3, #{Y_BASE}             // y")
w(f"    .li       s4, #{O_BASE}             // out")
w("    .li       s5, #0                     // pid")
w("")
w("loop:")
w("    // offs = pid * BLOCK + arange(0, BLOCK)")
w(f"    .li       s6, #{BLOCK}")
w("    s.mul     s7, s5, s6                 // pid * BLOCK")
w("    v.iota    v1                         // arange(0, BLOCK)")
w("    v.splat   v2, s7")
w("    v.add     v3, v1, v2                 // offs")
w("")
w("    // mask = offs < n")
w("    v.splat   v4, s1")
w("    v.cmp.lt  p1, v3, v4")
w("")
w("    // The offsets are contiguous, so a plain vector load reaches them:")
w("    // ISA sec 9.1 gives lane i the address base + i*sz. No gather is")
w("    // needed, and emitting one would cost per-lane addressing for nothing.")
w("    s.shli    s8, s7, #2                 // byte offset = pid*BLOCK*4")
w("    s.add     s9, s2, s8                 // &x[pid*BLOCK]")
w("    s.add     s10, s3, s8                // &y[pid*BLOCK]")
w("    s.add     s11, s4, s8                // &out[pid*BLOCK]")
w("")
w("    // other=0.0 is a value, not an absence (sec 12). The masked-off lanes")
w("    // keep what the register already held, so it has to be set first.")
w("    v.movi    v5, #0")
w("    v.movi    v6, #0")
w("    @p1 v.ld.w v5, [s9, #0]")
w("    @p1 v.ld.w v6, [s10, #0]")
w("")
w("    vf.add    v7, v5, v6")
w("    @p1 v.st.w [s11, #0], v7")
w("")
w("    s.addi    s5, s5, #1")
w(f"    .li       s12, #{NUM_PROGRAMS}")
w("    s.cmp.lt  s13, s5, s12")
w("    br.nz     s13, loop")
w("")
w("    // ---- check every element, including the masked tail ----")

# Verify results. Masked-off lanes of the last program must be untouched in
# memory: the store is predicated, so out[] past n keeps its initial value.
n = 1
w(f"    .li       s20, #{O_BASE}")
for i in range(0, N):
    expect = f2b(xval(i) + yval(i))
    w(f"    s.ld.w    s21, [s20, #{i * 4}]")
    w(f"    .assert_eq s21, #{expect:#010x}, #{n}")
    n += 1

w("")
w("    // Lanes past n were masked off. A predicated store must not write")
w("    // them, so the sentinel below has to survive untouched -- this is the")
w("    // half of masking that a passing arithmetic check would not catch.")
for i in range(N, NUM_PROGRAMS * BLOCK):
    w(f"    s.ld.w    s21, [s20, #{i * 4}]")
    w(f"    .assert_eq s21, #0xdeadbeef, #{n}")
    n += 1

w("")
w("    exit")
w("")


def emit_words(addr, words, label, comment=None):
    w(f".org {addr:#x}")
    if comment:
        w(f"// {comment}")
    w(f"{label}:")
    for word in words:
        w(f"    .dword 0x{word & ((1 << 64) - 1):016x}")
    w("")


def pack32(values):
    """Two 32-bit values per 64-bit word, little-endian."""
    words = []
    for k in range(0, len(values), 2):
        lo = values[k]
        hi = values[k + 1] if k + 1 < len(values) else 0
        words.append((hi << 32) | lo)
    return words


padded = NUM_PROGRAMS * BLOCK
emit_words(X_BASE, pack32([f2b(xval(i)) for i in range(padded)]), "xs",
           "x[], padded to a whole number of blocks")
emit_words(Y_BASE, pack32([f2b(yval(i)) for i in range(padded)]), "ys", "y[]")
emit_words(O_BASE, pack32([0xdeadbeef] * padded), "os",
           "out[], pre-filled with a sentinel the masked tail must preserve")

path = os.path.join(HERE, 't16_vecadd.s')
open(path, 'w').write('\n'.join(out) + '\n')
print(f"wrote {path}: n={N}, BLOCK={BLOCK}, {NUM_PROGRAMS} programs, "
      f"{padded - N} masked tail lanes")
