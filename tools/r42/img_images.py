#!/usr/bin/env python3
"""R42-img: image parameter files of the arms of the combined-image study.

    img_images.py [--out-sim DIR] [--out-hbm DIR]

The R41 run-3 image (evidence/r41/hbm_bw/g4/run2/image.tcl, link 3, RTL 8d237223) is the base. Each arm adds image
parameters of the three R42 RTL items to it:
  TENSOR_LINE_HALF 1  half-line rows on the line-wide transfer engine (R42 lineelig, profile core-r42-line32)
  MTX_PIPE 1          overlapped matrix sequencer (R42 mtx, profile core-r42)
  MAC_F32 1           m.mma.f32.async, binary32 fragments (R42 fp32, profile core-r42-fp32)
Two forms are written: `hbm` (the run-3 parameter set as linked, HBM_STRIPED 1: the kernel synthesis and the link) and
`sim` (without HBM_STRIPED, the geometry of the three-core RTL stand-in, tools/r42/images/r41_run2_sim.tcl).
"""
import argparse
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RUN3 = ROOT / 'evidence/r41/hbm_bw/g4/run2/image.tcl'
RUN3_FALLBACK = ROOT / 'tools/r42/images/r41_run2_sim.tcl'
ARMS = {                       # name -> parameters added to the run-3 image
    'base': {},
    'l': {'TENSOR_LINE_HALF': 1},
    'm': {'MTX_PIPE': 1},
    'f': {'MAC_F32': 1},
    'lm': {'TENSOR_LINE_HALF': 1, 'MTX_PIPE': 1},
    'lf': {'TENSOR_LINE_HALF': 1, 'MAC_F32': 1},
    'mf': {'MTX_PIPE': 1, 'MAC_F32': 1},
    'lmf': {'TENSOR_LINE_HALF': 1, 'MTX_PIPE': 1, 'MAC_F32': 1},
}


def write(src_text, extra, dest, note, strip=()):
    m = re.search(r'(set TNCA_IMAGE_PARAMS \[dict create )([^\]]*)(\])', src_text)
    words = m.group(2).split()
    pairs = [(words[i], words[i + 1]) for i in range(0, len(words), 2)]
    pairs = [p for p in pairs if p[0] not in strip]
    for k, v in extra.items():
        assert all(k != p[0] for p in pairs), k
        pairs.append((k, str(v)))
    line = m.group(1) + ' '.join(f'{k} {v}' for k, v in pairs) + m.group(3)
    body = src_text[:m.start()] + line + src_text[m.end():]
    Path(dest).write_text(note + body)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--out-sim', default=str(ROOT / 'tools/r42/images'))
    ap.add_argument('--out-hbm', default=str(ROOT / 'evidence/r42/img/images'))
    a = ap.parse_args()
    if RUN3.exists():
        hbm = RUN3.read_text()
    else:                                   # a sparse checkout without evidence/
        import subprocess
        hbm = subprocess.check_output(['git', '-C', str(ROOT), 'show',
                                       'origin/R42:evidence/r41/hbm_bw/g4/run2/image.tcl']).decode()
    Path(a.out_sim).mkdir(parents=True, exist_ok=True)
    Path(a.out_hbm).mkdir(parents=True, exist_ok=True)
    sim = RUN3_FALLBACK.read_text()
    sim = '\n'.join(l for l in sim.splitlines() if not l.startswith('# copy of'))
    for name, extra in ARMS.items():
        what = ', '.join(f'{k} {v}' for k, v in extra.items()) or 'none (the run-3 parameter set)'
        note = (f'# R42-img arm {name}: R41 run-3 image plus {what}. Generated by tools/r42/img_images.py; not linked.\n')
        write(sim, extra, Path(a.out_sim) / f'r42img_{name}_sim.tcl', note)
        if hbm is not None:
            write(hbm, extra, Path(a.out_hbm) / f'image_{name}.tcl', note)


if __name__ == '__main__':
    main()
