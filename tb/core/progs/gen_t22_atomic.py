#!/usr/bin/env python3
"""
Generate tb/core/progs/t22_atomic.s -- ISA sec 9.2 on one core.

Every atomic operation, at both widths, checked twice: the value it RETURNS
(the old one) and the value it LEAVES (the new one). Checking only the return
would pass an implementation that computed correctly and never wrote; checking
only memory would pass one that wrote correctly and returned the new value.
Both together are the contract.

The 4-byte cases are run at both halves of an 8-byte word, with the other half
pre-filled with a sentinel that is asserted unchanged afterwards. That is the
part a byte-enable mistake breaks and nothing else notices: an atomic that
widened itself to 8 bytes would produce the right answer in the half being
tested and quietly destroy its neighbour.

Multi-core atomicity is a different property and lives in the four-tile bench;
this one is about the arithmetic, the widths and the fault.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))

BASE = 0x4000          # the doubleword under test
SENT_HI = 0x5a5a5a5a   # the untouched half of a 4-byte case
M64 = (1 << 64) - 1
M32 = (1 << 32) - 1


def s64(v):
    v &= M64
    return v - (1 << 64) if v >> 63 else v


def s32(v):
    v &= M32
    return v - (1 << 32) if v >> 31 else v


OPS = {
    'add':   lambda o, a, w: (o + a),
    'and':   lambda o, a, w: (o & a),
    'or':    lambda o, a, w: (o | a),
    'xor':   lambda o, a, w: (o ^ a),
    'xchg':  lambda o, a, w: a,
    'min.s': lambda o, a, w: (o if (s32(o) < s32(a) if w else s64(o) < s64(a)) else a),
    'max.s': lambda o, a, w: (a if (s32(o) < s32(a) if w else s64(o) < s64(a)) else o),
    'min.u': lambda o, a, w: (o if o < a else a),
    'max.u': lambda o, a, w: (a if o < a else o),
}

# (old, arg) pairs that make the signed and unsigned answers differ, so a
# min.u that quietly used a signed compare fails.
PAIRS64 = [(100, 7), (0xffff_ffff_ffff_fff0, 5), (3, 0xffff_ffff_ffff_ffff),
           (0x0123_4567_89ab_cdef, 0xfedc_ba98_7654_3210)]
PAIRS32 = [(100, 7), (0xffff_fff0, 5), (3, 0xffff_ffff), (0x1234_5678, 0x8765_4321)]

out = []
w = out.append
tid = [0]


def nid():
    tid[0] += 1
    return tid[0]


def li(reg, val):
    w(f"    .li      {reg}, #0x{val & M64:x}")


w("// t22_atomic -- generated by gen_t22_atomic.py; do not edit by hand.")
w("// ISA sec 9.2. Every operation checked for what it returns AND what it")
w("// leaves in memory; 4-byte cases checked for what they leave alone.")
w(".org 0")
w("start:")
li('s1', BASE)
w("")

for name, fn in OPS.items():
    for old, arg in PAIRS64:
        new = fn(old, arg, False) & M64
        w(f"    // atom.{name}.d  old=0x{old:x} arg=0x{arg:x}")
        li('s2', old)
        w("    s.st.d   [s1, #0], s2")
        li('s3', arg)
        w(f"    atom.{name}.d s4, [s1], s3")
        w(f"    .assert_eq s4, #0x{old:x}, #{nid()}")
        w("    s.ld.d   s6, [s1, #0]")
        w(f"    .assert_eq s6, #0x{new:x}, #{nid()}")
    w("")

# ---- 4-byte, in both halves, with the neighbour checked --------------------
for half, off in (('low', 0), ('high', 4)):
    for name, fn in OPS.items():
        old, arg = PAIRS32[1] if name.endswith('.u') or name.endswith('.s') else PAIRS32[0]
        new = fn(old, arg, True) & M32
        word_old = (SENT_HI << 32) | old if off == 0 else (old << 32) | SENT_HI
        word_new = (SENT_HI << 32) | new if off == 0 else (new << 32) | SENT_HI
        w(f"    // atom.{name}.w in the {half} half; the other half must not move")
        li('s2', word_old)
        w("    s.st.d   [s1, #0], s2")
        li('s7', BASE + off)
        li('s3', arg)
        w(f"    atom.{name}.w s4, [s7], s3")
        w(f"    .assert_eq s4, #0x{old:x}, #{nid()}")
        w("    s.ld.d   s6, [s1, #0]")
        w(f"    .assert_eq s6, #0x{word_new:x}, #{nid()}")
    w("")

# ---- compare and swap ------------------------------------------------------
w("    // atom.cas: swaps only on a match, and returns the old value either way")
for old, cmp_, swap, expect_mem in ((7, 7, 99, 99), (7, 8, 99, 7)):
    li('s2', old)
    w("    s.st.d   [s1, #0], s2")
    li('s3', cmp_)
    li('s8', swap)
    w("    atom.cas.d s4, [s1], s3, s8")
    w(f"    .assert_eq s4, #0x{old:x}, #{nid()}")
    w("    s.ld.d   s6, [s1, #0]")
    w(f"    .assert_eq s6, #0x{expect_mem:x}, #{nid()}")
w("")

# ---- atomic load and store -------------------------------------------------
w("    // atom.ld returns the word and leaves it; atom.st replaces it")
li('s2', 0x0bad_c0de_dead_beef)
w("    s.st.d   [s1, #0], s2")
w("    atom.ld.d.acquire s4, [s1]")
w(f"    .assert_eq s4, #0x0badc0dedeadbeef, #{nid()}")
w("    s.ld.d   s6, [s1, #0]")
w(f"    .assert_eq s6, #0x0badc0dedeadbeef, #{nid()}   // atom.ld is not a write")
li('s3', 0x1234)
w("    atom.st.d.release [s1], s3")
w("    s.ld.d   s6, [s1, #0]")
w(f"    .assert_eq s6, #0x1234, #{nid()}")
w("")

# ---- fence -----------------------------------------------------------------
w("    // A fence between a store and an atomic changes no value, which is the")
w("    // point: it must be a no-op on the data and an ordering point on the")
w("    // machine. What is checked here is that it retires at all.")
li('s2', 5)
w("    s.st.d   [s1, #0], s2")
w("    fence.release.device")
li('s3', 3)
w("    atom.add.d.acquire.device s4, [s1], s3")
w(f"    .assert_eq s4, #5, #{nid()}")
w("    fence.acq_rel.device")
w("    s.ld.d   s6, [s1, #0]")
w(f"    .assert_eq s6, #8, #{nid()}")
w("")
w("    exit")
w("")

path = os.path.join(HERE, 't22_atomic.s')
with open(path, 'w') as fh:
    fh.write("\n".join(out) + "\n")
print(f"{len(out)} lines, {tid[0]} checks -> {path}")
