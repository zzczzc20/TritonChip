#!/usr/bin/env python3
"""
Generate tb/core/progs/t41_mmadp.s -- m.mma.dp.async end to end through the
core (ISA sec 9C.4, approved 2026-10-29), for a core built with MAC_DP=1.

Every expectation comes from tools/model/fdp.py's mma_dp_ref, the exact oracle:
the products of a group of G consecutive k summed exactly, one RO_48, one RNE
into C, groups in increasing k. G = 4 for E4M3 x E4M3 and 2 for every other
pair of formats, so a wrong group size, a wrong B layout or a wrong A element
selection produces a wrong C, not a rounding difference.
"""
import os
import random
import sys
from fractions import Fraction

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..', '..'))
sys.path.insert(0, os.path.join(ROOT, 'tools', 'model'))
import fdp                                            # noqa: E402
from fp32 import f2b                                  # noqa: E402

M = N = 16
WIDTH = {'f16': 2, 'bf16': 2, 'e5m2': 1, 'e4m3': 1}
SFX = {'f16': 'f16', 'bf16': 'bf16', 'e5m2': 'e5m2', 'e4m3': 'e4m3'}
# (A format, B format, K)
COMBOS = [
    ('e4m3', 'e4m3', 16), ('e4m3', 'e4m3', 32), ('e4m3', 'e4m3', 64),
    ('f16', 'f16', 16), ('f16', 'f16', 32), ('bf16', 'bf16', 16), ('bf16', 'bf16', 32),
    ('e5m2', 'e5m2', 16), ('e5m2', 'e5m2', 32),
    ('e4m3', 'f16', 16), ('f16', 'e4m3', 32), ('e5m2', 'e4m3', 16),
    ('e4m3', 'e5m2', 32), ('bf16', 'e5m2', 16), ('f16', 'bf16', 16),
]
rng = random.Random(20261029)


def rnd_elem(fmt):
    """A finite element of moderate magnitude, with some zeros."""
    w = 8 * WIDTH[fmt]
    while True:
        b = rng.getrandbits(w)
        k, s, v = fdp.element(fmt, b)
        if k == 'zero':
            if rng.random() < 0.3:
                return b
            continue
        if k != 'fin':
            continue
        if Fraction(1, 64) <= abs(v) <= 64:
            return b


out = []
w = out.append
tid = [0]


def nid():
    tid[0] += 1
    return tid[0]


w("// t41_mmadp -- generated by gen_t41_mmadp.py; do not edit by hand.")
w("// m.mma.dp.async (ISA sec 9C.4) against tools/model/fdp.py mma_dp_ref.")
w(".org 0")
w("start:")
w("    mb.init   b1")
data = []
base = 0x8000
for idx, (fa, fb, K) in enumerate(COMBOS):
    ba, bb = WIDTH[fa], WIDTH[fb]
    a = [rnd_elem(fa) for _ in range(M * K)]
    b = [rnd_elem(fb) for _ in range(K * N)]
    c0 = [f2b(0.0)] * (M * N)
    c = fdp.mma_dp_ref(fa, fb, a, b, c0, M, N, K)
    a_regs = (M * K * ba) // 64
    b_regs = (K * N * bb) // 64
    a_addr = base
    b_addr = base + M * K * ba
    base = (b_addr + K * N * bb + 0x3ff) & ~0x3ff
    data.append((f"a{idx}", a_addr, a, ba))
    data.append((f"b{idx}", b_addr, b, bb))
    kname = {16: 'k16', 32: 'k32', 64: 'k64'}[K]
    sfx = '.' + kname + '.' + SFX[fa] + ('' if fa == fb else '.' + SFX[fb])
    w(f"    // ---- {idx}: A {fa}, B {fb}, K {K} (G = {4 if fa == fb == 'e4m3' else 2}) ----")
    w(f"    .li       s10, #{a_addr}")
    for i in range(a_regs):
        w(f"    v.ld.w    v{8+i}, [s10, #{i*64}]")
    w(f"    .li       s11, #{b_addr}")
    for i in range(b_regs):
        w(f"    v.ld.w    v{32+i}, [s11, #{i*64}]")
    w("    m.zero    a3")
    w("    mb.arm    s12, b1, #0, #1")
    w(f"    m.mma.dp.async{sfx} a3, v8, v32, s12")
    w("    mb.wait   s12")
    for r in (0, 7, 15):
        w(f"    .li       s13, #{r}")
        w("    a.vread   v7, a3, s13")
        for ln in (0, 3, 8, 15):
            w(f"    .assert_lane v7, #{ln}, #0x{c[r*N+ln]:08x}, #{nid()}")
    if idx in (0, 3):
        # a second command accumulates onto the same C
        c2 = fdp.mma_dp_ref(fa, fb, a, b, c, M, N, K)
        w("    mb.arm    s12, b1, #0, #1")
        w(f"    m.mma.dp.async{sfx} a3, v8, v32, s12")
        w("    mb.wait   s12")
        for r in (0, 15):
            w(f"    .li       s13, #{r}")
            w("    a.vread   v7, a3, s13")
            for ln in (0, 15):
                w(f"    .assert_lane v7, #{ln}, #0x{c2[r*N+ln]:08x}, #{nid()}")
    w("")
w("    exit")
w("")


def emit(label, addr, vals, nb):
    raw = b''.join(int(v).to_bytes(nb, 'little') for v in vals)
    words = [int.from_bytes(raw[i:i+4], 'little') for i in range(0, len(raw), 4)]
    w(f".org 0x{addr:x}")
    w(f"{label}:")
    for k in range(0, len(words), 8):
        w("    .word " + ", ".join(f"0x{v:08x}" for v in words[k:k+8]))


for label, addr, vals, nb in data:
    emit(label, addr, vals, nb)

path = os.path.join(HERE, 't41_mmadp.s')
with open(path, 'w') as fh:
    fh.write("\n".join(out) + "\n")
print(f"{tid[0]} checks -> {path} (data to 0x{base:x})")
