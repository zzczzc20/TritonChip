#!/usr/bin/env python3
"""
Generate tb/core/progs/t20_sfu.s.

ISA sec 8.8 specifies the SFU by an error bound, so the checks in this program
are *bounds* checks, expressed in the ISA itself: the result is compared
against a lower and an upper vector with vf.cmp and the ballot is required to
be all ones. Writing an exact expected lane would pin the test to this
implementation's rounding rather than to the contract.

The bounds come from tools/model/gen_sfu_vectors.py -- the same 60-digit
decimal oracle that tb_sfu_xls uses -- so the unit test and the core test
cannot disagree about what the contract is.

Values that sec 8.8 *does* specify exactly (the infinities, the signed zeros,
and the subnormal inputs it flushes) are checked with .assert_lane instead,
because there the ISA gives a result and not a band.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..', '..'))
sys.path.insert(0, os.path.join(ROOT, 'tools', 'model'))
from gen_sfu_vectors import bounds, f2b            # noqa: E402

VLEN = 16
PINF, NINF = 0x7f80_0000, 0xff80_0000
PZERO, NZERO = 0x0000_0000, 0x8000_0000
ONE = 0x3f80_0000

# Ordinary arguments, chosen to keep every result finite and normal so the
# band check is a band check and not an accident of saturation.
POS = [1.0, 2.0, 0.5, 3.0, 1.5, 0.75, 10.0, 100.0,
       0.125, 1024.0, 1e-6, 7.0, 1.25, 63.0, 255.0, 0.3]
EXPO = [-3.0, -1.0, -0.5, 0.25, 0.5, 1.0, 2.0, 3.5,
        10.0, -10.0, 7.25, -7.25, 0.1, -0.1, 20.0, -20.0]

# log2(1) is exactly zero, which is a specified result rather than a bounded
# one -- it is checked by .assert_lane further down, not by a band.
LOGA = [1.1 if v == 1.0 else v for v in POS]

ARGS = {'exp2': EXPO, 'log2': LOGA, 'rcp': POS, 'rsqrt': POS}
MNEM = {'exp2': 'v.exp2.approx', 'log2': 'v.log2.approx',
        'rcp': 'v.rcp.approx', 'rsqrt': 'v.rsqrt.approx'}

out = []
w = out.append
tid = [0]


def nid():
    tid[0] += 1
    return tid[0]


def band(op):
    xs, los, his = [], [], []
    for v in ARGS[op]:
        b = f2b(v)
        lo, hi = bounds(op, b)
        if lo == 'special':
            raise SystemExit(f"{op}({v}) is a special value; pick another argument")
        xs.append(b)
        los.append(lo & 0xffffffff)
        his.append(hi & 0xffffffff)
    return xs, los, his


w("// t20_sfu -- generated by gen_t20_sfu.py; do not edit by hand.")
w("// ISA sec 8.8. Bounds from tools/model/gen_sfu_vectors.py (60-digit decimal).")
w(".org 0")
w("start:")

data = {}
for op in ('exp2', 'log2', 'rcp', 'rsqrt'):
    xs, los, his = band(op)
    data[f"x_{op}"] = xs
    data[f"lo_{op}"] = los
    data[f"hi_{op}"] = his
    w(f"    // ---- {MNEM[op]} : every lane inside the 2^-22 band ----")
    w(f"    .li      s1, #x_{op}")
    w(f"    .li      s2, #lo_{op}")
    w(f"    .li      s3, #hi_{op}")
    w("    v.ld.w   v1, [s1, #0]")
    w("    v.ld.w   v2, [s2, #0]")
    w("    v.ld.w   v3, [s3, #0]")
    w(f"    {MNEM[op]} v4, v1")
    w("    vf.cmp.ge p1, v4, v2")
    w("    p.ballot s4, p1")
    w(f"    .assert_eq s4, #0xffff, #{nid()}")
    w("    vf.cmp.le p1, v4, v3")
    w("    p.ballot s4, p1")
    w(f"    .assert_eq s4, #0xffff, #{nid()}")
    w("")

# ---- the results sec 8.8 gives exactly -------------------------------------
SPEC_X = [PZERO, NZERO, PINF, NINF, 0x0000_0001, 0x8000_0001,
          f2b(1.0), f2b(4.0)] + [f2b(1.0)] * 8
data["x_spec"] = SPEC_X

w("    // ---- sec 8.8 special values: specified exactly, so checked exactly --")
w("    .li      s1, #x_spec")
w("    v.ld.w   v1, [s1, #0]")

w("    v.rcp.approx v4, v1")
for lane, want, why in [
        (0, PINF, "rcp(+0) = +inf"),
        (1, NINF, "rcp(-0) = -inf"),
        (2, PZERO, "rcp(+inf) = +0"),
        (3, NZERO, "rcp(-inf) = -0"),
        (4, PINF, "subnormal flushed to +0 first"),
        (5, NINF, "subnormal flushed to -0 first"),
        (6, ONE, "rcp(1) = 1"),
        (7, f2b(0.25), "rcp(4) = 0.25")]:
    w(f"    .assert_lane v4, #{lane}, #0x{want:08x}, #{nid()}   // {why}")

w("    v.exp2.approx v4, v1")
for lane, want, why in [
        (0, ONE, "exp2(+0) = 1"),
        (1, ONE, "exp2(-0) = 1"),
        (2, PINF, "exp2(+inf) = +inf"),
        (3, PZERO, "exp2(-inf) = +0"),
        (4, ONE, "subnormal flushed to zero first"),
        (5, ONE, "subnormal flushed to zero first")]:
    w(f"    .assert_lane v4, #{lane}, #0x{want:08x}, #{nid()}   // {why}")

w("    v.log2.approx v4, v1")
for lane, want, why in [
        (0, NINF, "log2(+0) = -inf"),
        (1, NINF, "log2(-0) = -inf"),
        (2, PINF, "log2(+inf) = +inf"),
        (4, NINF, "subnormal flushed to zero first"),
        (6, PZERO, "log2(1) = +0"),
        (7, f2b(2.0), "log2(4) = 2")]:
    w(f"    .assert_lane v4, #{lane}, #0x{want:08x}, #{nid()}   // {why}")

w("    v.rsqrt.approx v4, v1")
for lane, want, why in [
        (0, PINF, "rsqrt(+0) = +inf"),
        (2, PZERO, "rsqrt(+inf) = +0"),
        (6, ONE, "rsqrt(1) = 1"),
        (7, f2b(0.5), "rsqrt(4) = 0.5")]:
    w(f"    .assert_lane v4, #{lane}, #0x{want:08x}, #{nid()}   // {why}")
w("")

# ---- predication -----------------------------------------------------------
# The SFU retires through the multicycle completion port, which carries its own
# copy of the lane enable. If that copy were missing the masked lanes would be
# overwritten, and the first half of this check is what would catch it.
w("    // ---- a masked SFU write leaves the inactive lanes alone -------------")
w("    .li      s1, #x_rcp")
w("    .li      s2, #lo_rcp")
w("    .li      s3, #hi_rcp")
w("    v.ld.w   v1, [s1, #0]")
w("    v.ld.w   v2, [s2, #0]")
w("    v.ld.w   v3, [s3, #0]")
w("    .li      s5, #0x0f0f")
w("    p.frombits p5, s5")
w("    v.movi   v6, #7")
w("    @p5 v.rcp.approx v6, v1")
for lane in (4, 5, 12, 13):
    w(f"    .assert_lane v6, #{lane}, #7, #{nid()}      // masked off, untouched")
w("    vf.cmp.ge p1, v6, v2")
w("    p.ballot s6, p1")
w("    s.and    s6, s6, s5")
w(f"    .assert_eq s6, #0x0f0f, #{nid()}       // the written lanes are in band")
w("    vf.cmp.le p1, v6, v3")
w("    p.ballot s6, p1")
w("    s.and    s6, s6, s5")
w(f"    .assert_eq s6, #0x0f0f, #{nid()}")
w("")

# ---- back to back ----------------------------------------------------------
# Two SFU instructions in a row, and an ordinary FP instruction immediately
# after one: the completion port is shared with the FMA array's scheduled
# writeback, and issuing into a busy unit is exactly what red_busy_next exists
# to prevent.
w("    // ---- back to back, and an FP op straight after ----------------------")
w("    .li      s1, #x_rcp")
w("    v.ld.w   v1, [s1, #0]")
w("    v.rcp.approx v4, v1")
w("    v.rcp.approx v5, v4")
w("    vf.add   v7, v5, v5")
w("    vf.mul   v8, v5, v5")
w("    // rcp(rcp(x)) is x to within two roundings; 2*that is within four.")
w("    .li      s2, #lo_rt")
w("    .li      s3, #hi_rt")
w("    v.ld.w   v2, [s2, #0]")
w("    v.ld.w   v3, [s3, #0]")
w("    vf.cmp.ge p1, v7, v2")
w("    p.ballot s4, p1")
w(f"    .assert_eq s4, #0xffff, #{nid()}")
w("    vf.cmp.le p1, v7, v3")
w("    p.ballot s4, p1")
w(f"    .assert_eq s4, #0xffff, #{nid()}")
w("")
w("    exit")
w("")

# 2*rcp(rcp(x)): four 2^-22 roundings plus the doubling, which is exact.
TOL4 = 1 + 5 * 2 ** -22
data["lo_rt"] = [f2b(2.0 * v / TOL4) for v in POS]
data["hi_rt"] = [f2b(2.0 * v * TOL4) for v in POS]


def words(label, vals):
    w(f"{label}:")
    for k in range(0, len(vals), 8):
        w("    .word " + ", ".join(f"0x{v:08x}" for v in vals[k:k + 8]))


w(".org 0x8000")
for label, vals in data.items():
    words(label, vals)

path = os.path.join(HERE, 't20_sfu.s')
with open(path, 'w') as fh:
    fh.write("\n".join(out) + "\n")
print(f"{len(out)} lines, {tid[0]} checks -> {path}")
