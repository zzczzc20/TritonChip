#!/usr/bin/env python3
"""
Generate tb/core/progs/t25_mmasf.s -- m.mma.async's two completion events.

arch overview sec 13.1 asks for three completions to be distinguishable, and
names confusing them as a known hazard. Until now `m.mma.async` signalled one:
the result landing in the accumulator. A double-buffered producer that wants to
refill the A and B fragments needs a different one -- the fragments having been
read for the last time -- and had to use the result event as a conservative
proxy, which serialises a pipeline that did not need to be.

ISA sec 9C `mod[4]` adds it, on the barrier whose token is in Sc+1.

THE TEST IS THE OVERWRITE.

The program waits on the source-free barrier and then destroys both fragments,
filling them with a value that would give a completely different product. Only
then does it wait on the result barrier and check C. If the two events were the
same event, or if source-free fired too early, the overwrite would land inside
the MAC sweep and the product would be wrong -- which is exactly what this
asserts is not the case.

Expectations come from tools/model/fp32.py's mma_ref, the same oracle
t11_matrix uses.
"""
import os
import random
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..', '..'))
sys.path.insert(0, os.path.join(ROOT, 'tools', 'model'))
from fp32 import f32_to_f16_bits, mma_ref, f2b   # noqa: E402

M = N = K = 16
A_BASE = 0x2000
B_BASE = 0x2400

rng = random.Random(20260920)
A = [f32_to_f16_bits(rng.randint(-8, 8) / 2.0) for _ in range(M * K)]
B = [f32_to_f16_bits(rng.randint(-8, 8) / 2.0) for _ in range(K * N)]
C = mma_ref(A, B, [f2b(0.0)] * (M * N), M, N, K)

out = []
w = out.append
tid = [0]


def nid():
    tid[0] += 1
    return tid[0]


w("// t25_mmasf -- generated by gen_t25_mmasf.py; do not edit by hand.")
w("// ISA sec 9C mod[4]: the source-free event, proved by overwriting the")
w("// fragments the moment it fires and then checking the product anyway.")
w(".org 0")
w("start:")
w(f"    .li       s1, #{A_BASE}")
for i in range(8):
    w(f"    v.ld.w    v{32+i}, [s1, #{i*64}]")
w(f"    .li       s2, #{B_BASE}")
for i in range(8):
    w(f"    v.ld.w    v{40+i}, [s2, #{i*64}]")
w("")
w("    m.zero    a1")
w("    mb.init   b0")
w("    mb.init   b1")
w("    // b0 counts the result; b1 counts the fragments going free. Two")
w("    // barriers, because two events that share one cannot be waited on")
w("    // separately -- which is the whole point of having two.")
w("    mb.arm    s10, b0, #0, #1          // s10: result token")
w("    mb.arm    s11, b1, #0, #1          // s11 = s10+1: source-free token")
w("    m.mma.async.sf a1, v32, v40, s10")
w("")
w("    mb.wait   s11                      // fragments are free")
w("    // Destroy both of them. If source-free meant anything less than 'the")
w("    // engine will not read these again', C is now wrong.")
w("    .li       s3, #0x7fc00000")
w("    v.splat   v20, s3")
for i in range(8):
    w(f"    v.mov     v{32+i}, v20")
    w(f"    v.mov     v{40+i}, v20")
w("")
w("    mb.wait   s10                      // now the result")
CHECK = [(0, 0), (0, 15), (1, 3), (7, 8), (15, 15)]
for r, c in CHECK:
    w(f"    .li       s13, #{r}")
    w("    a.vread   v8, a1, s13")
    w(f"    .assert_lane v8, #{c}, #0x{C[r*N+c]:08x}, #{nid()}")
w("")
w("    // And the plain form still works: one event, the fragments held until")
w("    // the result is done. The same product, from the registers just")
w("    // refilled.")
w(f"    .li       s1, #{A_BASE}")
for i in range(8):
    w(f"    v.ld.w    v{32+i}, [s1, #{i*64}]")
w(f"    .li       s2, #{B_BASE}")
for i in range(8):
    w(f"    v.ld.w    v{40+i}, [s2, #{i*64}]")
w("    m.zero    a2")
w("    mb.arm    s10, b0, #0, #1")
w("    m.mma.async a2, v32, v40, s10")
w("    mb.wait   s10")
for r, c in CHECK[:2]:
    w(f"    .li       s13, #{r}")
    w("    a.vread   v8, a2, s13")
    w(f"    .assert_lane v8, #{c}, #0x{C[r*N+c]:08x}, #{nid()}")
w("")
w("    exit")
w("")


def emit_words(label, addr, words):
    w(f".org 0x{addr:x}")
    w(f"{label}:")
    for k in range(0, len(words), 8):
        w("    .word " + ", ".join(f"0x{v:08x}" for v in words[k:k+8]))


def pack(h):
    return [(h[2*i+1] << 16) | h[2*i] for i in range(len(h)//2)]


emit_words("a_frag", A_BASE, pack(A))
emit_words("b_frag", B_BASE, pack(B))

path = os.path.join(HERE, 't25_mmasf.s')
with open(path, 'w') as fh:
    fh.write("\n".join(out) + "\n")
print(f"{tid[0]} checks -> {path}")
