#!/usr/bin/env python3
"""Emit the SFU coefficient tables from the product's xls/tnca_sfu_tables.x.

The model's SFU is a literal port of xls/tnca_sfu.x (the source of
rtl/gen/tnca_sfu_*_xls.v); reading the same generated tables at build time
keeps the model and the RTL on one set of coefficients.
"""
import re
from pathlib import Path
import sys

text = Path(sys.argv[1]).read_text()
lines = ['#pragma once', '// GENERATED by generate_sfu.py from xls/tnca_sfu_tables.x -- do not edit.',
         '#include <cstdint>', 'namespace tnca_sfu_tables {']
for name, value in re.findall(r'pub const (\w+): u32 = u32:(\d+);', text):
    lines.append(f'constexpr std::uint32_t {name} = {value};')
tables = re.findall(r'pub const (\w+) = s32\[(\d+)\]:\[(.*?)\];', text, re.S)
if len(tables) != 15:
    raise SystemExit(f'expected 15 SFU tables, found {len(tables)}')
for name, size, body in tables:
    values = re.findall(r's32:(-?\d+)', body)
    if len(values) != int(size):
        raise SystemExit(f'{name}: {len(values)} values for s32[{size}]')
    lines.append(f'constexpr std::int32_t {name}[{size}] = {{' + ','.join(values) + '};')
lines.append('}')
Path(sys.argv[2]).write_text('\n'.join(lines) + '\n')
