#!/usr/bin/env python3
"""
Generate tb/core/progs/t19_waitgen0.s -- waiting on a generation that is
already complete must return, not oscillate.

Two predicates decide what an `mb.wait` does: one whether to sleep, one
whether to wake. They disagreed. The sleep test required the barrier to have
been armed at least once; the wake test did not. So a wait on generation 0 --
the quiescent state every barrier starts in (ISA sec 9A.7) -- slept, woke
immediately, re-executed the instruction, and slept again. A livelock, not a
hang: it burned every issue slot on squashes, so the failure looked like a
program running very fast and getting nowhere.

The `armed` term was wrong on its own terms too. It is only ever clear before
the first `mb.arm`, and generation 0 has trivially completed because nothing
was ever pending.

Three cases here: generation 0 of an untouched barrier, generation 0 after the
barrier has been used, and a late waiter on a generation that finished a while
ago -- which is the case the ">=" comparison exists for and which `armed`
would have broken as soon as a barrier were re-initialised.
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))

out = []
w = out.append
w("// t19_waitgen0 -- generated by gen_t19_waitgen0.py; do not edit by hand.")
w("//")
w("// mb.wait on an already-complete generation must return immediately. The")
w("// sleep and wake predicates have to agree, or the waiter oscillates.")
w(".org 0")
w("start:")
w("    // (1) generation 0 of a barrier nothing has armed. ISA sec 9A.7: every")
w("    //     barrier starts here, so this generation is complete already.")
w("    .li       s1, #0                   // token = {epoch 0, barrier 0}")
w("    mb.wait   s1")
w("    .li       s2, #1")
w("    .assert_eq s2, #1, #1              // reached at all")
w("")
w("    // (2) arm and complete generation 1, then wait on it again.")
w("    mb.arm    s3, b0, #1, #0")
w("    mb.arrive b0")
w("    mb.wait   s3")
w("    mb.wait   s3                       // second wait: already complete")
w("    .assert_eq s2, #1, #2")
w("")
w("    // (3) a late waiter on an older generation. The '>=' comparison is")
w("    //     there for exactly this, and it is what makes a token that has")
w("    //     been overtaken safe to wait on.")
w("    mb.arm    s4, b0, #1, #0")
w("    mb.arrive b0")
w("    mb.wait   s4")
w("    mb.wait   s3                       // generation 1, long since done")
w("    .assert_eq s2, #1, #3")
w("")
w("    // (4) generation 0 of a barrier that has since advanced.")
w("    .li       s5, #0")
w("    mb.wait   s5")
w("    .assert_eq s2, #1, #4")
w("")
w("    exit")
w("")

path = os.path.join(HERE, 't19_waitgen0.s')
open(path, 'w').write('\n'.join(out) + '\n')
print(f"wrote {path}")
