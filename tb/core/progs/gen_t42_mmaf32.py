#!/usr/bin/env python3
"""
Generate tb/core/progs/t42_mmaf32.s -- m.mma.f32.async end to end through the
core (ISA sec 9C.5), for a core built with MAC_F32=1.

Every expectation is the sequential binary32 FMA of ISA sec 9C.1 over
binary32 operands: tools/model/fp32.py mma_ref with the identity widening,
that is fma_ref(A[m][k], B[k][n], C) for k = 0..15 in order, one rounding a
step. This is the vector unit's vf.fma chain bit for bit, which is what the
compiler emitted for an fp32 tl.dot before the opcode existed.

The cases: random finite values over a wide exponent range (so the single
rounding and the order are observable), a second command accumulating onto
the same C, cancellation (a product that must not be rounded before the add),
subnormals, signed zeros, infinities and NaN, and a fragment at other
register bases with the source-free event.
"""
import os
import random
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..', '..'))
sys.path.insert(0, os.path.join(ROOT, 'tools', 'model'))
from fp32 import mma_ref                               # noqa: E402

M = N = K = 16
DATA = 0x10000          # the fragments' data, above the program
rng = random.Random(20261120)


def f2b(x):
    return struct.unpack('<I', struct.pack('<f', x))[0]


def rnd(lo=-20, hi=20):
    """A finite binary32 with a uniformly drawn exponent and a full mantissa."""
    e = rng.randint(lo, hi) + 127
    return (rng.getrandbits(1) << 31) | (e << 23) | rng.getrandbits(23)


def ident(x):
    return x


def case_random():
    return [rnd() for _ in range(M * K)], [rnd() for _ in range(K * N)]


def case_narrow():
    # Same-magnitude terms of both signs: heavy cancellation in every sum.
    return [rnd(-1, 1) for _ in range(M * K)], [rnd(-1, 1) for _ in range(K * N)]


def case_fused():
    # ISA sec 9C.1's table in binary32: 2^127 * 2 - 2^127 must be 2^127, not
    # inf, and (1+2^-23)^2 - 1 keeps the low product bits a rounded product
    # loses. Rows alternate the two patterns; the rest random.
    a, b = case_random()
    big, two, one_eps = f2b(2.0 ** 127), f2b(2.0), 0x3f800001
    for m in range(M):
        for k in range(K):
            a[m * K + k] = f2b(0.0)
    for k in range(K):
        for n in range(N):
            b[k * N + n] = f2b(0.0)
    for m in range(M):
        if m % 2 == 0:
            a[m * K + 0], a[m * K + 1] = f2b(-2.0 ** 127), big
        else:
            a[m * K + 0], a[m * K + 1] = f2b(-1.0), one_eps
    for n in range(N):
        b[0 * N + n] = f2b(1.0)
        b[1 * N + n] = two if n % 2 == 0 else one_eps
    return a, b


def case_special():
    a, b = case_random()
    specials = [0x00000000, 0x80000000, 0x00000001, 0x807fffff, 0x00800000,
                0x7f800000, 0xff800000, 0x7fc00000, 0x7f7fffff, 0xff7fffff]
    for i in range(0, M * K, 7):
        a[i] = specials[(i // 7) % len(specials)]
    for i in range(3, K * N, 11):
        b[i] = specials[(i // 11) % len(specials)]
    # subnormal results: tiny times tiny-ish
    for k in range(K):
        a[5 * K + k] = rnd(-80, -70)
        b[k * N + 5] = rnd(-70, -60)
    return a, b


CASES = [('random', case_random, 8, 32, False), ('cancel', case_narrow, 8, 32, False),
         ('fused', case_fused, 8, 32, False), ('special', case_special, 8, 32, False),
         # other bases, B below A, and the source-free event (mod[4])
         ('bases', case_random, 40, 3, True)]

out = []
w = out.append
tid = [0]


def nid():
    tid[0] += 1
    return tid[0]


w("// t42_mmaf32 -- generated by gen_t42_mmaf32.py; do not edit by hand.")
w("// m.mma.f32.async (ISA sec 9C.5) against tools/model/fp32.py mma_ref,")
w("// the sequential binary32 FMA of sec 9C.1.")
w(".org 0")
w("start:")
w("    mb.init   b1")
w("    mb.init   b2")
data = []
base = DATA
for idx, (name, gen, va, vb, sf) in enumerate(CASES):
    a, b = gen()
    c0 = [f2b(0.0)] * (M * N)
    c = mma_ref(a, b, c0, M, N, K, widen=ident)
    a_addr, b_addr = base, base + M * K * 4
    base = b_addr + K * N * 4
    data.append((f"a{idx}", a_addr, a))
    data.append((f"b{idx}", b_addr, b))
    w(f"    // ---- {idx}: {name}, A at v{va}, B at v{vb}{', source-free' if sf else ''} ----")
    w(f"    .li       s10, #{a_addr}")
    for i in range(16):
        w(f"    v.ld.w    v{va+i}, [s10, #{i*64}]")
    w(f"    .li       s11, #{b_addr}")
    for i in range(16):
        w(f"    v.ld.w    v{vb+i}, [s11, #{i*64}]")
    w("    m.zero    a3")
    w("    mb.arm    s12, b1, #0, #1")
    if sf:
        w("    mb.arm    s13, b2, #0, #1")
        w(f"    m.mma.f32.async.sf a3, v{va}, v{vb}, s12")
        w("    mb.wait   s13")
        # the fragments are free: overwrite them before the result is read
        w(f"    v.movi    v{va}, #-1")
        w(f"    v.movi    v{vb+15}, #-1")
    else:
        w(f"    m.mma.f32.async a3, v{va}, v{vb}, s12")
    w("    mb.wait   s12")
    # Every row; eight lanes of it (even lanes of even rows, odd of odd), so
    # every row and every lane is checked and the program stays below DATA.
    for r in range(M):
        w(f"    .li       s14, #{r}")
        w("    a.vread   v7, a3, s14")
        for ln in sorted((3 * r + 2 * j) % N for j in range(8)):
            w(f"    .assert_lane v7, #{ln}, #0x{c[r*N+ln]:08x}, #{nid()}")
    if idx == 0:
        # a second command accumulates onto the same C
        c2 = mma_ref(a, b, c, M, N, K, widen=ident)
        w("    mb.arm    s12, b1, #0, #1")
        w(f"    m.mma.f32.async.k16 a3, v{va}, v{vb}, s12")
        w("    mb.wait   s12")
        for r in (0, 6, 15):
            w(f"    .li       s14, #{r}")
            w("    a.vread   v7, a3, s14")
            for ln in range(N):
                w(f"    .assert_lane v7, #{ln}, #0x{c2[r*N+ln]:08x}, #{nid()}")
        # and an FP16 command after it still reads FP16 fragments: the
        # binary32 addressing must not stick. The first eight registers of
        # each fragment, read as 16x16 FP16.
        a16 = [(a[i // 2] >> (16 * (i % 2))) & 0xffff for i in range(M * K)]
        b16 = [(b[i // 2] >> (16 * (i % 2))) & 0xffff for i in range(K * N)]
        c16 = mma_ref(a16, b16, c0, M, N, K)
        w("    m.zero    a4")
        w("    mb.arm    s12, b1, #0, #1")
        w(f"    m.mma.async.k16.f16 a4, v{va}, v{vb}, s12")
        w("    mb.wait   s12")
        for r in (0, 9, 15):
            w(f"    .li       s14, #{r}")
            w("    a.vread   v7, a4, s14")
            for ln in range(N):
                w(f"    .assert_lane v7, #{ln}, #0x{c16[r*N+ln]:08x}, #{nid()}")
    w("")
w("    exit")
w("")

for label, addr, vals in data:
    w(f".org 0x{addr:x}")
    w(f"{label}:")
    for k in range(0, len(vals), 8):
        w("    .word " + ", ".join(f"0x{v:08x}" for v in vals[k:k+8]))

path = os.path.join(HERE, 't42_mmaf32.s')
with open(path, 'w') as fh:
    fh.write("\n".join(out) + "\n")
print(f"{tid[0]} checks -> {path} (data to 0x{base:x})")
