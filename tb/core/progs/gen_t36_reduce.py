#!/usr/bin/env python3
"""
Generate tb/core/progs/t36_reduce.s -- every integer reduction, every mask
shape, against a Python model.

The VALU's integer reductions were rebuilt for timing (R38, timing-003): three
trees chosen at the end instead of one tree choosing among eight operations at
every level, and min/max as one unsigned max over an order-preserving key.
That rewrite is only right if it is right for every operation, every sign
pattern and every mask -- including the empty mask, where each operation must
return its identity -- and t01 covers five of the eight operations on one
vector. This covers all eight, signed and unsigned, on vectors built from the
values where signed and unsigned order disagree, under full, empty,
single-lane and random masks, scalar and broadcast forms.
"""
import os
import random

HERE = os.path.dirname(os.path.abspath(__file__))
M32 = (1 << 32) - 1
VLEN = 16
DATA = 0x10000

INTERESTING = [0, 1, 2, M32, M32 - 1, 1 << 31, (1 << 31) - 1, (1 << 31) + 1,
               0x5555aaaa, 0xaaaa5555, 0x80000001, 0x7ffffffe, 0xffff0000, 0x0000ffff]


def s32(x):
    return x - (1 << 32) if x >> 31 else x


OPS = {
    'add':   (lambda xs: sum(xs) & M32, 0),
    'and':   (lambda xs: _fold(lambda a, b: a & b, xs, M32), M32),
    'or':    (lambda xs: _fold(lambda a, b: a | b, xs, 0), 0),
    'xor':   (lambda xs: _fold(lambda a, b: a ^ b, xs, 0), 0),
    'max.s': (lambda xs: max(xs, key=s32) if xs else 1 << 31, 1 << 31),
    'min.s': (lambda xs: min(xs, key=s32) if xs else (1 << 31) - 1, (1 << 31) - 1),
    'max.u': (lambda xs: max(xs) if xs else 0, 0),
    'min.u': (lambda xs: min(xs) if xs else M32, M32),
}


def _fold(f, xs, ident):
    r = ident
    for x in xs:
        r = f(r, x)
    return r


def main():
    rng = random.Random(20261009)
    vectors = []
    for k in range(8):
        if k == 0:
            v = [(1 << 31) + i if i % 2 else i for i in range(VLEN)]   # signs alternate
        elif k == 1:
            v = [M32 - i for i in range(VLEN)]                          # all negative
        else:
            v = [rng.choice(INTERESTING) if rng.random() < 0.5 else rng.getrandbits(32)
                 for _ in range(VLEN)]
        vectors.append(v)
    masks = [0xffff, 0x0000, 0x0001, 0x8000, 0x0f0f] + [rng.getrandbits(16) for _ in range(3)]

    out = []
    w = out.append
    tid = [0]

    def nid():
        tid[0] += 1
        return tid[0]

    w("// t36_reduce -- generated by gen_t36_reduce.py; do not edit by hand.")
    w("// Every integer reduction under every mask shape, against a Python model.")
    w(".org 0")
    w("start:")
    for vi, v in enumerate(vectors):
        w(f"    .li      s3, #{DATA + vi * 64}")
        w(f"    v.ld.w   v1, [s3, #0]")
        for m in masks:
            w(f"    .li      s4, #{m:#x}")
            w(f"    p.frombits p1, s4")
            active = [v[i] for i in range(VLEN) if (m >> i) & 1]
            for op, (fn, _ident) in OPS.items():
                want = fn(active) & M32
                w(f"    @p1 v.reduce.{op} s6, v1")
                w(f"    .assert_eq s6, #{want:#x}, #{nid()}")
        # The broadcast form, unpredicated (a masked destination keeps its
        # inactive lanes, which is t01's business): every lane holds the result.
        for op in ('min.u', 'max.s'):
            want = OPS[op][0](v) & M32
            w(f"    v.reduce.{op}.b v24, v1")
            w(f"    .assert_lane v24, #0, #{want:#x}, #{nid()}")
            w(f"    .assert_lane v24, #15, #{want:#x}, #{nid()}")
    w("    exit")
    w("")
    for vi, v in enumerate(vectors):
        w(f".org {DATA + vi * 64:#x}")
        for i in range(0, VLEN, 2):
            w(f"    .dword 0x{(v[i + 1] << 32) | v[i]:016x}")
    path = os.path.join(HERE, 't36_reduce.s')
    open(path, 'w').write('\n'.join(out) + '\n')
    print(f"wrote {path}: {tid[0]} checks")


if __name__ == '__main__':
    main()
