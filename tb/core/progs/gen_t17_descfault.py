#!/usr/bin/env python3
"""
Generate tb/core/progs/t17_descfault.s -- a geometry the engine must refuse.

ISA sec 9E.2 lists what raises DESCRIPTOR_FAULT rather than being
approximated, and an 8-byte-aligned source is on that list. The RTL header and
doc/conformance.md D4 both claimed that check existed; only the block row SIZE
was checked, never where each row STARTS. A 13-element FP16 row is 26 bytes,
so every row after the first began two bytes off, and the engine returned data
shifted by two bytes per row while raising nothing.

That was found by compiling a GEMM with an N tail (milestone C2), which is
where sec 15 C2 says the fragment/tile mismatch should surface.

The transfer here uses a 26-byte row stride and must fault. Run with
+expectfault=04.
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))

SRC = 0x8000
DESC = 0x9000
LDB = 13            # 13 FP16 elements = 26 bytes: not a multiple of 8
ROWS = 16


def tensormap(base, e0, e1, s0, s1, b0, b1, rank=2, dtype=0, pad=0):
    w = [0] * 32
    w[0] = base
    w[1] = e0
    w[2] = e1
    w[6] = s0
    w[7] = s1
    w[11] = (b1 << 32) | b0
    w[13] = (pad << 48) | (dtype << 40) | (rank << 32)
    return w


out = []
w = out.append
w("// t17_descfault -- generated by gen_t17_descfault.py; do not edit.")
w("//")
w("// A source row stride of 26 bytes is neither a whole number of 8-byte")
w("// units nor a multiple of one, so every row after the first would land")
w("// shifted in the window. ISA sec 9E.2 makes that DESCRIPTOR_FAULT rather")
w("// than an approximation: the engine used to return the shifted data and")
w("// raise nothing, which is a wrong answer wearing the shape of a right one.")
w(".org 0")
w("start:")
w("    w.def     w0, #32, #8")
w(f"    .li       s1, #{DESC}")
w("    td.load   d0, [s1]")
w("    mb.init   b0")
w("    mb.arm    s2, b0, #0, #1")
w("    .li       s10, #0")
w("    .li       s11, #0")
w("    t.ld.async.h w0, d0, s10, s2      // must raise DESCRIPTOR_FAULT")
w("    mb.wait   s2")
w("    trap      #99                     // must be unreachable")
w("")


def emit(addr, words, label):
    w(f".org {addr:#x}")
    w(f"{label}:")
    for x in words:
        w(f"    .dword 0x{x & ((1 << 64) - 1):016x}")
    w("")


emit(SRC, [0] * (ROWS * LDB // 4 + 4), "src")
emit(DESC, tensormap(SRC, ROWS, LDB, LDB * 2, 2, 16, 16), "desc")

path = os.path.join(HERE, 't17_descfault.s')
open(path, 'w').write('\n'.join(out) + '\n')
print(f"wrote {path}: row stride {LDB * 2} bytes must fault")
