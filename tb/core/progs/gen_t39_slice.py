#!/usr/bin/env python3
"""
Generate tb/core/progs/t39_slice.s -- every Role Context names the same
descriptor, window, barriers and accumulator, and each gets its own (R39-05,
RSLICE).

Run with +allroles +slice. Every context executes the same instructions with
the same indices: `td.load d1`, `w.def w1`, `mb.arm ... b0`, `t.ld.async w1,
d1`, `m.zero a1`, `mb.arm ... b1`, `m.mma.async a1`, `a.vread ... a1`. Only the
data differ: context r snapshots the TensorMap at DESC + 256r, which points at
its own A, and loads its own B. A context that reached another's slice -- a
descriptor, a window, a barrier generation or an accumulator -- computes some
other context's product, or waits forever, and the per-context check of C
says which.

Expectations come from tools/model/fp32.py's mma_ref, as for t11 and t25.
"""
import os
import random
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..', '..'))
sys.path.insert(0, os.path.join(ROOT, 'tools', 'model'))
sys.path.insert(0, HERE)
from fp32 import f32_to_f16_bits, mma_ref, f2b   # noqa: E402
from gen_t33_tdesc import Mem, tensormap         # noqa: E402

M = N = K = 16
ROLES = 4                 # data for up to four contexts
DESC = 0xC000             # TensorMap of context r at DESC + 256 r
A_BASE = 0xD000           # A of context r at A_BASE + 512 r (16 x 16 f16)
B_BASE = 0xE000           # B of context r at B_BASE + 512 r
CHECK = [(0, 0), (0, 15), (5, 9), (15, 0), (15, 15)]

rng = random.Random(20261009)
A, B, C = [], [], []
for r in range(ROLES):
    a = [f32_to_f16_bits(rng.randint(-8, 8) / 2.0) for _ in range(M * K)]
    b = [f32_to_f16_bits(rng.randint(-8, 8) / 2.0) for _ in range(K * N)]
    A.append(a)
    B.append(b)
    C.append(mma_ref(a, b, [f2b(0.0)] * (M * N), M, N, K))


def pack64(h):
    """f16 halves -> 64-bit words, little-endian."""
    return [h[4*i] | (h[4*i+1] << 16) | (h[4*i+2] << 32) | (h[4*i+3] << 48)
            for i in range(len(h) // 4)]


out = []
w = out.append
n = [0]


def nid():
    n[0] += 1
    return n[0]


mem = Mem()
for r in range(ROLES):
    mem.put_words(A_BASE + 512 * r, pack64(A[r]))
    mem.put_words(B_BASE + 512 * r, pack64(B[r]))
    mem.put_words(DESC + 256 * r,
                  tensormap(A_BASE + 512 * r, [M, K], [2 * K, 2], [M, K], 'f16', 0))

w("// t39_slice -- generated by gen_t39_slice.py; do not edit by hand.")
w("// Every context names d1, w1, b0, b1 and a1 and must get its own (RSLICE).")
w(".org 0")
w("start:")
w("    s.rdspecial s1, role_id")
w("    // A, through this context's TensorMap, the transfer engine, a window")
w("    // and a barrier -- the same names in every context")
w("    s.shli      s2, s1, #8")
w(f"    .li         s3, #{DESC}")
w("    s.add       s3, s3, s2")
w("    td.load     d1, [s3]")
w("    w.def       w1, #32, #8                // v32..v39")
w("    mb.arm      s5, b0, #0, #1")
w("    .li         s10, #0")
w("    .li         s11, #0")
w("    t.ld.async.h w1, d1, s10, s5")
w("    mb.wait     s5")
w("    // B, with the LSU")
w("    s.shli      s6, s1, #9")
w(f"    .li         s7, #{B_BASE}")
w("    s.add       s7, s7, s6")
for i in range(8):
    w(f"    v.ld.w      v{40 + i}, [s7, #{64 * i}]")
w("    // C = A B in a1, completing on b1")
w("    m.zero      a1")
w("    mb.arm      s12, b1, #0, #1")
w("    m.mma.async a1, v32, v40, s12")
w("    mb.wait     s12")
for r in range(1, ROLES):
    w(f"    s.addi      s20, s1, #-{r}")
    w(f"    br.z        s20, check{r}")
for r in range(ROLES):
    w(f"check{r}:")
    for row, col in CHECK:
        w(f"    .li         s13, #{row}")
        w("    a.vread     v8, a1, s13")
        w(f"    .assert_lane v8, #{col}, #0x{C[r][row * N + col]:08x}, #{nid()}")
    w("    w.release   w1")
    w("    td.release  d1")
    w("    exit")
w("")
mem.emit(w)

path = os.path.join(HERE, 't39_slice.s')
with open(path, 'w') as fh:
    fh.write("\n".join(out) + "\n")
print(f"{n[0]} checks -> {path}")
