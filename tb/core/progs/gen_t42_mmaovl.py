#!/usr/bin/env python3
"""
Generate tb/core/progs/t42_mmaovl.s -- trains of m.mma.dp.async issued with
nothing between them (R42, tnca_core MTX_PIPE): same slot and different
slots, different formats and K, one barrier counting the whole train, and an
a.vread, an a.vwrite and an m.zero issued straight behind a train without a
wait, so the ordering against in-flight commands is the core's to keep.

It is an ordinary program: it passes on any core with MAC_DP=1, and on one
with MTX_PIPE=1 the commands overlap. Expectations: tools/model/fdp.py.
"""
import os
import random
import sys
from fractions import Fraction

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..', '..'))
sys.path.insert(0, os.path.join(ROOT, 'tools', 'model'))
import fdp                                            # noqa: E402
from fp32 import f2b                                  # noqa: E402

M = N = 16
WIDTH = {'f16': 2, 'bf16': 2, 'e5m2': 1, 'e4m3': 1}
rng = random.Random(20261120)


def rnd_elem(fmt):
    w = 8 * WIDTH[fmt]
    while True:
        b = rng.getrandbits(w)
        k, s, v = fdp.element(fmt, b)
        if k == 'fin' and Fraction(1, 16) <= abs(v) <= 4:
            return b


# fragment sets: (A format, B format, K, first A register, first B register)
SETS = [('f16', 'f16', 16, 0, 8), ('f16', 'e4m3', 16, 16, 24), ('e4m3', 'e4m3', 32, 32, 40),
        ('bf16', 'f16', 16, 44, 52)]
out = []
w = out.append
tid = [0]


def nid():
    tid[0] += 1
    return tid[0]


w("// t42_mmaovl -- generated by gen_t42_mmaovl.py; do not edit by hand.")
w(".org 0")
w("start:")
w("    mb.init   b1")
data = []
base = 0x8000
frag = []
for idx, (fa, fb, K, va, vb) in enumerate(SETS):
    ba, bb = WIDTH[fa], WIDTH[fb]
    a = [rnd_elem(fa) for _ in range(M * K)]
    b = [rnd_elem(fb) for _ in range(K * N)]
    a_addr = base
    b_addr = base + M * K * ba
    base = (b_addr + K * N * bb + 0x3ff) & ~0x3ff
    data.append((f"a{idx}", a_addr, a, ba))
    data.append((f"b{idx}", b_addr, b, bb))
    w(f"    .li       s10, #{a_addr}")
    for i in range((M * K * ba) // 64):
        w(f"    v.ld.w    v{va+i}, [s10, #{i*64}]")
    w(f"    .li       s11, #{b_addr}")
    for i in range((K * N * bb) // 64):
        w(f"    v.ld.w    v{vb+i}, [s11, #{i*64}]")
    sfx = f".k{K}.{fa}" + ('' if fa == fb else '.' + fb)
    frag.append((fa, fb, K, a, b, va, vb, sfx))
vw = [f2b(float(i) - 3.5) for i in range(16)]
data.append(("vw", base, vw, 4))
w(f"    .li       s10, #{base}")
w("    v.ld.w    v61, [s10, #0]")
base += 0x400

acc = {1: [f2b(0.0)] * (M * N), 2: [f2b(0.0)] * (M * N)}


def mma(slot, s):
    fa, fb, K, a, b, va, vb, sfx = frag[s]
    w(f"    m.mma.dp.async{sfx} a{slot}, v{va}, v{vb}, s12")
    acc[slot] = fdp.mma_dp_ref(fa, fb, a, b, acc[slot], M, N, K)


def check(slot, rows=(0, 6, 15), lanes=(0, 5, 15)):
    for r in rows:
        w(f"    .li       s13, #{r}")
        w(f"    a.vread   v60, a{slot}, s13")
        for ln in lanes:
            w(f"    .assert_lane v60, #{ln}, #0x{acc[slot][r*N+ln]:08x}, #{nid()}")


w("    m.zero    a1")
w("    m.zero    a2")
w("    // ---- train 1: four commands, one barrier, then the wait ----")
w("    mb.arm    s12, b1, #0, #4")
mma(1, 0); mma(1, 1); mma(2, 0); mma(1, 2)
w("    mb.wait   s12")
check(1); check(2)
w("    // ---- train 2: reads straight behind the train, no wait first ----")
w("    mb.arm    s12, b1, #0, #3")
mma(2, 1); mma(2, 3); mma(1, 0)
check(2, rows=(3,)); check(1, rows=(9,))
w("    mb.wait   s12")
w("    // ---- train 3: a row write and a zero behind in-flight commands ----")
w("    mb.arm    s12, b1, #0, #5")
mma(1, 3); mma(1, 0)
w("    .li       s13, #5")
w("    a.vwrite  a1, s13, v61")
acc[1][5*N:6*N] = vw
mma(2, 2)
w("    m.zero    a2")
acc[2] = [f2b(0.0)] * (M * N)
mma(2, 0); mma(1, 1)
w("    mb.wait   s12")
check(1, rows=(0, 5, 15)); check(2)
w("    // ---- train 4: twelve on one slot ----")
w("    mb.arm    s12, b1, #0, #12")
for i in range(12):
    mma(2, (0, 1, 3, 2)[i % 4])
w("    mb.wait   s12")
check(2)
w("    exit")
w("")


def emit(label, addr, vals, nb):
    raw = b''.join(int(v).to_bytes(nb, 'little') for v in vals)
    words = [int.from_bytes(raw[i:i+4], 'little') for i in range(0, len(raw), 4)]
    w(f".org 0x{addr:x}")
    w(f"{label}:")
    for k in range(0, len(words), 8):
        w("    .word " + ", ".join(f"0x{v:08x}" for v in words[k:k+8]))


for label, addr, vals, nb in data:
    emit(label, addr, vals, nb)

path = os.path.join(HERE, 't42_mmaovl.s')
with open(path, 'w') as fh:
    fh.write("\n".join(out) + "\n")
print(f"{tid[0]} checks -> {path} (data to 0x{base:x})")
