#!/usr/bin/env python3
"""
Generate tb/core/progs/t37_lsu_straddle.s -- unaligned contiguous vector
stores and loads, every byte offset, against a Python model.

The LSU's beat planner was restructured for timing (R38, timing-006): each
lane's word addresses, byte enables and shifted write data are now formed in
S_SETUP and the planner only chooses a word and ORs the lanes that hit it.
The case that rewrite has to get right is a beat that carries the high half
of one straddling lane, whole lanes, and the low half of the next straddler
-- an unaligned vector STORE -- and t02 has only a scalar straddling store
and one unaligned vector load. This covers byte, half and word elements at
every byte offset 0..7, under a full and a sparse mask, both directions:
  store: each case writes into its own area between guard words, and every
         word of the area (guards included) is checked;
  load:  every lane is checked, inactive lanes keeping their old value.
"""
import os
import random

HERE = os.path.dirname(os.path.abspath(__file__))
VLEN = 16
DATA = 0x18000                      # past the code (~92 KB), inside the 128 KB image
SIZES = [('b', 1), ('h', 2), ('w', 4)]
AREA_WORDS = 12                     # guard + up to 9 data words + slack
BG = 0xa5                           # background byte of every store area
OLD = 77                            # inactive lanes' value before a load


def main():
    rng = random.Random(20261009)
    masks = [0xffff, 0x5a3c]        # full; sparse with active neighbours
    src = [rng.getrandbits(32) for _ in range(VLEN)]            # store data
    src2 = bytes(rng.getrandbits(8) for _ in range(160))        # load source

    out = []
    w = out.append
    tid = [0]

    def nid():
        tid[0] += 1
        return tid[0]

    src_at = DATA
    src2_at = DATA + 0x100
    area0 = DATA + 0x400

    w("// t37_lsu_straddle -- generated by gen_t37_lsu_straddle.py; do not edit by hand.")
    w("// Unaligned contiguous vector stores and loads at every byte offset.")
    w(".org 0")
    w("start:")
    w(f"    .li      s3, #{src_at:#x}")
    w(f"    v.ld.w   v1, [s3, #0]")
    w(f"    .li      s9, #{src2_at:#x}")

    areas = []
    case = 0
    for sfx, sz in SIZES:
        for off in range(8):
            for m in masks:
                # ---- store: into its own area, after a guard word ----------
                base = area0 + case * AREA_WORDS * 8
                mem = bytearray([BG]) * (AREA_WORDS * 8)
                for i in range(VLEN):
                    if (m >> i) & 1:
                        a = 8 + off + i * sz
                        mem[a:a + sz] = (src[i] & ((1 << (8 * sz)) - 1)).to_bytes(sz, 'little')
                areas.append(base)
                w(f"    // store .{sfx}, offset {off}, mask {m:#06x}")
                w(f"    .li      s4, #{m:#x}")
                w(f"    p.frombits p1, s4")
                w(f"    .li      s5, #{base + 8:#x}")
                w(f"    @p1 v.st.{sfx} [s5, #{off}], v1")
                w(f"    .li      s6, #{base:#x}")
                for k in range(AREA_WORDS):
                    want = int.from_bytes(mem[8 * k:8 * k + 8], 'little')
                    w(f"    s.ld.d   s7, [s6, #{8 * k}]")
                    w(f"    .assert_eq s7, #{want:#018x}, #{nid()}")
                # ---- load: the same geometry, from the byte source ---------
                w(f"    // load .{sfx}, offset {off}, mask {m:#06x}")
                w(f"    v.movi   v2, #{OLD}")
                w(f"    @p1 v.ld.{sfx} v2, [s9, #{off}]")
                for i in range(VLEN):
                    if (m >> i) & 1:
                        a = off + i * sz
                        want = int.from_bytes(src2[a:a + sz], 'little')
                    else:
                        want = OLD
                    w(f"    .assert_lane v2, #{i}, #{want:#x}, #{nid()}")
                case += 1
    w("    exit")
    w("")
    w(f".org {src_at:#x}")
    for i in range(0, VLEN, 2):
        w(f"    .dword 0x{(src[i + 1] << 32) | src[i]:016x}")
    w(f".org {src2_at:#x}")
    for k in range(0, len(src2), 8):
        w(f"    .dword 0x{int.from_bytes(src2[k:k + 8], 'little'):016x}")
    bgw = int.from_bytes(bytes([BG]) * 8, 'little')
    for base in areas:
        w(f".org {base:#x}")
        for _ in range(AREA_WORDS):
            w(f"    .dword 0x{bgw:016x}")
    path = os.path.join(HERE, 't37_lsu_straddle.s')
    open(path, 'w').write('\n'.join(out) + '\n')
    print(f"wrote {path}: {tid[0]} checks")


if __name__ == '__main__':
    main()
