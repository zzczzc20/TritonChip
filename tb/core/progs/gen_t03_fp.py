#!/usr/bin/env python3
"""
Generate tb/core/progs/t03_fp.s.

Expected values come from tools/model/fp32.py -- the same exact-arithmetic
oracle the FMA unit was verified against -- so the core test and the unit test
cannot drift apart. The vf.reduce.add expectation is folded with the balanced
binary tree the ISA fixes in sec 8.7, not with a left-to-right sum.
"""
import os
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..', '..'))
sys.path.insert(0, os.path.join(ROOT, 'tools', 'model'))
from fp32 import fma_ref, f2b, b2f            # noqa: E402

ONE = f2b(1.0)
VLEN = 16

A = [1.0, -2.5, 3.75, 0.0, -0.0, 1e-30, 1e30, 65504.0,
     0.1, -0.2, 123456.75, -1.0, 2.0, -3.0, 7.5, 1024.0]
B = [2.0, 4.0, -1.25, 5.0, -5.0, 1e-20, 1e20, 0.5,
     0.3, 0.4, -0.25, 1.0, -2.0, 3.0, -7.5, 0.001953125]
C = [0.5, 1.0, 2.0, -3.0, 4.0, 1.0, -1e30, 1.0,
     -0.03, 0.08, 1.0, 0.0, 1.0, -1.0, 56.25, 1.0]

Ab = [f2b(x) for x in A]
Bb = [f2b(x) for x in B]
Cb = [f2b(x) for x in C]


def reduce_tree(vals, op):
    """The balanced binary fold the ISA mandates (sec 8.7)."""
    cur = list(vals)
    while len(cur) > 1:
        cur = [op(cur[2 * i], cur[2 * i + 1]) for i in range(len(cur) // 2)]
    return cur[0]


def fadd(x, y):
    return fma_ref(x, ONE, y)


def lt32(x, y):
    mx = (0x80000000 - (x & 0x7fffffff)) if (x >> 31) else (0x80000000 + (x & 0x7fffffff))
    my = (0x80000000 - (y & 0x7fffffff)) if (y >> 31) else (0x80000000 + (y & 0x7fffffff))
    return mx < my


def fmax(x, y):
    return y if lt32(x, y) else x


def fmin(x, y):
    return x if lt32(x, y) else y


out = []
w = out.append
tid = [0]


def nid():
    tid[0] += 1
    return tid[0]


w("// t03_fp -- generated by gen_t03_fp.py; do not edit by hand.")
w("// Expected values come from tools/model/fp32.py (exact Fraction arithmetic).")
w(".org 0")
w("start:")
w("    .li s1, #va")
w("    .li s2, #vb")
w("    .li s3, #vc")
w("    v.ld.w v1, [s1, #0]")
w("    v.ld.w v2, [s2, #0]")
w("    v.ld.w v3, [s3, #0]")
w("")

cases = [
    ("vf.add v4, v1, v2", [fma_ref(Ab[i], ONE, Bb[i]) for i in range(VLEN)], "add"),
    ("vf.sub v4, v1, v2", [fma_ref(Ab[i], ONE, Bb[i], sub_c=True) for i in range(VLEN)], "sub"),
    ("vf.mul v4, v1, v2", [fma_ref(Ab[i], Bb[i], 0, mul_only=True) for i in range(VLEN)], "mul"),
    ("vf.fma v4, v1, v2, v3", [fma_ref(Ab[i], Bb[i], Cb[i]) for i in range(VLEN)], "fma"),
    ("vf.fms v4, v1, v2, v3", [fma_ref(Ab[i], Bb[i], Cb[i], sub_c=True) for i in range(VLEN)], "fms"),
    ("vf.min v4, v1, v2", [fmin(Ab[i], Bb[i]) for i in range(VLEN)], "min"),
    ("vf.max v4, v1, v2", [fmax(Ab[i], Bb[i]) for i in range(VLEN)], "max"),
    ("vf.neg v4, v1", [Ab[i] ^ 0x80000000 for i in range(VLEN)], "neg"),
    ("vf.abs v4, v1", [Ab[i] & 0x7fffffff for i in range(VLEN)], "abs"),
]

for insn, expect, label in cases:
    w(f"    // ---- {label} ----")
    w(f"    {insn}")
    for i in range(VLEN):
        w(f"    .assert_lane v4, #{i}, #0x{expect[i]:08x}, #{nid()}")
    w("")

# ---- compares --------------------------------------------------------------
w("    // ---- vf.cmp ----")
def fcmp(cc, x, y):
    nanx = (x >> 23) & 0xff == 0xff and (x & 0x7fffff)
    nany = (y >> 23) & 0xff == 0xff and (y & 0x7fffff)
    unord = bool(nanx or nany)
    eq = (not unord) and (x == y or ((x & 0x7fffffff) == 0 and (y & 0x7fffffff) == 0))
    lt = (not unord) and lt32(x, y) and not eq
    return {
        'eq': eq, 'ne': unord or not eq,
        'lt': lt, 'le': (not unord) and (lt or eq),
        'gt': (not unord) and not lt32(x, y) and not eq,
        'ge': (not unord) and ((not lt32(x, y)) or eq),
        'o': not unord, 'uo': unord,
    }[cc]

for cc in ('lt', 'le', 'gt', 'ge', 'eq', 'ne'):
    bits = 0
    for i in range(VLEN):
        if fcmp(cc, Ab[i], Bb[i]):
            bits |= 1 << i
    w(f"    vf.cmp.{cc} p1, v1, v2")
    w("    p.ballot s4, p1")
    w(f"    .assert_eq s4, #0x{bits:04x}, #{nid()}")
w("")

# NaN handling: unordered compares
w("    // ---- NaN: every ordered compare is false, ne and uo are true ----")
w("    .li s5, #nanv")
w("    v.ld.w v5, [s5, #0]")
for cc in ('lt', 'le', 'gt', 'ge', 'eq'):
    w(f"    vf.cmp.{cc} p1, v5, v1")
    w("    p.any s4, p1")
    w(f"    .assert_eq s4, #0, #{nid()}")
w("    vf.cmp.ne p1, v5, v1")
w("    p.ballot s4, p1")
w(f"    .assert_eq s4, #0xffff, #{nid()}")
w("    vf.cmp.uo p1, v5, v1")
w("    p.ballot s4, p1")
w(f"    .assert_eq s4, #0xffff, #{nid()}")
w("    vf.cmp.o p1, v5, v1")
w("    p.any s4, p1")
w(f"    .assert_eq s4, #0, #{nid()}")
w("")

# min/max NaN modes
w("    // ---- min/max NaN modes (ISA sec 8.3) ----")
w("    vf.min.ieee v6, v5, v1")
for i in (0, 1):
    w(f"    .assert_lane v6, #{i}, #0x{Ab[i]:08x}, #{nid()}")   # NaN ignored
w("    vf.min.prop v6, v5, v1")
w("    vf.cmp.uo p1, v6, v6")
w("    p.all s4, p1")
w(f"    .assert_eq s4, #1, #{nid()}")                            # .prop => every lane NaN
w("")

# signed zero in min/max
w("    // ---- min(+0,-0) = -0, max(+0,-0) = +0 ----")
w("    .li s6, #zeros")
w("    v.ld.w v7, [s6, #0]")          # +0 in even lanes, -0 in odd
w("    .li s7, #zeros2")
w("    v.ld.w v8, [s7, #0]")          # -0 in even lanes, +0 in odd
w("    vf.min v9, v7, v8")
w(f"    .assert_lane v9, #0, #0x80000000, #{nid()}")
w(f"    .assert_lane v9, #1, #0x80000000, #{nid()}")
w("    vf.max v9, v7, v8")
w(f"    .assert_lane v9, #0, #0x00000000, #{nid()}")
w(f"    .assert_lane v9, #1, #0x00000000, #{nid()}")
w("")

# converts
w("    // ---- converts ----")
w("    v.iota v10")
w("    v.subi v10, v10, #8")            # -8 .. 7
w("    vf.cvt.s32.f32 v11, v10")
for i in (0, 8, 15):
    w(f"    .assert_lane v11, #{i}, #0x{f2b(float(i - 8)):08x}, #{nid()}")
w("    vf.cvt.f32.s32 v12, v11")
for i in (0, 8, 15):
    w(f"    .assert_lane v12, #{i}, #0x{(i - 8) & 0xffffffff:08x}, #{nid()}")
w("    .li s8, #rnd")
w("    v.ld.w v13, [s8, #0]")           # 2.5, -2.5, 1.5, -1.5, ...
w("    vf.cvt.f32.s32 v14, v13")                       # .rtz
for i, e in ((0, 2), (1, -2), (2, 1), (3, -1)):
    w(f"    .assert_lane v14, #{i}, #0x{e & 0xffffffff:08x}, #{nid()}")
w("    vf.cvt.f32.s32.rne v14, v13")
for i, e in ((0, 2), (1, -2), (2, 2), (3, -2)):                # ties to even
    w(f"    .assert_lane v14, #{i}, #0x{e & 0xffffffff:08x}, #{nid()}")
w("    vf.cvt.f32.s32.rpi v14, v13")
for i, e in ((0, 3), (1, -2), (2, 2), (3, -1)):
    w(f"    .assert_lane v14, #{i}, #0x{e & 0xffffffff:08x}, #{nid()}")
w("    vf.cvt.f32.s32.rmi v14, v13")
for i, e in ((0, 2), (1, -3), (2, 1), (3, -2)):
    w(f"    .assert_lane v14, #{i}, #0x{e & 0xffffffff:08x}, #{nid()}")
w("")

# reductions
w("    // ---- FP reductions (balanced tree, ISA sec 8.7) ----")
w("    .li s9, #red")
w("    v.ld.w v15, [s9, #0]")
RED = [float(i + 1) * 0.5 for i in range(VLEN)]
Rb = [f2b(x) for x in RED]
w("    vf.reduce.add s10, v15")
w(f"    .assert_eq s10, #0x{reduce_tree(Rb, fadd):08x}, #{nid()}")
w("    vf.reduce.max s10, v15")
w(f"    .assert_eq s10, #0x{reduce_tree(Rb, fmax):08x}, #{nid()}")
w("    vf.reduce.min s10, v15")
w(f"    .assert_eq s10, #0x{reduce_tree(Rb, fmin):08x}, #{nid()}")
w("    vf.reduce.add.b v16, v15")
w(f"    .assert_lane v16, #7, #0x{reduce_tree(Rb, fadd):08x}, #{nid()}")

# masked reduction: identity for the masked-off half
w("    v.iota v17")
w("    v.cmpi.lt p2, v17, #8")
w("    @p2 vf.reduce.add s10, v15")
half = reduce_tree(Rb[:8] + [f2b(0.0)] * 8, fadd)
w(f"    .assert_eq s10, #0x{half:08x}, #{nid()}")
w("    @p2 vf.reduce.max s10, v15")
halfmax = reduce_tree(Rb[:8] + [f2b(float('-inf'))] * 8, fmax)
w(f"    .assert_eq s10, #0x{halfmax:08x}, #{nid()}")
w("")
w("    exit")
w("")

# ---- data ------------------------------------------------------------------
def words(label, vals):
    w(f"{label}:")
    for k in range(0, len(vals), 8):
        w("    .word " + ", ".join(f"0x{v:08x}" for v in vals[k:k + 8]))

w(".org 0x8000")
words("va", Ab)
words("vb", Bb)
words("vc", Cb)
words("nanv", [0x7fc00000] * VLEN)
words("zeros", [0x00000000 if (i % 2 == 0) else 0x80000000 for i in range(VLEN)])
words("zeros2", [0x80000000 if (i % 2 == 0) else 0x00000000 for i in range(VLEN)])
words("rnd", [f2b(2.5), f2b(-2.5), f2b(1.5), f2b(-1.5)] + [f2b(0.0)] * 12)
words("red", Rb)

path = os.path.join(HERE, 't03_fp.s')
with open(path, 'w') as fh:
    fh.write("\n".join(out) + "\n")
print(f"{len(out)} lines, {tid[0]} checks -> {path}")
