#!/usr/bin/env python3
"""
Generate the transposed-transfer tests (ISA sec 9E mod[5], R38 S1-07).

  t30_xpose.s          every lane of the window after `t.ld.async.h.t`, for
                       4, 8 and 16 source rows, with rows and columns past the
                       descriptor's extents. Run on tb_core_xpose.vvp.
  t31_xpose_illegal.s  the same encoding on an engine built without the
                       feature: ILLEGAL_INSTRUCTION (+expectfault=01), not the
                       untransposed transfer it used to perform.
  t32_xpose_badsize.s  a transposed 4-byte transfer, which the engine does
                       not implement: DESCRIPTOR_FAULT (+expectfault=04).
  t33_xpose8.s         R41 X8: `t.ld.async.b.t` (1-byte elements) on an
                       engine built with HAS_TENSOR_XPOSE=2, for 4, 8 and 16
                       source rows, every 1-byte dtype code (int8, e4m3,
                       e5m2), multi-block columns, negative and past-extent
                       rows, a partial (tail) last unit and wholly
                       out-of-bounds units, and a predicated-off command that
                       must leave its window untouched and still complete.
  t34_xpose8_old.s     the same 1-byte transposed load on a 16-bit-only
                       engine (HAS_TENSOR_XPOSE=1): DESCRIPTOR_FAULT (04), the
                       refusal old images keep.
  t35_xpose8_badrows.s 1-byte, R = 12 source rows on the X8 engine:
                       DESCRIPTOR_FAULT (04), the 16-bit geometry rule.
  t36_xpose8_badcol.s  1-byte, contiguous coordinate 4 (not on an 8-byte
                       boundary) on the X8 engine: DESCRIPTOR_FAULT (04).

The engine moves bits and never interprets them, so the source holds
distinct 16-bit patterns and the expected window is computed from the
definition: window element (c, r) = source (r0 + r, c0 + c), zero where
either index falls outside the descriptor.
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))

SRC = 0x8000
LD = 24                  # source row stride in elements: 48 bytes
ROWS_E0 = 20             # source extent, rows
COLS_E1 = 20             # source extent, columns
DESC = 0x9000


def src(r, c):
    return 0x1000 + r * 32 + c


def tensormap(base, e0, e1, s0, s1, b0, b1, rank=2, dtype=0, pad=0):
    w = [0] * 32
    w[0] = base
    w[1] = e0
    w[2] = e1
    w[6] = s0
    w[7] = s1
    w[11] = (b1 << 32) | b0
    w[13] = (pad << 48) | (dtype << 40) | (rank << 32)
    return w


def expected_window(R, C, r0, c0):
    halves = []
    for c in range(C):
        for r in range(R):
            rr, cc = r0 + r, c0 + c
            halves.append(src(rr, cc) if rr < ROWS_E0 and cc < COLS_E1 else 0)
    lanes = [halves[2 * i] | (halves[2 * i + 1] << 16) for i in range(len(halves) // 2)]
    return lanes


def emit_data(w, descs):
    words = []
    for r in range(ROWS_E0 + 16):
        row = [src(r, c) if (r < ROWS_E0 and c < COLS_E1) else 0 for c in range(LD)]
        for i in range(0, LD, 4):
            words.append(row[i] | (row[i + 1] << 16) | (row[i + 2] << 32) | (row[i + 3] << 48))
    w(f".org {SRC:#x}")
    w("src:")
    for x in words:
        w(f"    .dword 0x{x:016x}")
    for i, d in enumerate(descs):
        w(f".org {DESC + 0x100 * i:#x}")
        w(f"desc{i}:")
        for x in d:
            w(f"    .dword 0x{x:016x}")


def t30():
    out = []
    w = out.append
    w("// t30_xpose -- generated by gen_t30_xpose.py; do not edit by hand.")
    w("// ISA sec 9E mod[5]: window element (c, r) = source (r0+r, c0+c).")
    w(".org 0")
    w("start:")
    cases = [(16, 0, 0), (8, 4, 8), (4, ROWS_E0 - 2, 12)]
    descs = [tensormap(SRC, ROWS_E0, COLS_E1, LD * 2, 2, R, 16) for R, _, _ in cases]
    n = 0
    w("    mb.init   b0")
    for i, (R, r0, c0) in enumerate(cases):
        nregs = (16 * R * 2) // 64
        w(f"    // ---- {R} source rows at ({r0}, {c0}) ----")
        w(f"    .li       s1, #{DESC + 0x100 * i}")
        w(f"    td.load   d{i}, [s1]")
        w(f"    w.def     w{i}, #32, #{nregs}")
        for v in range(nregs):
            w(f"    v.movi    v{32 + v}, #-1           // a lane left unwritten shows as ffffffff")
        w("    mb.arm    s3, b0, #0, #1")
        w(f"    .li       s10, #{r0}")
        w(f"    .li       s11, #{c0}")
        w(f"    t.ld.async.h.t w{i}, d{i}, s10, s3")
        w("    mb.wait   s3")
        lanes = expected_window(R, 16, r0, c0)
        for li, val in enumerate(lanes):
            n += 1
            w(f"    .assert_lane v{32 + li // 16}, #{li % 16}, #{val:#010x}, #{n}")
        w(f"    w.release w{i}")
    w("    exit")
    w("")
    emit_data(w, descs)
    return out, n


def fault_prog(name, why, suffix, dtype, b1):
    out = []
    w = out.append
    w(f"// {name} -- generated by gen_t30_xpose.py; do not edit by hand.")
    w(f"// {why}")
    w(".org 0")
    w("start:")
    w("    w.def     w0, #32, #8")
    w(f"    .li       s1, #{DESC}")
    w("    td.load   d0, [s1]")
    w("    mb.init   b0")
    w("    mb.arm    s2, b0, #0, #1")
    w("    .li       s10, #0")
    w("    .li       s11, #0")
    w(f"    t.ld.async.{suffix}.t w0, d0, s10, s2")
    w("    mb.wait   s2")
    w("    trap      #99                     // must be unreachable")
    w("")
    esz = 2 if suffix == 'h' else 4
    emit_data(w, [tensormap(SRC, ROWS_E0, COLS_E1, LD * 2, esz, 16, b1, dtype=dtype)])
    return out


SRC8 = 0xA000
LD8 = 48                 # 1-byte source row stride (bytes)
ROWS8 = 20
COLS8 = 44


def src8(r, c):
    return (r * 13 + c * 3 + 0x11) & 0xff


def emit_data8(w, descs):
    for i, d in enumerate(descs):
        w(f".org {DESC + 0x100 * i:#x}")
        w(f"desc{i}:")
        for x in d:
            w(f"    .dword 0x{x:016x}")
    w(f".org {SRC8:#x}")
    w("src8:")
    for r in range(ROWS8 + 16):
        row = [src8(r, c) if (r < ROWS8 and c < COLS8) else 0 for c in range(LD8)]
        for i in range(0, LD8, 8):
            w(f"    .dword 0x{sum(b << (8 * k) for k, b in enumerate(row[i:i + 8])):016x}")


def t33():
    out = []
    w = out.append
    w("// t33_xpose8 -- generated by gen_t30_xpose.py; do not edit by hand.")
    w("// R41 X8, ISA sec 9E mod[5] with 1-byte elements:")
    w("// window byte (c, r) = source (r0+r, c0+c), zero outside the extents.")
    w(".org 0")
    w("start:")
    # (R source rows, C source columns, r0, c0, dtype code, predicated off)
    cases = [(16, 16, 0, 0, 3, False), (8, 24, 4, 8, 7, False),
             (4, 32, ROWS8 - 2, 24, 8, False), (8, 16, -3, 32, 3, False),
             (16, 8, 2, 40, 7, False), (4, 8, 0, 0, 8, True)]
    descs = [tensormap(SRC8, ROWS8, COLS8, LD8, 1, R, C, dtype=dt)
             for R, C, _, _, dt, _ in cases]
    n = 0
    w("    mb.init   b0")
    w("    p.frombits p1, s0                 // every lane off")
    for i, (R, C, r0, c0, dt, off) in enumerate(cases):
        nregs = (C * R + 63) // 64
        w(f"    // ---- {R} x {C} bytes at ({r0}, {c0}), dtype {dt}{', predicated off' if off else ''} ----")
        w(f"    .li       s1, #{DESC + 0x100 * i}")
        w(f"    td.load   d{i}, [s1]")
        w(f"    w.def     w{i}, #32, #{nregs}")
        for v in range(nregs):
            w(f"    v.movi    v{32 + v}, #-1           // a lane left unwritten shows as ffffffff")
        w("    mb.arm    s3, b0, #0, #1")
        w(f"    .li       s10, #{r0}")
        w(f"    .li       s11, #{c0}")
        w(f"    {'@p1 ' if off else ''}t.ld.async.b.t w{i}, d{i}, s10, s3")
        w("    mb.wait   s3")
        if off:
            lanes = [0xffffffff] * (nregs * 16)
        else:
            bs = []
            for c in range(C):
                for r in range(R):
                    rr, cc = r0 + r, c0 + c
                    bs.append(src8(rr, cc) if 0 <= rr < ROWS8 and cc < COLS8 else 0)
            bs += [0xff] * (nregs * 64 - len(bs))
            lanes = [bs[4 * k] | bs[4 * k + 1] << 8 | bs[4 * k + 2] << 16 | bs[4 * k + 3] << 24
                     for k in range(len(bs) // 4)]
        for li, val in enumerate(lanes):
            n += 1
            w(f"    .assert_lane v{32 + li // 16}, #{li % 16}, #{val:#010x}, #{n}")
        w(f"    w.release w{i}")
    w("    exit")
    w("")
    emit_data8(w, descs)
    return out, n


def fault8(name, why, R, c0):
    out = []
    w = out.append
    w(f"// {name} -- generated by gen_t30_xpose.py; do not edit by hand.")
    w(f"// {why}")
    w(".org 0")
    w("start:")
    w("    w.def     w0, #32, #8")
    w(f"    .li       s1, #{DESC}")
    w("    td.load   d0, [s1]")
    w("    mb.init   b0")
    w("    mb.arm    s2, b0, #0, #1")
    w("    .li       s10, #0")
    w(f"    .li       s11, #{c0}")
    w("    t.ld.async.b.t w0, d0, s10, s2")
    w("    mb.wait   s2")
    w("    trap      #99                     // must be unreachable")
    w("")
    emit_data8(w, [tensormap(SRC8, ROWS8, COLS8, LD8, 1, R, 16, dtype=7)])
    return out


def main():
    prog, n = t30()
    open(os.path.join(HERE, 't30_xpose.s'), 'w').write('\n'.join(prog) + '\n')
    open(os.path.join(HERE, 't31_xpose_illegal.s'), 'w').write('\n'.join(fault_prog(
        't31_xpose_illegal',
        'mod[5] on an engine built without HAS_TENSOR_XPOSE: ILLEGAL_INSTRUCTION.',
        'h', 0, 16)) + '\n')
    open(os.path.join(HERE, 't32_xpose_badsize.s'), 'w').write('\n'.join(fault_prog(
        't32_xpose_badsize',
        'A transposed 4-byte transfer is not implemented: DESCRIPTOR_FAULT.',
        'w', 2, 8)) + '\n')
    prog8, n8 = t33()
    open(os.path.join(HERE, 't33_xpose8.s'), 'w').write('\n'.join(prog8) + '\n')
    for name, why, R, c0 in [
            ('t34_xpose8_old', 'A 1-byte transposed load on a 16-bit-only engine: DESCRIPTOR_FAULT.', 16, 0),
            ('t35_xpose8_badrows', 'A 1-byte transposed load of 12 source rows: DESCRIPTOR_FAULT.', 12, 0),
            ('t36_xpose8_badcol', 'A 1-byte transposed load at contiguous coordinate 4: DESCRIPTOR_FAULT.', 16, 4)]:
        open(os.path.join(HERE, name + '.s'), 'w').write('\n'.join(fault8(name, why, R, c0)) + '\n')
    print(f"wrote t33_xpose8.s ({n8} lane assertions), t34-t36 fault programs")
    print(f"wrote t30_xpose.s ({n} lane assertions), t31_xpose_illegal.s, t32_xpose_badsize.s")


if __name__ == '__main__':
    main()
