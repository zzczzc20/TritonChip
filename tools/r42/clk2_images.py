#!/usr/bin/env python3
"""R42 clk2: image parameter files of the arms of the clock-pipelining study (stand-in `sim` form and kernel `hbm` form).

    issue_images.py [--out-sim DIR] [--out-hbm DIR]

Base: the R41 run-3 image (tools/r42/img_images.py). Each arm changes image parameters:
  s3       FMA_IMPL 465 SHRINK 42 (the shrunk tile with the area FMA/MAC/converter: the tile of the OOC screens `tscr_s3_*`)
  c2_<m>   s3 plus CLKFIX2 = m (tnca_core CLKFIX2 timing pipelining bit field, bits in rtl/core/tnca_core.v)
Nothing here is linked or loaded.
"""
import argparse
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RUN3_SIM = ROOT / 'tools/r42/images/r41_run2_sim.tcl'
RUN3_HBM = ROOT / 'evidence/r41/hbm_bw/g4/run2/image.tcl'
ARMS = {
    's3': {'FMA_IMPL': 465, 'SHRINK': 42},
    'c2_7': {'FMA_IMPL': 465, 'SHRINK': 42, 'CLKFIX2': 7},
    'c2_63': {'FMA_IMPL': 465, 'SHRINK': 42, 'CLKFIX2': 63},
    'c2_127': {'FMA_IMPL': 465, 'SHRINK': 42, 'CLKFIX2': 127},
    # the union of R42-clk (CLKFIX 383: bits 0-6 and 8, the mask of its c383 tile) and R42-clk2: arm A all of mine, arm Z without FP latency
    'u_A': {'FMA_IMPL': 465, 'SHRINK': 42, 'CLKFIX': 383, 'CLKFIX2': 255},
    'u_Z': {'FMA_IMPL': 465, 'SHRINK': 42, 'CLKFIX': 383, 'CLKFIX2': 967},
    # image-level bits of R42-clk2: 10 TMU input registers, 11 fast router (zero cycles); n3 = NOC_LINK_STAGES 3 (the fallback, +1 cycle per hop)
    'b10': {'FMA_IMPL': 465, 'SHRINK': 42, 'CLKFIX2': 1024},
    'b11': {'FMA_IMPL': 465, 'SHRINK': 42, 'CLKFIX2': 2048},
    'b1011': {'FMA_IMPL': 465, 'SHRINK': 42, 'CLKFIX2': 3072},
    'n3': {'FMA_IMPL': 465, 'SHRINK': 42, 'NOC_LINK_STAGES': 3},
    'u_A2': {'FMA_IMPL': 465, 'SHRINK': 42, 'CLKFIX': 383, 'CLKFIX2': 3327},
    'u_Z2': {'FMA_IMPL': 465, 'SHRINK': 42, 'CLKFIX': 383, 'CLKFIX2': 4039},
}


def write(src_text, extra, dest, note):
    m = re.search(r'(set TNCA_IMAGE_PARAMS \[dict create )([^\]]*)(\])', src_text)
    words = m.group(2).split()
    pairs = [[words[i], words[i + 1]] for i in range(0, len(words), 2)]
    for k, v in extra.items():
        for p in pairs:
            if p[0] == k:
                p[1] = str(v)
                break
        else:
            pairs.append([k, str(v)])
    line = m.group(1) + ' '.join(f'{k} {v}' for k, v in pairs) + m.group(3)
    Path(dest).write_text(note + src_text[:m.start()] + line + src_text[m.end():])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--out-sim', default=str(ROOT / 'tools/r42/clk2/images'))
    ap.add_argument('--out-hbm', default=str(ROOT / 'evidence/r42/clk2/images'))
    a = ap.parse_args()
    sim = '\n'.join(l for l in RUN3_SIM.read_text().splitlines() if not l.startswith('# copy of')) + '\n'
    hbm = (RUN3_HBM.read_text() if RUN3_HBM.exists() else
           subprocess.check_output(['git', '-C', str(ROOT), 'show', 'origin/R42:evidence/r41/hbm_bw/g4/run2/image.tcl']).decode())
    for d in (a.out_sim, a.out_hbm):
        Path(d).mkdir(parents=True, exist_ok=True)
    for name, extra in ARMS.items():
        note = f'# R42-clk2 arm {name}: run-3 image with {extra or "no change"}. Generated by tools/r42/clk2_images.py; not linked.\n'
        write(sim, extra, Path(a.out_sim) / f'clk2_{name}_sim.tcl', note)
        write(hbm, extra, Path(a.out_hbm) / f'clk2_{name}.tcl', note)
    print(len(ARMS), 'arms written')


if __name__ == '__main__':
    main()
