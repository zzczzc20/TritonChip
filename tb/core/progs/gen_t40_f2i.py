#!/usr/bin/env python3
"""
Generate tb/core/progs/t40_f2i.s.

vf.cvt.f32.s32 / vf.cvt.f32.u32 (ISA sec 8.4) as a program sees them, in
every rounding mode, at the magnitudes the original t03 never reached:
|x| in [2^23, 2^32), ties at 2^23..2^24, +-2^31, 2^32 - ulp, (-1, 0) and
(0, 1) for unsigned, infinities and NaN. Lanes 0 and 15 are checked
individually as well as by a whole-vector compare, so lane routing is
covered. Expectations come from tools/model/f2i.py (exact Fractions, the
ISA text), not from the RTL.
"""
import os
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..', '..'))
sys.path.insert(0, os.path.join(ROOT, 'tools', 'model'))
from f2i import f32_to_int            # noqa: E402

VLEN = 16
MODES = (('rtz', 0), ('rne', 1), ('rmi', 2), ('rpi', 3))


def f(x):
    return struct.unpack('<I', struct.pack('<f', x))[0]


# Sixteen probes per vector; each vector is run through all eight
# (signedness, mode) conversions.
PROBES = [
    # [2^24, 2^31): converted to 0/+-1 by the old 8-bit shift wrap
    [f(16777216.0), f(-16777218.0), f(33554436.0), f(-1.5e9), f(2147483520.0), f(-2147483520.0),
     f(1e8), f(-1e8), f(123456792.0), f(-987654336.0), 0x4b800001, 0xcb800001,
     f(3e7), f(-3e7), 0x4effffff, 0xceffffff],
    # ties and odd values in [2^23, 2^24): old RNE rounded these up
    [0x4b000001, 0xcb000001, 0x4b000003, 0xcb000003, 0x4b7fffff, 0xcb7fffff,
     f(8388608.5), f(-8388608.5), f(8388609.5), f(-8388609.5), f(12582913.0), f(-12582913.0),
     0x4b000000, 0xcb000000, f(16777215.0), f(-16777215.0)],
    # +-2^31, [2^31, 2^32), 2^32, infinities, NaN
    [f(2147483648.0), f(-2147483648.0), f(3e9), f(-3e9), 0x4f7fffff, 0xcf7fffff,
     f(4294967296.0), f(-4294967296.0), 0x7f800000, 0xff800000, 0x7fc00000, 0xffc00001,
     f(2147483904.0), f(-2147483904.0), f(4e9), f(-1e10)],
    # (-1, 1) incl. +-0.5 ties, subnormals and zeros; small ties
    [f(-0.75), f(-0.5), f(-0.25), 0x80000001, 0x80000000, 0x00000000, 0x00000001, f(0.25),
     f(0.5), f(0.75), f(-1.0), f(1.0), f(-1.5), f(1.5), f(-2.5), f(2.5)],
]

out = []
w = out.append
tid = [0]
data = {}


def nid():
    tid[0] += 1
    return tid[0]


w("// t40_f2i -- generated by gen_t40_f2i.py; do not edit by hand.")
w("// ISA sec 8.4 vf.cvt.f32.s32 / vf.cvt.f32.u32, every rounding mode.")
w("// Expectations from tools/model/f2i.py (exact Fractions, the ISA text).")
w(".org 0")
w("start:")
for k, xs in enumerate(PROBES):
    assert len(xs) == VLEN
    data[f"x{k}"] = xs
    for kind, signed in (('s32', 1), ('u32', 0)):
        for name, mode in MODES:
            ys = [f32_to_int(x, signed, mode) for x in xs]
            label = f"e{k}_{kind}_{name}"
            data[label] = ys
            w(f"    // ---- probes {k}: vf.cvt.f32.{kind}.{name} ----")
            w(f"    .li      s1, #x{k}")
            w("    v.ld.w   v1, [s1, #0]")
            w(f"    vf.cvt.f32.{kind}.{name} v2, v1")
            w(f"    .li      s2, #{label}")
            w("    v.ld.w   v3, [s2, #0]")
            w("    v.cmp.eq p1, v2, v3")
            w("    p.ballot s3, p1")
            w(f"    .assert_eq s3, #0xffff, #{nid()}")
            for lane in (0, 15):
                w(f"    .assert_lane v2, #{lane}, #0x{ys[lane]:08x}, #{nid()}")
    w("")
w("    exit")
w("")
w(".org 0x8000")
for label, vals in data.items():
    w(f"{label}:")
    for i in range(0, len(vals), 8):
        w("    .word " + ", ".join(f"0x{v & 0xffffffff:08x}" for v in vals[i:i + 8]))

path = os.path.join(HERE, 't40_f2i.s')
with open(path, 'w') as fh:
    fh.write("\n".join(out) + "\n")
print(f"{len(out)} lines, {tid[0]} checks -> {path}")
