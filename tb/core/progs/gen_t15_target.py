#!/usr/bin/env python3
"""
Generate tb/core/progs/t15_target.s -- the target description must match silicon.

compiler_overview.md sec 15 C0 requires a target configuration covering RCTX
count, VLEN, register limits, accumulator count, DMA rank, barrier count and
the capability set. A compiler reads those numbers to decide how many barriers
it may allocate and which encodings it may emit; if the file drifts from the
hardware, every kernel it produces is wrong in a way no individual test
catches.

So the numbers are not written here. They are read out of
compiler/targets/tnca-sim-v0.1.json -- itself generated from the RTL
parameters -- and asserted against what the machine reports at run time. The
chain is: RTL parameter -> target file -> this program -> special register.
A break anywhere fails this test.

Only the per-core facts are checked. NUM_CORES is a property of the full mesh,
so tb_tnca_core.v elaborates a single core and reports 1; the mesh count is
checked by the top-level bench instead.
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..', '..'))
TARGET = os.path.join(ROOT, 'compiler', 'targets', 'tnca-sim-v0.1.json')

with open(TARGET) as f:
    t = json.load(f)

CAP_BIT = {
    'vector_fp32': 0, 'sfu': 1, 'gather_scatter': 2,
    'atomics_device': 3, 'atomics_system': 4,
    'matrix_f16': 5, 'matrix_bf16': 6, 'tensor_dma': 7,
    'mbarrier': 8, 'packed_f16': 9, 'cache_hints': 10,
}

cap0 = 0
for name, bit in CAP_BIT.items():
    if t['capabilities'].get(name):
        cap0 |= 1 << bit

# (special register, expected value, what it constrains in the compiler)
CHECKS = [
    ('num_roles', t['num_rctx'],
     'how many Role Contexts a partition may use'),
    ('num_lanes', t['vlen'],
     'the vector width every layout is expressed in'),
    ('num_vregs', t['registers']['vreg_logical_per_rctx'],
     'the largest V index one RCTX may name'),
    ('num_phys_vregs', t['registers']['vreg_physical_total'],
     'the pool a shared window is carved out of'),
    ('num_acc', t['accumulators']['count'],
     'whole-program accumulator allocation'),
    ('num_barriers', t['barriers']['count'],
     'whole-program barrier allocation'),
    ('num_windows', t['windows']['count'],
     'concurrent RF windows, so pipeline depth'),
    ('num_descriptors', t['descriptors']['count'],
     'live tensor descriptors'),
    ('tensor_max_rank', t['dma']['max_rank'],
     'when a descriptor must be flattened or fall back to the LSU'),
    ('cap0', cap0,
     'which encodings may be emitted at all'),
]

out = []
w = out.append
w("// t15_target -- generated by gen_t15_target.py; do not edit by hand.")
w("//")
w(f"// Every value below comes from {os.path.relpath(TARGET, ROOT)},")
w("// which is generated from the RTL parameters. This program asserts the")
w("// machine agrees. A compiler trusts that file; nothing else proves it.")
w(".org 0")
w("start:")

for n, (spec, val, why) in enumerate(CHECKS, start=1):
    w(f"    // {spec}: {why}")
    w(f"    s.rdspecial s1, {spec}")
    w(f"    .assert_eq s1, #{val:#x}, #{n}")
w("")
w("    exit")

path = os.path.join(HERE, 't15_target.s')
open(path, 'w').write('\n'.join(out) + '\n')
print(f"wrote {path}: {len(CHECKS)} target facts checked against the hardware")
