#!/usr/bin/env python3
"""
Generate tb/core/progs/t39_pair.s -- Role Context pairs (R39-12, RPAIR).

Run with +allroles +slice +slicek=1 +pair on a four-context core: contexts 0
and 1 are pair 0, contexts 2 and 3 pair 1. In each pair the even context is
the producer and the odd one the consumer of a K = 64 GEMM, C = A B, through a
two-stage ring of windows -- the shape R39-12's compiler gives a GEMM loop:

  producer: for each k step: wait until the consumer has released the stage
            (generation = uses of that stage so far), arm the stage's `full`
            barrier for two operations, and start the A and B transfers into
            the stage's windows. It never waits for its own transfers.
  consumer: for each k step: wait for the stage's `full` generation, multiply
            the two windows into the accumulator, wait for that, then arm and
            arrive on the stage's `empty` barrier.

The consumer's `m.mma.async` names v32..v63 -- registers it never wrote. It
gets the producer's only because the pair shares a vector base (RPAIR), and
the barriers, descriptors, windows and accumulator it names are the pair's
because RSLICE slices by the pair. Pair p reads its own A and B, so a pair
that reached the other's slice -- or a consumer that read its own registers
-- computes something else, and the per-pair check of C says which.

Expectations come from tools/model/fp32.py's mma_ref, chained over the four
k steps exactly as the matrix unit accumulates them.
"""
import os
import random
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..', '..'))
sys.path.insert(0, os.path.join(ROOT, 'tools', 'model'))
sys.path.insert(0, HERE)
from fp32 import f32_to_f16_bits, mma_ref, f2b   # noqa: E402
from gen_t33_tdesc import Mem, tensormap         # noqa: E402

M = N = 16
K = 64
STEPS = K // 16
PAIRS = 2
DESC = 0xC000             # pair p: A's TensorMap at DESC + 512p, B's at +256
A_BASE = 0xD000           # pair p: A (16 x 64 f16) at A_BASE + 2048p
B_BASE = 0xE000           # pair p: B (64 x 16 f16) at B_BASE + 2048p
CHECK = [(0, 0), (0, 15), (5, 9), (9, 4), (15, 0), (15, 15)]

rng = random.Random(20261010)
A, B, C = [], [], []
for p in range(PAIRS):
    a = [f32_to_f16_bits(rng.randint(-8, 8) / 2.0) for _ in range(M * K)]
    b = [f32_to_f16_bits(rng.randint(-8, 8) / 2.0) for _ in range(K * N)]
    c = [f2b(0.0)] * (M * N)
    for s in range(STEPS):
        ak = [a[r * K + s * 16 + k] for r in range(M) for k in range(16)]
        bk = [b[(s * 16 + k) * N + n] for k in range(16) for n in range(N)]
        c = mma_ref(ak, bk, c, M, N, 16)
    A.append(a)
    B.append(b)
    C.append(c)


def pack64(h):
    """f16 halves -> 64-bit words, little-endian."""
    return [h[4*i] | (h[4*i+1] << 16) | (h[4*i+2] << 32) | (h[4*i+3] << 48)
            for i in range(len(h) // 4)]


out = []
w = out.append
n = [0]


def nid():
    n[0] += 1
    return n[0]


mem = Mem()
for p in range(PAIRS):
    mem.put_words(A_BASE + 2048 * p, pack64(A[p]))
    mem.put_words(B_BASE + 2048 * p, pack64(B[p]))
    mem.put_words(DESC + 512 * p,
                  tensormap(A_BASE + 2048 * p, [M, K], [2 * K, 2], [16, 16], 'f16', 0))
    mem.put_words(DESC + 512 * p + 256,
                  tensormap(B_BASE + 2048 * p, [K, N], [2 * N, 2], [16, 16], 'f16', 0))

# Per stage: windows (A, B) at these registers, and barriers full / empty.
WIN = [(32, 40), (48, 56)]
FULL = [0, 1]
EMPTY = [2, 3]
MMA_BAR = 4

w("// t39_pair -- generated by gen_t39_pair.py; do not edit by hand.")
w("// Two pairs, each a producer and a consumer sharing registers (RPAIR).")
w(".org 0")
w("start:")
w("    s.rdspecial s1, role_id")
w("    s.lshri     s2, s1, #1                 // the pair")
w("    s.andi      s3, s1, #1                 // the role in it")
w("    br.nz       s3, consumer")
w("")
w("producer:")
w("    s.shli      s4, s2, #9")
w(f"    .li         s5, #{DESC}")
w("    s.add       s5, s5, s4")
w("    td.load     d0, [s5]                   // A")
w("    s.addi      s5, s5, #256")
w("    td.load     d1, [s5]                   // B")
for st, (wa, wb) in enumerate(WIN):
    w(f"    w.def       w{2 * st}, #{wa}, #8")
    w(f"    w.def       w{2 * st + 1}, #{wb}, #8")
w("    .li         s20, #0                    // uses of each stage so far")
w("    .li         s21, #0                    // k offset")
w(f"    .li         s22, #{STEPS // 2}")
w("p_loop:")
for st in range(2):
    w(f"    // stage {st}: wait until the consumer released it s20 times")
    w("    s.shli      s6, s20, #16")
    w(f"    s.ori       s6, s6, #{EMPTY[st]}")
    w("    mb.wait     s6")
    w(f"    mb.arm      s7, b{FULL[st]}, #0, #2")
    w("    .li         s10, #0")
    w(f"    s.addi      s11, s21, #{16 * st}")
    w(f"    t.ld.async.h w{2 * st}, d0, s10, s7")
    w(f"    s.addi      s12, s21, #{16 * st}")
    w("    .li         s13, #0")
    w(f"    t.ld.async.h w{2 * st + 1}, d1, s12, s7")
w("    s.addi      s20, s20, #1")
w("    s.addi      s21, s21, #32")
w("    s.addi      s22, s22, #-1")
w("    br.nz       s22, p_loop")
w("    exit")
w("")
w("consumer:")
w("    m.zero      a0")
w("    .li         s20, #0")
w(f"    .li         s22, #{STEPS // 2}")
w("c_loop:")
w("    s.addi      s20, s20, #1               // the generation this trip fills")
for st, (wa, wb) in enumerate(WIN):
    w("    s.shli      s6, s20, #16")
    w(f"    s.ori       s6, s6, #{FULL[st]}")
    w("    mb.wait     s6")
    w(f"    mb.arm      s8, b{MMA_BAR}, #0, #1")
    w(f"    m.mma.async a0, v{wa}, v{wb}, s8")
    w("    mb.wait     s8")
    w(f"    mb.arm      s9, b{EMPTY[st]}, #1, #0")
    w(f"    mb.arrive   b{EMPTY[st]}")
w("    s.addi      s22, s22, #-1")
w("    br.nz       s22, c_loop")
w("    br.nz       s2, check1")
for p in range(PAIRS):
    w(f"check{p}:")
    for row, col in CHECK:
        w(f"    .li         s13, #{row}")
        w("    a.vread     v8, a0, s13")
        w(f"    .assert_lane v8, #{col}, #0x{C[p][row * N + col]:08x}, #{nid()}")
    w("    exit")
w("")
mem.emit(w)

path = os.path.join(HERE, 't39_pair.s')
with open(path, 'w') as fh:
    fh.write("\n".join(out) + "\n")
print(f"{n[0]} checks -> {path}")
