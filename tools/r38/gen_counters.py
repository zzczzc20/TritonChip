#!/usr/bin/env python3
"""Generate rtl/common/tnca_perf_sel.vh and tnca_perf_count.vh from spec/r38/counters.json.

    tools/r38/gen_counters.py           write the include
    tools/r38/gen_counters.py --check   non-zero if the include is stale

The include is the body of the shell's counter read mux. It is generated so
that the index the runtime asks for and the counter the RTL returns come
from the same list.
"""
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
SPEC = ROOT / 'spec' / 'r38' / 'counters.json'
OUT = ROOT / 'rtl' / 'common' / 'tnca_perf_sel.vh'
COUNT = ROOT / 'rtl' / 'common' / 'tnca_perf_count.vh'


def render():
    spec = json.loads(SPEC.read_text())
    counters = sorted(spec['counters'], key=lambda c: c['index'])
    assert [c['index'] for c in counters] == list(range(len(counters))), 'indices must be dense'
    w = spec['sel_width']
    assert len(counters) <= (1 << w)
    lines = [
        '// GENERATED by tools/r38/gen_counters.py from spec/r38/counters.json.',
        '// Do not edit: change the JSON and regenerate.',
        'always @(*) begin',
        '    case (perf_sel)',
    ]
    for c in counters:
        lines.append(f"    {w}'d{c['index']}: perf_rdata = {c['name']};")
    lines += ["    default: perf_rdata = 64'd0;", '    endcase', 'end', '']
    count = '\n'.join([lines[0], lines[1],
                       f'localparam integer PERF_NUM_COUNTERS = {len(counters)};', ''])
    return '\n'.join(lines), count


def main():
    outputs = dict(zip((OUT, COUNT), render()))
    if '--check' in sys.argv:
        bad = [p for p, t in outputs.items() if not p.exists() or p.read_text() != t]
        for p in outputs:
            print(f'{p.relative_to(ROOT)}: {"STALE -- run tools/r38/gen_counters.py" if p in bad else "up to date"}')
        return 1 if bad else 0
    for p, t in outputs.items():
        p.write_text(t)
        print(f'wrote {p.relative_to(ROOT)}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
