#!/usr/bin/env python3
"""
Generate the transposed-transfer tests (ISA sec 9E mod[5], R38 S1-07).

  t30_xpose.s          every lane of the window after `t.ld.async.h.t`, for
                       4, 8 and 16 source rows, with rows and columns past the
                       descriptor's extents. Run on tb_core_xpose.vvp.
  t31_xpose_illegal.s  the same encoding on an engine built without the
                       feature: ILLEGAL_INSTRUCTION (+expectfault=01), not the
                       untransposed transfer it used to perform.
  t32_xpose_badsize.s  a transposed 4-byte transfer, which the engine does
                       not implement: DESCRIPTOR_FAULT (+expectfault=04).

The engine moves bits and never interprets them, so the source holds
distinct 16-bit patterns and the expected window is computed from the
definition: window element (c, r) = source (r0 + r, c0 + c), zero where
either index falls outside the descriptor.
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))

SRC = 0x8000
LD = 24                  # source row stride in elements: 48 bytes
ROWS_E0 = 20             # source extent, rows
COLS_E1 = 20             # source extent, columns
DESC = 0x9000


def src(r, c):
    return 0x1000 + r * 32 + c


def tensormap(base, e0, e1, s0, s1, b0, b1, rank=2, dtype=0, pad=0):
    w = [0] * 32
    w[0] = base
    w[1] = e0
    w[2] = e1
    w[6] = s0
    w[7] = s1
    w[11] = (b1 << 32) | b0
    w[13] = (pad << 48) | (dtype << 40) | (rank << 32)
    return w


def expected_window(R, C, r0, c0):
    halves = []
    for c in range(C):
        for r in range(R):
            rr, cc = r0 + r, c0 + c
            halves.append(src(rr, cc) if rr < ROWS_E0 and cc < COLS_E1 else 0)
    lanes = [halves[2 * i] | (halves[2 * i + 1] << 16) for i in range(len(halves) // 2)]
    return lanes


def emit_data(w, descs):
    words = []
    for r in range(ROWS_E0 + 16):
        row = [src(r, c) if (r < ROWS_E0 and c < COLS_E1) else 0 for c in range(LD)]
        for i in range(0, LD, 4):
            words.append(row[i] | (row[i + 1] << 16) | (row[i + 2] << 32) | (row[i + 3] << 48))
    w(f".org {SRC:#x}")
    w("src:")
    for x in words:
        w(f"    .dword 0x{x:016x}")
    for i, d in enumerate(descs):
        w(f".org {DESC + 0x100 * i:#x}")
        w(f"desc{i}:")
        for x in d:
            w(f"    .dword 0x{x:016x}")


def t30():
    out = []
    w = out.append
    w("// t30_xpose -- generated by gen_t30_xpose.py; do not edit by hand.")
    w("// ISA sec 9E mod[5]: window element (c, r) = source (r0+r, c0+c).")
    w(".org 0")
    w("start:")
    cases = [(16, 0, 0), (8, 4, 8), (4, ROWS_E0 - 2, 12)]
    descs = [tensormap(SRC, ROWS_E0, COLS_E1, LD * 2, 2, R, 16) for R, _, _ in cases]
    n = 0
    w("    mb.init   b0")
    for i, (R, r0, c0) in enumerate(cases):
        nregs = (16 * R * 2) // 64
        w(f"    // ---- {R} source rows at ({r0}, {c0}) ----")
        w(f"    .li       s1, #{DESC + 0x100 * i}")
        w(f"    td.load   d{i}, [s1]")
        w(f"    w.def     w{i}, #32, #{nregs}")
        for v in range(nregs):
            w(f"    v.movi    v{32 + v}, #-1           // a lane left unwritten shows as ffffffff")
        w("    mb.arm    s3, b0, #0, #1")
        w(f"    .li       s10, #{r0}")
        w(f"    .li       s11, #{c0}")
        w(f"    t.ld.async.h.t w{i}, d{i}, s10, s3")
        w("    mb.wait   s3")
        lanes = expected_window(R, 16, r0, c0)
        for li, val in enumerate(lanes):
            n += 1
            w(f"    .assert_lane v{32 + li // 16}, #{li % 16}, #{val:#010x}, #{n}")
        w(f"    w.release w{i}")
    w("    exit")
    w("")
    emit_data(w, descs)
    return out, n


def fault_prog(name, why, suffix, dtype, b1):
    out = []
    w = out.append
    w(f"// {name} -- generated by gen_t30_xpose.py; do not edit by hand.")
    w(f"// {why}")
    w(".org 0")
    w("start:")
    w("    w.def     w0, #32, #8")
    w(f"    .li       s1, #{DESC}")
    w("    td.load   d0, [s1]")
    w("    mb.init   b0")
    w("    mb.arm    s2, b0, #0, #1")
    w("    .li       s10, #0")
    w("    .li       s11, #0")
    w(f"    t.ld.async.{suffix}.t w0, d0, s10, s2")
    w("    mb.wait   s2")
    w("    trap      #99                     // must be unreachable")
    w("")
    esz = 2 if suffix == 'h' else 4
    emit_data(w, [tensormap(SRC, ROWS_E0, COLS_E1, LD * 2, esz, 16, b1, dtype=dtype)])
    return out


def main():
    prog, n = t30()
    open(os.path.join(HERE, 't30_xpose.s'), 'w').write('\n'.join(prog) + '\n')
    open(os.path.join(HERE, 't31_xpose_illegal.s'), 'w').write('\n'.join(fault_prog(
        't31_xpose_illegal',
        'mod[5] on an engine built without HAS_TENSOR_XPOSE: ILLEGAL_INSTRUCTION.',
        'h', 0, 16)) + '\n')
    open(os.path.join(HERE, 't32_xpose_badsize.s'), 'w').write('\n'.join(fault_prog(
        't32_xpose_badsize',
        'A transposed 4-byte transfer is not implemented: DESCRIPTOR_FAULT.',
        'w', 2, 8)) + '\n')
    print(f"wrote t30_xpose.s ({n} lane assertions), t31_xpose_illegal.s, t32_xpose_badsize.s")


if __name__ == '__main__':
    main()
