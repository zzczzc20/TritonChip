#!/usr/bin/env python3
"""R42 issue, step 0: vector-issue microbenchmarks (assembly), one straight-line stream per program.

Each program: a short preamble (three source vectors, scalar operands), then N back-to-back instructions of one
kind, then `exit`.  The probe is measured with `+trace` (one line per instruction in X) by probe_run.py.

  python3 gen_probe.py OUTDIR [N]
"""
import os
import sys

N = int(sys.argv[2]) if len(sys.argv) > 2 else 160
out = sys.argv[1]
os.makedirs(out, exist_ok=True)

PRE = """.org 0
start:
    .li s1, #5
    .li s2, #9
    v.movi v1, #3
    v.movi v2, #4
    v.movi v3, #5
    v.movi v4, #1
    v.movi v5, #1
    v.movi v6, #1
    v.movi v7, #1
    v.movi v8, #1
    v.movi v9, #1
    v.movi v10, #1
    v.movi v11, #1
    v.movi v12, #1
    v.movi v13, #1
    v.movi v14, #1
    v.movi v15, #1
    s.add s20, s1, s2
    s.add s21, s1, s2
    s.add s22, s1, s2
    s.add s23, s1, s2
"""
POST = "    exit\n"

# destinations rotate over v16..v31 (16 registers): no stream result is read back
def dst(i):
    return 16 + (i % 16)


def chain_dst(i, d):
    return 4 + (i % d)   # v4..v4+d-1: d independent chains


progs = {}

def mk(name, f):
    progs[name] = PRE + "".join(f(i) + "\n" for i in range(N)) + POST

# scalar: baseline of one instruction per cycle
mk("sc_add",    lambda i: f"    s.add s{24 + i % 16}, s1, s2")
mk("sc_movi",   lambda i: f"    s.movz s{24 + i % 16}, #{i & 0xff}")
# vector, independent, by number of vector source operands
mk("v0_movi",   lambda i: f"    v.movi v{dst(i)}, #{i & 0x7f}")
mk("v0_iota",   lambda i: f"    v.iota v{dst(i)}")
mk("v1_addi",   lambda i: f"    v.addi v{dst(i)}, v1, #1")
mk("v1_shli",   lambda i: f"    v.shli v{dst(i)}, v1, #2")
mk("v1_splat",  lambda i: f"    v.splat v{dst(i)}, s1")
mk("v2_add",    lambda i: f"    v.add v{dst(i)}, v1, v2")
mk("v2_mul",    lambda i: f"    v.mul v{dst(i)}, v1, v2")
mk("v2_and",    lambda i: f"    v.and v{dst(i)}, v1, v2")
mk("f2_add",    lambda i: f"    vf.add v{dst(i)}, v1, v2")
mk("f2_mul",    lambda i: f"    vf.mul v{dst(i)}, v1, v2")
mk("f3_fma",    lambda i: f"    vf.fma v{dst(i)}, v1, v2, v3")
mk("f1_neg",    lambda i: f"    vf.neg v{dst(i)}, v1")
mk("cvt_f2i",   lambda i: f"    vf.cvt.s32.f32 v{dst(i)}, v1")
mk("shuf_rot",  lambda i: f"    v.rotate v{dst(i)}, v1, s1")
# vector, d independent dependent chains (distance d), integer add: v(4+i%d) += v2
for d in (1, 2, 3, 4, 6):
    mk(f"v2_chain{d}", lambda i, d=d: f"    v.add v{chain_dst(i, d)}, v{chain_dst(i, d)}, v2")
    mk(f"f2_chain{d}", lambda i, d=d: f"    vf.add v{chain_dst(i, d)}, v{chain_dst(i, d)}, v2")
    mk(f"f3_chain{d}", lambda i, d=d: f"    vf.fma v{chain_dst(i, d)}, v1, v2, v{chain_dst(i, d)}")
    mk(f"v1_chain{d}", lambda i, d=d: f"    v.addi v{chain_dst(i, d)}, v{chain_dst(i, d)}, #1")
# mixes: vector instruction alternating with a scalar one, with two vector ones
mk("mix_v2_s", lambda i: (f"    v.add v{dst(i)}, v1, v2" if i % 2 == 0 else f"    s.add s{24 + i % 16}, s1, s2"))
mk("mix_v2_v0", lambda i: (f"    v.add v{dst(i)}, v1, v2" if i % 2 == 0 else f"    v.movi v{dst(i)}, #7"))
mk("mix_v2_v1", lambda i: (f"    v.add v{dst(i)}, v1, v2" if i % 2 == 0 else f"    v.addi v{dst(i)}, v1, #7"))
mk("mix_v3_v0", lambda i: (f"    vf.fma v{dst(i)}, v1, v2, v3" if i % 2 == 0 else f"    v.movi v{dst(i)}, #7"))
# the distance of a producer: the consumer of v(dst) k instructions later (a short pipeline of producer/consumer pairs)
for k in (1, 2, 3):
    # producer, then k-1 independents, then consumer of the producer's register
    def f(i, k=k):
        j = i % (k + 1)
        base = 16 + ((i // (k + 1)) % 8)
        if j == 0:
            return f"    v.add v{base}, v1, v2"
        if j < k:
            return f"    v.movi v{24 + j}, #3"
        return f"    v.addi v{24 + k}, v{base}, #1"
    mk(f"dist{k}_int", f)

for name, text in progs.items():
    with open(os.path.join(out, name + ".s"), "w") as fh:
        fh.write("// R42 issue probe (generated by gen_probe.py): %s, N=%d\n" % (name, N))
        fh.write(text)
print(len(progs), "programs in", out)
