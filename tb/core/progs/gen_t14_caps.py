#!/usr/bin/env python3
"""
Generate tb/core/progs/t14_caps.s -- CAPABILITY0 must describe the hardware.

ISA sec 11: "A capability bit being clear means the corresponding encodings
raise ILLEGAL_INSTRUCTION. It never means 'works, but slowly, by some other
route'." That makes the bitmap a contract the compiler reads to decide what it
may emit (compiler_overview.md sec 12: an absent SFU or absent atomics must
become a capability diagnostic, never a quiet substitution).

Nothing checked that contract in both directions. The transfer engine shipped
in Stage 2b decoding and executing TXFER while CAPABILITY0.TENSOR_DMA still
read 0, so a compiler that honoured the bitmap would have refused to emit a
DMA the hardware performs.

This test pins the bitmap to an exact value, and then executes one instruction
per advertised bit. Reaching `exit` is the assertion: a capability that is
advertised but faults stops the Role Context, and the bench reports it.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))

# Build configuration of tb/core/tb_tnca_core.v.
HAS_SFU = 1

CAP = {
    'VECTOR_FP32': 0, 'SFU': 1, 'GATHER_SCATTER': 2,
    'ATOMICS_DEVICE': 3, 'SYSTEM_ATOMICS': 4,
    'MATRIX_F16': 5, 'MATRIX_BF16': 6, 'TENSOR_DMA': 7,
    'MBARRIER': 8, 'PACKED_F16': 9, 'CACHE_HINTS': 10,
}

# What this build implements. Anything not listed must read 0, and its
# encodings must raise ILLEGAL_INSTRUCTION -- t05_fault covers that direction.
IMPLEMENTED = ['VECTOR_FP32', 'GATHER_SCATTER', 'MATRIX_F16', 'MATRIX_BF16',
               'TENSOR_DMA', 'MBARRIER']
if HAS_SFU:
    IMPLEMENTED.append('SFU')

EXPECT = 0
for name in IMPLEMENTED:
    EXPECT |= 1 << CAP[name]

SRC_BASE  = 0x4000      # 16x16 FP16, every element 1.0
DESC_BASE = 0x5000      # its TensorMap
IDX_BASE  = 0x5200      # gather offsets
VAL_BASE  = 0x5300      # gather payload

ROWS = COLS = 16
HALF_ONE = 0x3C00       # FP16 1.0
LANE_ONE = (HALF_ONE << 16) | HALF_ONE


def GVAL(lane):
    """The word lane `lane` gathers: a distinct value per lane."""
    return 0x11111100 | lane


def tensormap(base, e0, e1, s0, s1, b0, b1, rank=2, dtype=0, pad=0):
    """The 256-byte layout of ISA sec 9D.3, as 32 little-endian 64-bit words."""
    words = [0] * 32
    words[0] = base
    words[1] = e0
    words[2] = e1
    words[6] = s0
    words[7] = s1
    words[11] = (b1 << 32) | b0
    words[13] = (pad << 48) | (dtype << 40) | (rank << 32)
    return words


out = []
w = out.append

w("// t14_caps -- generated by gen_t14_caps.py; do not edit by hand.")
w("//")
w("// CAPABILITY0 is a contract, not a comment: a clear bit promises the")
w("// encoding raises ILLEGAL_INSTRUCTION (ISA sec 11). Every bit set below is")
w("// exercised, so the bitmap cannot drift away from the decoder again.")
w(".org 0")
w("start:")
w("    s.rdspecial s1, cap0")
w(f"    .assert_eq s1, #{EXPECT:#x}, #1        // bits: {', '.join(IMPLEMENTED)}")
w("")

n = 2

# ---- bit 0: VECTOR_FP32 ---------------------------------------------------
w("    // bit 0 VECTOR_FP32 -- a native FP32 vector datapath")
w("    .li       s2, #0x3f800000            // 1.0f")
w("    v.splat   v1, s2")
w("    vf.add    v2, v1, v1")
w(f"    .assert_lane v2, #0, #0x40000000, #{n}")
n += 1
w("")

# ---- bit 1: SFU -----------------------------------------------------------
if HAS_SFU:
    w("    // bit 1 SFU -- a native approximate datapath, not a library call")
    w("    .li       s2, #0x40800000            // 4.0f")
    w("    v.splat   v1, s2")
    w("    v.rsqrt.approx v2, v1")
    # 0.5 is representable and sec 8.8's band around it contains no other
    # binary32, so this one lane can be asserted exactly.
    w(f"    .assert_lane v2, #0, #0x3f000000, #{n}")
    n += 1
    w("")

# ---- bit 2: GATHER_SCATTER ------------------------------------------------
w("    // bit 2 GATHER_SCATTER -- native per-lane addressing")
w(f"    .li       s3, #{IDX_BASE}")
w("    v.ld.w    v3, [s3, #0]              // element indices, one per lane")
w(f"    .li       s4, #{VAL_BASE}")
w("    v.ld.gather.w v4, [s4, v3]")
w(f"    .assert_lane v4, #0, #{GVAL(0):#x}, #{n}")
n += 1
w(f"    .assert_lane v4, #15, #{GVAL(15):#x}, #{n}")
n += 1
w("")

# ---- bits 5/6: MATRIX_F16 / MATRIX_BF16 -----------------------------------
w("    // bits 5,6 MATRIX_* -- the accumulator file backing m.mma")
w("    m.zero    a0")
w("    .li       s5, #0")
w("    a.vread   v5, a0, s5")
w(f"    .assert_lane v5, #0, #0, #{n}")
n += 1
w("")

# ---- bits 7/8: TENSOR_DMA / MBARRIER --------------------------------------
w("    // bits 7,8 TENSOR_DMA + MBARRIER -- the pair that was mis-advertised.")
w("    // The window is pre-filled with a value the source cannot produce, so")
w("    // a transfer that silently did nothing would fail the lane checks.")
w("    v.movi    v32, #-1")
w("    v.movi    v39, #-1")
w("    w.def     w0, #32, #8               // v32..v39 holds a 16x16 FP16 tile")
w(f"    .li       s6, #{DESC_BASE}")
w("    td.load   d0, [s6]")
w("    mb.init   b0")
w("    mb.arm    s7, b0, #0, #1")
w("    .li       s10, #0                   // coord0")
w("    .li       s11, #0                   // coord1 (consecutive registers)")
w("    t.ld.async.h w0, d0, s10, s7")
w("    mb.wait   s7")
w(f"    .assert_lane v32, #0,  #{LANE_ONE:#x}, #{n}")
n += 1
w(f"    .assert_lane v32, #15, #{LANE_ONE:#x}, #{n}")
n += 1
w(f"    .assert_lane v39, #15, #{LANE_ONE:#x}, #{n}")
n += 1
w("")
w("    exit")
w("")


def emit_words(addr, words, label):
    w(f".org {addr:#x}")
    w(f"{label}:")
    for word in words:
        w(f"    .dword 0x{word & ((1 << 64) - 1):016x}")
    w("")


# 16x16 FP16, every element 1.0 -- 512 bytes.
emit_words(SRC_BASE, [((HALF_ONE << 48) | (HALF_ONE << 32) |
                       (HALF_ONE << 16) | HALF_ONE)] * (ROWS * COLS // 4),
           "src")

emit_words(DESC_BASE,
           tensormap(SRC_BASE, ROWS, COLS, COLS * 2, 2, ROWS, COLS),
           "desc")

# Gather scales its index by the access size (ISA sec 9.1:
# lane i => Sa + sext(Vb[i]) * sz), so these are element indices, not bytes.
emit_words(IDX_BASE, [((2 * k + 1) << 32) | (2 * k) for k in range(8)], "idx")
emit_words(VAL_BASE, [(GVAL(2 * k + 1) << 32) | GVAL(2 * k)
                      for k in range(8)], "vals")

path = os.path.join(HERE, 't14_caps.s')
open(path, 'w').write('\n'.join(out) + '\n')
print(f"wrote {path}: CAPABILITY0 expected {EXPECT:#x}")
