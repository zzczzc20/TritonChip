#!/usr/bin/env python3
"""R42 issue: random vector/scalar programs for the lockstep of a core parameter against the shipped core.

  python3 lockstep_gen.py OUTDIR COUNT [SEED0]

Each program loads vectors from a data block, runs a random mix (integer, FP, convert, SFU, shuffle, reduction,
predicated and lane-masked forms, loads and stores, short counted loops, dependent chains of random distance),
stores every vector register it used and exits. Programs are race free when several contexts run them (every
context computes and stores the same values to the same words). lockstep_run.py compares the memory image and the
cycle counts of two builds.
"""
import os
import random
import sys

out, count = sys.argv[1], int(sys.argv[2])
seed0 = int(sys.argv[3]) if len(sys.argv) > 3 else 1
os.makedirs(out, exist_ok=True)

DATA, RES = 0x1000, 0x2000
NV = 20                       # vector registers v1..v20
INT2 = ["v.add", "v.sub", "v.mul", "v.and", "v.or", "v.xor", "v.min.s", "v.max.u", "v.shl", "v.lshr"]
INT1I = ["v.addi", "v.subi", "v.andi", "v.xori", "v.shli", "v.lshri"]
FP2 = ["vf.add", "vf.sub", "vf.mul", "vf.min", "vf.max"]
CC = ["lt", "le", "eq", "ne", "ge", "gt"]


def gen(seed):
    r = random.Random(seed)
    L = []
    w = L.append
    recent = []

    def pick(k=1):
        """a source register: usually a recent destination (dependence of distance 1..4), else any initialised one"""
        if recent and r.random() < 0.65:
            d = min(len(recent), r.choice([1, 1, 1, 2, 2, 3, 4]))
            return recent[-d]
        return r.randint(1, NV)

    def dst():
        d = r.randint(5, NV)
        recent.append(d)
        if len(recent) > 8:
            recent.pop(0)
        return d

    def mask():
        t = r.random()
        if t < 0.25:
            return "@p%d " % r.randint(1, 3)
        if t < 0.35:
            return "@!p%d " % r.randint(1, 3)
        return ""

    w("// R42 issue lockstep program, seed %d (generated by lockstep_gen.py)" % seed)
    w(".org 0")
    w("start:")
    w("    .li s1, #%d" % DATA)
    w("    .li s2, #%d" % RES)
    for i in range(1, 5):
        w("    v.ld.w v%d, [s1, #%d]" % (i, 64 * (i - 1)))
    for i in range(5, NV + 1):
        w("    v.movi v%d, #%d" % (i, r.randint(-100, 100)))
    for p in (1, 2, 3):
        w("    v.cmp.lt p%d, v%d, v%d" % (p, r.randint(1, 4), r.randint(1, 4)) if False else
          "    v.cmpi.lt p%d, v%d, #%d" % (p, r.randint(1, 4), r.randint(-50, 50)))
    w("    .li s5, #3")
    w("    .li s6, #5")
    nstore = 0
    n = r.randint(60, 140)
    i = 0
    while i < n:
        t = r.random()
        if t < 0.28:
            op = r.choice(INT2)
            w("    %s%s v%d, v%d, v%d" % (mask(), op, dst(), pick(), pick()))
        elif t < 0.38:
            op = r.choice(INT1I)
            w("    %s%s v%d, v%d, #%d" % (mask(), op, dst(), pick(), r.randint(0, 15)))
        elif t < 0.55:
            op = r.choice(FP2)
            w("    %s%s v%d, v%d, v%d" % (mask(), op, dst(), pick(), pick()))
        elif t < 0.63:
            w("    %svf.fma v%d, v%d, v%d, v%d" % (mask(), dst(), pick(), pick(), pick()))
        elif t < 0.67:
            w("    %svf.neg v%d, v%d" % (mask(), dst(), pick()))
        elif t < 0.70:
            w("    %svf.cvt.f32.s32 v%d, v%d" % (mask(), dst(), pick()))
        elif t < 0.73:
            w("    %svf.cvt.s32.f32 v%d, v%d" % (mask(), dst(), pick()))
        elif t < 0.75:
            w("    v.exp2.approx v%d, v%d" % (dst(), pick()))
        elif t < 0.78:
            w("    %sv.rotate v%d, v%d, s%d" % (mask(), dst(), pick(), r.choice([5, 6])))
        elif t < 0.82:
            w("    v.cmp.%s p%d, v%d, v%d" % (r.choice(CC), r.randint(1, 3), pick(), pick()))
        elif t < 0.86:
            w("    %sv.ld.w v%d, [s1, #%d]" % (mask(), dst(), 64 * r.randint(0, 15)))
        elif t < 0.90 and nstore < 24:
            w("    %sv.st.w [s2, #%d], v%d" % (mask(), 64 * (24 + nstore), pick()))
            nstore += 1
        elif t < 0.93:
            w("    %sv.reduce.add s7, v%d" % (mask(), pick()))
            w("    v.splat v%d, s7" % dst())
        elif t < 0.96:
            w("    s.add s5, s5, s6")
            w("    v.splat v%d, s5" % dst())
        elif t < 0.98 and i < n - 12:
            # a short counted loop around a few dependent instructions
            cnt = r.randint(2, 5)
            w("    .li s8, #%d" % cnt)
            lab = "L%d_%d" % (seed, i)
            w("%s:" % lab)
            for _ in range(r.randint(1, 4)):
                op = r.choice(INT2 + FP2)
                w("    %s v%d, v%d, v%d" % (op, dst(), pick(), pick()))
            w("    s.subi s8, s8, #1")
            w("    br.nz s8, %s" % lab)
        else:
            w("    v.movi v%d, #%d" % (dst(), r.randint(-9, 9)))
        i += 1
    # every vector register to the result area
    for v in range(1, NV + 1):
        w("    v.st.w [s2, #%d], v%d" % (64 * (v - 1), v))
    w("    exit")
    # data block: random words (some special FP patterns)
    w(".org %d" % DATA)
    specials = [0x3f800000, 0x40000000, 0xbf800000, 0x00000000, 0x7fc00000, 0x7f800000, 0x00800000, 0x80000000, 0x3f000000]
    for k in range(16 * 16):
        v = r.choice(specials) if r.random() < 0.3 else r.getrandbits(32)
        w("    .word 0x%08x" % v)
    return "\n".join(L) + "\n"


for k in range(count):
    open(os.path.join(out, "ls%04d.s" % (seed0 + k)), "w").write(gen(seed0 + k))
print(count, "programs in", out)
