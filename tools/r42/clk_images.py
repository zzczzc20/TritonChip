#!/usr/bin/env python3
"""R42 clk: image parameter files of the CLKFIX arms (stand-in `sim` form and kernel `hbm` form), the same way as tools/r42/issue_images.py.

    clk_images.py [--out-sim DIR] [--out-hbm DIR]

Base: the R41 run-3 image. Each arm sets image parameters; CLKFIX is the bit field of tnca_core / tnca_tile (see rtl/core/tnca_core.v). Nothing here is linked or loaded.
"""
import argparse
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / 'tools/r42'))
import issue_images as ii  # noqa: E402

ARMS = {
    'base': {},
    'pick': {'CLKFIX': 1},
    'c7': {'CLKFIX': 7},
    'c0': {'CLKFIX': 0},
    's2': {'CLKFIX': 16},
    'c23': {'CLKFIX': 23},
    'idle': {'CLKFIX': 128},
}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--out-sim', default=str(ROOT / 'tools/r42/clk/images'))
    ap.add_argument('--out-hbm', default=str(ROOT / 'evidence/r42/clk/images'))
    ap.add_argument('--arms', default=','.join(ARMS))
    ap.add_argument('--extra', default='', help='extra image parameters for every arm, NAME=VALUE,NAME=VALUE (e.g. the shrink parameters of the tile screens)')
    a = ap.parse_args()
    extra_all = {kv.split('=')[0]: kv.split('=')[1] for kv in a.extra.split(',') if kv}
    sim = '\n'.join(l for l in ii.RUN3_SIM.read_text().splitlines() if not l.startswith('# copy of')) + '\n'
    hbm = (ii.RUN3_HBM.read_text() if ii.RUN3_HBM.exists() else
           subprocess.check_output(['git', '-C', str(ROOT), 'show', 'origin/R42:evidence/r41/hbm_bw/g4/run2/image.tcl']).decode())
    for d in (a.out_sim, a.out_hbm):
        Path(d).mkdir(parents=True, exist_ok=True)
    names = a.arms.split(',')
    for name in names:
        extra = dict(extra_all)
        extra.update(ARMS[name])
        note = f'# R42-clk arm {name}: run-3 image with {extra or "no change"}. Generated by tools/r42/clk_images.py; not linked.\n'
        ii.write(sim, extra, Path(a.out_sim) / f'clk_{name}_sim.tcl', note)
        ii.write(hbm, extra, Path(a.out_hbm) / f'clk_{name}.tcl', note)
    print(len(names), 'arms written')


if __name__ == '__main__':
    main()
