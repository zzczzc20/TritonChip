#!/usr/bin/env python3
"""R42 issue: image parameter files of the arms of the issue/capacity study (stand-in `sim` form and kernel `hbm` form).

    issue_images.py [--out-sim DIR] [--out-hbm DIR]

Base: the R41 run-3 image (tools/r42/img_images.py). Each arm changes image parameters:
  VRF_FWD 1                  writeback-to-R operand forwarding (tnca_core VRF_FWD)
  SETS 128 SET_W 7 SHRINK 10 NUCA slice with 128 sets x 8 ways = 64 KiB in URAM (shrink DATA_RAM 2, AUX_RAM 2)
  SETS 128 SET_W 7 SHRINK 42 the same plus the VRF response crossbar XBAR 2 (area only, no cycle effect)
  TENSOR_TAG_W 5             32 word-walk tags in the line engine (16 transfer slots; the port tag allows at most 5 with 64 line slots)
  TENSOR_TAG_W 6, LINE_SLOTS 128   64 tags (32 transfer slots, the model's te32): the port tag must then be 9 bits, i.e. 128 LSU line slots
  TENSOR_LINE_HALF 1, MAC_F32 1   the R42-img items L and F
Nothing here is linked or loaded.
"""
import argparse
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RUN3_SIM = ROOT / 'tools/r42/images/r41_run2_sim.tcl'
RUN3_HBM = ROOT / 'evidence/r41/hbm_bw/g4/run2/image.tcl'
ARMS = {
    'base': {},
    'fwd': {'VRF_FWD': 1},
    's128': {'SETS': 128, 'SET_W': 7, 'SHRINK': 10},
    's128x': {'SETS': 128, 'SET_W': 7, 'SHRINK': 42},
    'te5': {'TENSOR_TAG_W': 5},
    'te6': {'TENSOR_TAG_W': 6, 'LINE_SLOTS': 128},
    'lf': {'TENSOR_LINE_HALF': 1, 'MAC_F32': 1},
    'lf_fwd': {'TENSOR_LINE_HALF': 1, 'MAC_F32': 1, 'VRF_FWD': 1},
    'lf_fwd_s128': {'TENSOR_LINE_HALF': 1, 'MAC_F32': 1, 'VRF_FWD': 1, 'SETS': 128, 'SET_W': 7, 'SHRINK': 42},
    'lf_fwd_s128_te5': {'TENSOR_LINE_HALF': 1, 'MAC_F32': 1, 'VRF_FWD': 1, 'SETS': 128, 'SET_W': 7, 'SHRINK': 42, 'TENSOR_TAG_W': 5},
    'lf_s128': {'TENSOR_LINE_HALF': 1, 'MAC_F32': 1, 'SETS': 128, 'SET_W': 7, 'SHRINK': 42},
}


def write(src_text, extra, dest, note):
    m = re.search(r'(set TNCA_IMAGE_PARAMS \[dict create )([^\]]*)(\])', src_text)
    words = m.group(2).split()
    pairs = [[words[i], words[i + 1]] for i in range(0, len(words), 2)]
    for k, v in extra.items():
        for p in pairs:
            if p[0] == k:
                p[1] = str(v)
                break
        else:
            pairs.append([k, str(v)])
    line = m.group(1) + ' '.join(f'{k} {v}' for k, v in pairs) + m.group(3)
    Path(dest).write_text(note + src_text[:m.start()] + line + src_text[m.end():])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--out-sim', default=str(ROOT / 'tools/r42/issue/images'))
    ap.add_argument('--out-hbm', default=str(ROOT / 'evidence/r42/issue/images'))
    a = ap.parse_args()
    sim = '\n'.join(l for l in RUN3_SIM.read_text().splitlines() if not l.startswith('# copy of')) + '\n'
    hbm = (RUN3_HBM.read_text() if RUN3_HBM.exists() else
           subprocess.check_output(['git', '-C', str(ROOT), 'show', 'origin/R42:evidence/r41/hbm_bw/g4/run2/image.tcl']).decode())
    for d in (a.out_sim, a.out_hbm):
        Path(d).mkdir(parents=True, exist_ok=True)
    for name, extra in ARMS.items():
        note = f'# R42-issue arm {name}: run-3 image with {extra or "no change"}. Generated by tools/r42/issue_images.py; not linked.\n'
        write(sim, extra, Path(a.out_sim) / f'issue_{name}_sim.tcl', note)
        write(hbm, extra, Path(a.out_hbm) / f'issue_{name}.tcl', note)
    print(len(ARMS), 'arms written')


if __name__ == '__main__':
    main()
