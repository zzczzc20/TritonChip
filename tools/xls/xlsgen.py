#!/usr/bin/env python3
"""
xlsgen.py -- generate RTL from the DSLX sources in xls/ with Google XLS.

Why a driver rather than a Makefile rule: XLS publishes binaries for
linux-x64 only, and this project is developed on macOS arm64, so the
generator runs on a remote host while everything else -- simulation with
iverilog, synthesis with yosys, the whole regression -- runs locally against
the *generated* Verilog, which is checked in.

That is the important structural point. XLS is a build-time dependency of the
RTL, not a runtime dependency of the project. Someone who clones this repo
can simulate and synthesise every generated module without XLS anywhere in
sight; they need it only to change a .x file.

  xlsgen.py            regenerate every module in config.json
  xlsgen.py --check    fail if any checked-in file differs from a fresh run
  xlsgen.py --list     show the module table
  xlsgen.py --report   measure what the pipelining bought, in asap7 ps
"""
import argparse
import hashlib
import json
import os
import shlex
import shutil
import subprocess
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                    '..', '..'))
CONFIG = os.path.join(ROOT, 'tools', 'xls', 'config.json')
DSLX_DIR = os.path.join(ROOT, 'xls')
OUT_DIR = os.path.join(ROOT, 'rtl', 'gen')

BANNER = """//==============================================================================
// GENERATED by Google XLS from {src} (top: {top}).
// DO NOT EDIT. Regenerate with `make xls`; see doc/xls.md.
//
// XLS version: {version}
// Pipeline:    {pipeline}
// DSLX sha256: {digest}
//==============================================================================
"""


def load_config():
    with open(CONFIG) as f:
        return json.load(f)


# ---------------------------------------------------------------------------
# Where the XLS binaries run.
#
# R1-09 is explicit: "不能依赖个人 SSH、私钥或远程 `cur` 目录". The remote
# runner below is a development convenience -- XLS publishes linux-x64
# binaries and this is developed on macOS arm64 -- and it is not an
# acceptance path. An acceptance environment IS linux-x64, so it runs the
# same binaries locally, from a release fetched by checksum
# (tools/xls/fetch_xls.sh) into a directory of its own.
#
# `R1_STRICT=1` refuses the remote runner outright rather than quietly using
# it: a personal SSH host is not a locked runner, and a generation step that
# silently fell back to one would make `make r1-check-generated` a check
# against somebody's home directory.
# ---------------------------------------------------------------------------

class LocalRunner:
    """XLS binaries on this machine."""

    kind = 'local'

    def __init__(self, xls_dir, workdir):
        self.xls = xls_dir
        self.workdir = workdir

    def prepare(self):
        os.makedirs(self.workdir, exist_ok=True)
        srcs = [os.path.join(DSLX_DIR, f) for f in sorted(os.listdir(DSLX_DIR))
                if f.endswith('.x')]
        for src in srcs:
            dst = os.path.join(self.workdir, os.path.basename(src))
            if os.path.abspath(src) != os.path.abspath(dst):
                shutil.copy2(src, dst)
        return srcs

    def run(self, script, *, capture=True):
        p = subprocess.run(['bash', '-s'], input=script, text=True,
                           capture_output=capture, cwd=self.workdir)
        if p.returncode != 0:
            raise SystemExit(f"XLS step failed:\n{p.stderr or p.stdout}")
        return p.stdout

    def describe(self):
        return f"local XLS at {self.xls}"


class RemoteRunner:
    """XLS binaries on another machine, over ssh. Development only."""

    kind = 'remote'

    def __init__(self, cfg):
        self.cfg = cfg
        r = cfg['remote']
        self.xls = r['xls']
        self.workdir = r['workdir']

    def prepare(self):
        return push_sources(self.cfg)

    def run(self, script, *, capture=True):
        return run_remote(self.cfg, script, capture=capture)

    def describe(self):
        r = self.cfg['remote']
        return f"remote XLS at {r['user']}@{r['host']}:{r['xls']}"


def find_local_xls(cfg):
    """An XLS install on this machine, in the order the contract prefers.

    Explicit environment variable, then the config's own local directory,
    then the default fetch destination. A directory only counts if the tools
    are actually in it -- an empty directory named `xls` has fooled a build
    before.
    """
    candidates = [os.environ.get('XLS_HOME'),
                  (cfg.get('local') or {}).get('xls_dir'),
                  os.path.join(ROOT, '.xls', 'cur')]
    for c in candidates:
        if not c:
            continue
        c = os.path.abspath(os.path.expanduser(c))
        if all(os.path.exists(os.path.join(c, t))
               for t in ('ir_converter_main', 'opt_main', 'codegen_main')):
            return c
    return None


def make_runner(cfg):
    local = find_local_xls(cfg)
    strict = os.environ.get('R1_STRICT') == '1'
    if local:
        wd = (cfg.get('local') or {}).get('workdir') or \
            os.path.join(ROOT, 'sim', 'build', 'xls')
        return LocalRunner(local, os.path.abspath(os.path.expanduser(wd)))
    if strict:
        raise SystemExit(
            "no local XLS install, and R1_STRICT=1 refuses the ssh runner.\n"
            "R1-09: a personal SSH host, a private key and a remote `cur`\n"
            "directory are not a locked generator. Fetch the pinned release:\n"
            "  tools/xls/fetch_xls.sh\n"
            "or point XLS_HOME at an existing install.")
    if 'remote' not in cfg:
        raise SystemExit("no local XLS install and no remote configured")
    return RemoteRunner(cfg)


def remote(cfg):
    r = cfg['remote']
    base = ['ssh', '-o', 'ConnectTimeout=20', '-o', 'BatchMode=yes']
    if r.get('identity'):
        base += ['-i', os.path.expanduser(r['identity'])]
    return base + [f"{r['user']}@{r['host']}"]


def run_remote(cfg, script, *, capture=True):
    cmd = remote(cfg) + ['bash -s']
    p = subprocess.run(cmd, input=script, text=True,
                       capture_output=capture)
    if p.returncode != 0:
        raise SystemExit(f"remote step failed:\n{p.stderr or p.stdout}")
    return p.stdout


def digest_of(path):
    with open(path, 'rb') as f:
        return hashlib.sha256(f.read()).hexdigest()[:16]


def push_sources(cfg):
    """Copy the DSLX sources to the generator host."""
    r = cfg['remote']
    dest = f"{r['user']}@{r['host']}:{r['workdir']}/"
    scp = ['scp', '-q', '-o', 'ConnectTimeout=20', '-o', 'BatchMode=yes']
    if r.get('identity'):
        scp += ['-i', os.path.expanduser(r['identity'])]
    run_remote(cfg, f"mkdir -p {shlex.quote(r['workdir'])}\n")
    srcs = [os.path.join(DSLX_DIR, f) for f in sorted(os.listdir(DSLX_DIR))
            if f.endswith('.x')]
    subprocess.run(scp + srcs + [dest], check=True)
    return srcs


def xls_version(runner):
    return runner.run(f"{runner.xls}/interpreter_main "
                      "--version 2>&1 | head -1\n").strip()


def generate(cfg, runner, mod, version):
    """Run the DSLX -> IR -> opt -> Verilog chain for one module."""
    x, wd = runner.xls, runner.workdir
    name = mod['module']
    stages = mod.get('pipeline_stages', 0)
    # A module may set its own period, or null for none: then XLS schedules
    # the given stage count at the shortest period it allows.
    period = mod['clock_period_ps'] if 'clock_period_ps' in mod else cfg.get('clock_period_ps')

    # Plain Verilog, not SystemVerilog. XLS defaults to SystemVerilog and
    # emits unpacked-array literals for its lookup tables; iverilog aborts on
    # those with an internal assertion, and this project simulates with
    # iverilog and synthesises with yosys. Verilog-2005 is what both are
    # happiest with, and nothing here needs the extra syntax.
    common = "--use_system_verilog=false"

    if stages:
        # Both the stage count and the period: the stage count fixes the
        # latency the core has to schedule around, and the period is what the
        # scheduler balances the stages against. With only the stage count it
        # would equalise node counts, which is not the same thing.
        model = mod.get('delay_model', 'unit')
        # flop_outputs: false for a unit whose consumer registers the result
        # anyway (the FMA: the writeback mux and the accumulator write), so
        # its last stage feeds that register directly, as the hand-written
        # pipeline's did. N stages are then N-1 registers.
        flop_out = mod.get('flop_outputs', True)
        gen = (f"--generator=pipeline --pipeline_stages={stages} "
               f"--delay_model={model} "
               + (f"--clock_period_ps={period} " if period else "")
               + f"--reset=rst --reset_active_low=false "
               f"--flop_inputs=false --flop_outputs={'true' if flop_out else 'false'}")
        pipeline = (f"{stages} stages, {model}"
                    + (f", {period} ps target" if period else "")
                    + (f" (latency {stages - 1} cycles: --flop_inputs=false)" if flop_out
                       else f" ({stages - 1} registers: --flop_inputs=false --flop_outputs=false;"
                            f" the result is combinational from the last stage)"))
    else:
        gen = "--generator=combinational"
        pipeline = "combinational"

    script = f"""set -e
cd {shlex.quote(wd)}
{x}/ir_converter_main --dslx_stdlib_path={x}/xls/dslx/stdlib \\
    --top={mod['top']} {mod['source']} > {name}.ir
{x}/opt_main {name}.ir > {name}.opt.ir
{x}/codegen_main {gen} {common} --top={mod['top']} --module_name={name} \\
    --output_verilog_path={name}.v {name}.opt.ir
# Report the optimiser's effect: this is the evidence that XLS is doing
# something, not merely transcribing.
echo "STATS {name} $(grep -c '^ ' {name}.ir) $(grep -c '^ ' {name}.opt.ir)"
cat {name}.v
"""
    out = runner.run(script)
    stats, verilog = None, []
    for line in out.splitlines():
        if line.startswith('STATS '):
            stats = line.split()[1:]
        else:
            verilog.append(line)
    return '\n'.join(verilog).rstrip('\n') + '\n', stats, pipeline


REPORT_DOC = """
What this measures
------------------
For each module, the shortest clock period XLS can schedule it at, in
picoseconds under the asap7 delay model, at one stage (purely combinational)
and at the stage count config.json asks for. The ratio is the frequency the
pipelining bought.

`floor` is the shortest period any schedule could reach: XLS never splits a
single IR node across stages, so the widest multiply in the module sets it.
A module whose configured period already equals its floor has nothing left to
win from more stages -- the only way down is narrower arithmetic.

These are the generator's own numbers against a real 7 nm model, and they are
independent of the yosys gate-level proxy in doc/synthesis.md, which has no
PDK and maps every adder to ripple carry.
"""


def report(cfg, runner, only=None):
    """Binary-search the shortest feasible clock period per stage count."""
    x, wd = runner.xls, runner.workdir
    mods = [m for m in cfg['modules'] if not only or m['module'] == only]

    # One remote script for everything: a round trip per probe would be
    # hundreds of ssh connections.
    target = cfg.get('clock_period_ps')
    lines = [f"cd {shlex.quote(wd)}"]
    lines.append("""
try_period() {   # module stages period -> 0 if schedulable
  %s/codegen_main --generator=pipeline --delay_model=asap7 \
      --pipeline_stages=$2 --clock_period_ps=$3 \
      --reset=rst --reset_active_low=false \
      --flop_inputs=false --flop_outputs=true --use_system_verilog=false \
      --module_name=probe --output_verilog_path=/dev/null \
      $1.opt.ir >/dev/null 2>&1
}
min_period() {   # module stages -> shortest feasible period, or - if none
  local lo=1 hi=40000 mid
  if ! try_period $1 $2 $hi; then echo -; return; fi
  while [ $((hi - lo)) -gt 8 ]; do
    mid=$(((lo + hi) / 2))
    if try_period $1 $2 $mid; then hi=$mid; else lo=$mid; fi
  done
  echo $hi
}
floor_period() { # module -> shortest period at any stage count
  %s/codegen_main --generator=pipeline --delay_model=asap7 \
      --clock_period_ps=1 --module_name=probe \
      --output_verilog_path=/dev/null $1.opt.ir 2>&1 \
      | grep -o 'clock_period_ps=[0-9]*' | head -1 | cut -d= -f2
}
""" % (x, x))
    for m in mods:
        name, st = m['module'], m.get('pipeline_stages', 0) or 1
        # Rebuild the IR so --report works on a host that has never run a
        # generate, and so it can never read a stale optimisation.
        lines.append(
            f"{x}/ir_converter_main --dslx_stdlib_path={x}/xls/dslx/stdlib "
            f"--top={m['top']} {m['source']} > {name}.ir")
        lines.append(f"{x}/opt_main {name}.ir > {name}.opt.ir")
        lines.append(f'echo "ROW {name} {st} $(min_period {name} 1) '
                     f'$(min_period {name} {st}) $(floor_period {name})"')
    out = runner.run('\n'.join(lines))

    print(REPORT_DOC)
    if target:
        print(f"  Target: {target} ps under asap7.\n")
    print(f"  {'module':<24s} {'stages':>6s} {'comb ps':>9s} "
          f"{'piped ps':>9s} {'speedup':>8s} {'floor ps':>9s}")
    for line in out.splitlines():
        if not line.startswith('ROW '):
            continue
        name, st, comb, piped, floor = line.split()[1:6]
        try:
            speed = f"{int(comb) / int(piped):.2f}x"
        except (ValueError, ZeroDivisionError):
            speed = "-"
        print(f"  {name:<24s} {st:>6s} {comb:>9s} {piped:>9s} "
              f"{speed:>8s} {floor:>9s}")
    return 0


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--check', action='store_true')
    ap.add_argument('--list', action='store_true')
    ap.add_argument('--report', action='store_true',
                    help='measure the scheduled clock period, do not write RTL')
    ap.add_argument('--only', help='regenerate just this module')
    args = ap.parse_args()

    cfg = load_config()
    if args.list:
        for m in cfg['modules']:
            print(f"  {m['module']:<24s} {m['source']:<20s} top={m['top']:<20s}"
                  f" {m.get('pipeline_stages', 0) or 'comb'}")
        return 0

    runner = make_runner(cfg)
    print(f"  generator: {runner.describe()}")
    runner.prepare()
    if args.report:
        return report(cfg, runner, args.only)
    version = xls_version(runner)
    os.makedirs(OUT_DIR, exist_ok=True)

    stale, rows = [], []
    for mod in cfg['modules']:
        if args.only and mod['module'] != args.only:
            continue
        body, stats, pipeline = generate(cfg, runner, mod, version)
        src = os.path.join(DSLX_DIR, mod['source'])
        text = BANNER.format(src=f"xls/{mod['source']}", top=mod['top'],
                             version=version, pipeline=pipeline,
                             digest=digest_of(src)) + body
        path = os.path.join(OUT_DIR, mod['module'] + '.v')
        if args.check:
            cur = open(path).read() if os.path.exists(path) else None
            if cur != text:
                stale.append(os.path.relpath(path, ROOT))
        else:
            with open(path, 'w') as f:
                f.write(text)
        if stats:
            rows.append((mod['module'], int(stats[1]), int(stats[2]),
                         len(text.splitlines())))

    if rows:
        print(f"  {'module':<24s} {'IR':>8s} {'opt IR':>8s} {'shrink':>7s} "
              f"{'verilog':>8s}")
        for name, ir, opt, vlines in rows:
            print(f"  {name:<24s} {ir:>8d} {opt:>8d} "
                  f"{ir / max(opt, 1):>6.1f}x {vlines:>8d}")

    if args.check:
        if stale:
            print("FAIL: generated RTL is stale: " + ', '.join(stale))
            print("      run `make xls`")
            return 1
        print("PASS: rtl/gen matches the DSLX sources")
    return 0


if __name__ == '__main__':
    sys.exit(main())
