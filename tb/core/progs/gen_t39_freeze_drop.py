#!/usr/bin/env python3
"""
Generate tb/core/progs/t39_freeze_drop.s -- results from the FP, MUL and LSU
pipes completing while the transfer engine holds the banked register file's
write ports (R39, found reading the RTL).

On the banked file the transfer engine wins a bank it writes, and the
writeback stage holds its payload and retries (vrf_wb_freeze). The stage's
next payload is dropped in a frozen cycle unless what produced it waits too.
The X stage does (a stall inserts a bubble behind it), but the FP and MUL
pipes advance regardless of stalls and the LSU is told its completion was
taken. A result from one of them landing in a frozen cycle would be lost: its
register keeps the old value, and its scoreboard bit never clears -- the next
reader waits forever.

The engine streams a 16x16 f32 box (sixteen window registers, eight cycles
each) while two chains run under it, each writing every bank in turn:
  vf.mul (FP pipe) and v.mul (integer multiply).
(A load cannot complete under a transfer here: the engine has the memory
port first.) Every checked lane of both chains' results is checked, and so
is the window; `wb_retry` in the bench's counters shows the freeze happened.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from gen_t33_tdesc import Case, Mem, tensormap, box_elements  # noqa: E402

DESC = 0xC000
DATA = 0xD000
ONES = 0xF000        # 16 f32 1.0 and 16 i32 1, for the chains
WIN_BASE = 32
ROUNDS = 4
LINKS = 48


def main():
    mem = Mem()
    out = []
    w = out.append
    n = [0]

    def nid():
        n[0] += 1
        return n[0]

    c = Case('rank2 f32 16x16', 'f32', [16, 16], [16, 1], [16, 16], [0, 0])
    c.base = DATA
    mem.fill_pattern(DATA - 16, DATA + 16 * 16 * 4 + 16)
    mem.put_words(DESC, tensormap(c.base, c.extents, c.strides, c.block, c.dtype, c.pad))
    win = []
    for idx in box_elements(c.block):
        win += c.element(mem, idx)[0]
    one_f32 = 0x3F800000
    words = []
    for i in range(0, 16, 2):
        words.append(one_f32 | (one_f32 << 32))
    for i in range(0, 16, 2):
        words.append(1 | (1 << 32))
    mem.put_words(ONES, words)

    w("// t39_freeze_drop -- generated by gen_t39_freeze_drop.py; do not edit by hand.")
    w("// FP, MUL and LSU results completing while the transfer engine holds the banks.")
    w(".org 0")
    w("start:")
    w("    mb.init   b0")
    w(f"    .li       s1, #{DESC}")
    w(f"    .li       s2, #{ONES}")
    w("    td.load   d1, [s1]")
    w(f"    w.def     w1, #{WIN_BASE}, #16")
    w("    v.ld.w    v20, [s2, #0]          // 1.0f in every lane")
    w("    v.ld.w    v21, [s2, #64]         // 1 in every lane")
    w("    v.movi    v0, #1")
    w("    v.movi    v4, #1")
    w("    v.ld.w    v8, [s2, #0]")
    for r in range(ROUNDS):
        w(f"    // ---- round {r}: start the transfer, then the three chains under it ----")
        w("    mb.arm    s3, b0, #0, #1")
        w("    .li       s10, #0")
        w("    t.ld.async.w w1, d1, s10, s3")
        fp, mu, ld = ['v8', 'v9', 'v10', 'v11'], ['v0', 'v1', 'v2', 'v3'], ['v12', 'v13', 'v14', 'v15']
        for k in range(LINKS):
            a, b = fp[k % 4], fp[(k + 1) % 4]
            w(f"    vf.mul    {b}, {a}, v20")              # 1.0 * x: x
            a, b = mu[k % 4], mu[(k + 1) % 4]
            w(f"    v.mul     {b}, {a}, v21")              # 1 * x: x
        w("    mb.wait   s3")
        last = (LINKS) % 4
        for lane in (0, 5, 15):
            w(f"    .assert_lane {fp[last]}, #{lane}, #{one_f32:#x}, #{nid()}")
            w(f"    .assert_lane {mu[last]}, #{lane}, #1, #{nid()}")
        for li in range(0, len(win) // 4, 7):
            val = int.from_bytes(bytes(win[4 * li:4 * li + 4]), 'little')
            w(f"    .assert_lane v{WIN_BASE + li // 16}, #{li % 16}, #{val:#010x}, #{nid()}")
        # Next round starts from the ends of these chains.
        w(f"    v.add     v0, {mu[last]}, v21")
        w(f"    v.sub     v0, v0, v21")
        w(f"    vf.mul    v8, {fp[last]}, v20")
    w("    w.release w1")
    w("    td.release d1")
    w("    exit")
    w("")
    mem.emit(w)
    path = os.path.join(HERE, 't39_freeze_drop.s')
    open(path, 'w').write('\n'.join(out) + '\n')
    print(f"wrote {path}: {n[0]} checks")


if __name__ == '__main__':
    main()
