#!/usr/bin/env python3
"""
Generate tb/core/progs/t21_cvt.s.

`vf.cvt.<src>.<dst>` (ISA sec 8.4) as a program sees it: all twenty-five
source/destination pairs among the five float formats, sixteen lanes each.

tb_cvt_xls already checks the converter exhaustively against the oracle. What
this adds is everything between the instruction and that converter: the
mod[5:0] encoding, the decoder's legality check, the lane routing, the
predicated write, and the fact that a narrow result is left right-aligned in
its lane rather than packed.

Comparison is an integer compare of the whole lane, which is exact and
catches a stray bit in the unused upper half of a narrow result -- a float
compare would call 0x0000_3c00 and 0xdead_3c00 both equal to 1.0. NaN inputs
are therefore left out of the bulk vectors, because the ISA promises a quiet
NaN and not a payload; they are checked separately by class where the
destination is binary32, and tb_cvt_xls covers the rest.

Expectations come from tools/model/floatfmt.py, in exact Fractions.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..', '..'))
sys.path.insert(0, os.path.join(ROOT, 'tools', 'model'))
from floatfmt import FORMATS, CODE, convert, width, decode, NAN   # noqa: E402

VLEN = 16
ORDER = ['f32', 'bf16', 'f16', 'e5m2', 'e4m3']


def probes(fmt):
    """Sixteen source patterns for `fmt`, chosen where conversion is hard."""
    e_sz, f_sz, has_inf = FORMATS[fmt]
    top = (1 << e_sz) - 1
    b = (1 << (e_sz - 1)) - 1                       # bias
    one = b << f_sz

    out = [
        0,                                          # +0
        1 << (e_sz + f_sz),                         # -0
        one,                                        # +1
        one | (1 << (e_sz + f_sz)),                 # -1
        1,                                          # smallest subnormal
        (1 << f_sz) - 1,                            # largest subnormal
        1 << f_sz,                                  # smallest normal
        one | (1 << (f_sz - 1)),                    # 1.5, a clean tie source
        one | 1,                                    # 1 + 1ulp
        one | ((1 << f_sz) - 1),                    # just under 2
        (b + 1) << f_sz,                            # 2
        (b - 1) << f_sz,                            # 0.5
    ]
    # The top of the range: the largest finite, and the infinity if there is
    # one. E4M3 has no infinity, and its only NaN is S.1111.111.
    if has_inf:
        out += [((top - 1) << f_sz) | ((1 << f_sz) - 1),   # max finite
                top << f_sz,                               # +inf
                (1 << (e_sz + f_sz)) | (top << f_sz)]      # -inf
    else:
        out += [(top << f_sz) | ((1 << f_sz) - 2),         # max finite (448)
                (top << f_sz),
                (1 << (e_sz + f_sz)) | (top << f_sz)]
    out.append((b + 4) << f_sz)                            # 32
    assert len(out) == VLEN, len(out)
    mask = (1 << width(fmt)) - 1
    got = [v & mask for v in out]
    assert not any(decode(fmt, v) == NAN for v in got), f"{fmt} probe is a NaN"
    return got


out = []
w = out.append
tid = [0]
data = {}


def nid():
    tid[0] += 1
    return tid[0]


w("// t21_cvt -- generated by gen_t21_cvt.py; do not edit by hand.")
w("// ISA sec 8.4 vf.cvt.<src>.<dst>. Expectations from tools/model/floatfmt.py")
w("// (exact Fractions), compared bit for bit with an integer compare.")
w(".org 0")
w("start:")

for src in ORDER:
    xs = probes(src)
    data[f"x_{src}"] = xs
    for dst in ORDER:
        ys = [convert(src, dst, b) for b in xs]
        data[f"e_{src}_{dst}"] = ys
        w(f"    // ---- vf.cvt.{src}.{dst} ----")
        w(f"    .li      s1, #x_{src}")
        w("    v.ld.w   v1, [s1, #0]")
        w(f"    vf.cvt.{src}.{dst} v2, v1")
        w(f"    .li      s2, #e_{src}_{dst}")
        w("    v.ld.w   v3, [s2, #0]")
        w("    v.cmp.eq p1, v2, v3")
        w("    p.ballot s3, p1")
        w(f"    .assert_eq s3, #0xffff, #{nid()}")
    w("")

# ---- NaN: checked by class, where the destination can express one ----------
def qnan(fmt):
    """That format's canonical quiet NaN, right-aligned."""
    e_sz, f_sz, has_inf = FORMATS[fmt]
    top = (1 << e_sz) - 1
    return (top << f_sz) | ((1 << (f_sz - 1)) if has_inf else ((1 << f_sz) - 1))


# A NaN is checked by class, not by pattern: the ISA promises a quiet NaN and
# not a payload. vf.cmp.uo is that test, and it needs a binary32 operand, so
# this runs each narrow format into binary32. One source vector per format,
# because the patterns do not survive being read as each other -- bf16's
# 0x7fc0 read as e5m2 is 0xc0, which is -512 and perfectly ordered.
w("    // ---- a NaN source stays a NaN, whatever the payload ----------------")
for src in ('bf16', 'f16', 'e5m2', 'e4m3'):
    data[f"nan_{src}"] = [qnan(src)] * VLEN
    w(f"    .li      s1, #nan_{src}")
    w("    v.ld.w   v1, [s1, #0]")
    w(f"    vf.cvt.{src}.f32 v2, v1")
    w("    vf.cmp.uo p1, v2, v2")
    w("    p.ballot s3, p1")
    w(f"    .assert_eq s3, #0xffff, #{nid()}")
w("")

w("    // ---- a masked convert leaves the inactive lanes alone --------------")
w("    .li      s5, #0x00ff")
w("    p.frombits p5, s5")
w("    v.movi   v6, #-1")
w("    .li      s1, #x_f32")
w("    v.ld.w   v1, [s1, #0]")
w("    @p5 vf.cvt.f32.e4m3 v6, v1")
w("    .li      s2, #e_f32_e4m3")
w("    v.ld.w   v3, [s2, #0]")
w("    v.cmp.eq p1, v6, v3")
w("    p.ballot s3, p1")
w("    s.and    s3, s3, s5")
w(f"    .assert_eq s3, #0x00ff, #{nid()}      // the written lanes converted")
for lane in (8, 15):
    w(f"    .assert_lane v6, #{lane}, #0xffffffff, #{nid()}   // and the rest did not")
w("")
w("    exit")
w("")

def words(label, vals):
    w(f"{label}:")
    for k in range(0, len(vals), 8):
        w("    .word " + ", ".join(f"0x{v & 0xffffffff:08x}" for v in vals[k:k + 8]))


w(".org 0x8000")
for label, vals in data.items():
    words(label, vals)

path = os.path.join(HERE, 't21_cvt.s')
with open(path, 'w') as fh:
    fh.write("\n".join(out) + "\n")
print(f"{len(out)} lines, {tid[0]} checks -> {path}")
