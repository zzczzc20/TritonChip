#!/usr/bin/env python3
"""
Generate tb/core/progs/t11_matrix.s -- mbarrier, accumulators and the matrix
unit.

The matrix expectations come from tools/model/fp32.py's mma_ref, which follows
the ISA's accumulation contract literally: each product exact, one rounding per
addition, increasing k order. A reference that used a library matmul would
reassociate and would therefore not be checking the thing the contract is about.
"""
import os
import random
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..', '..'))
sys.path.insert(0, os.path.join(ROOT, 'tools', 'model'))
from fp32 import (f32_to_f16_bits, f16_bits_to_f32_bits, mma_ref, fma_ref,   # noqa
                  f2b, b2f)

M = N = 16
K = 16
A_BASE = 0x2000
B_BASE = 0x2400
P_BASE = 0x2800          # an FP32 pattern for the accumulator tests

rng = random.Random(20260919)

out = []
w = out.append
tid = [0]


def nid():
    tid[0] += 1
    return tid[0]


# ---- data ------------------------------------------------------------------
# Values that stay exactly representable often enough to keep the test readable,
# with enough awkward ones to make the rounding contract matter.
def rnd_half():
    r = rng.random()
    if r < 0.4:
        return f32_to_f16_bits(rng.randint(-8, 8))
    if r < 0.7:
        return f32_to_f16_bits(rng.randint(-32, 32) / 4.0)
    return f32_to_f16_bits(rng.uniform(-6.0, 6.0))


A = [rnd_half() for _ in range(M * K)]
B = [rnd_half() for _ in range(K * N)]
C0 = [f2b(0.0)] * (M * N)
C = mma_ref(A, B, C0, M, N, K)

PAT = [f2b(rng.uniform(-100.0, 100.0)) for _ in range(N)]

w("// t11_matrix -- generated by gen_t11_matrix.py; do not edit by hand.")
w("// Expectations from tools/model/fp32.py (exact products, one rounding per")
w("// addition, increasing k order -- ISA sec 9C.1).")
w(".org 0")
w("start:")

# ---- mbarrier --------------------------------------------------------------
w("    // ---- mbarrier: arrivals only ----")
w("    mb.init   b0")
w("    mb.arm    s1, b0, #2, #0")
w("    mb.test   s2, s1")
w(f"    .assert_eq s2, #0, #{nid()}")
w("    mb.arrive b0")
w("    mb.test   s2, s1")
w(f"    .assert_eq s2, #0, #{nid()}")
w("    mb.arrive b0")
w("    mb.test   s2, s1")
w(f"    .assert_eq s2, #1, #{nid()}")
w("    mb.wait   s1                  // already complete: must not block")
w("")
w("    // a second generation on the same barrier is independent")
w("    mb.arm    s3, b0, #1, #0")
w("    mb.test   s4, s3")
w(f"    .assert_eq s4, #0, #{nid()}")
w("    mb.arrive b0")
w("    mb.wait   s3")
w("    mb.test   s4, s3")
w(f"    .assert_eq s4, #1, #{nid()}")
w("")

# ---- accumulator -----------------------------------------------------------
w("    // ---- accumulator ----")
w("    a.zero    a0")
w("    .li       s5, #3")
w("    a.vread   v1, a0, s5")
for lane in (0, 7, 15):
    w(f"    .assert_lane v1, #{lane}, #0x00000000, #{nid()}")
w("")
w(f"    .li       s6, #{P_BASE}")
w("    v.ld.w    v2, [s6, #0]")
w("    a.vwrite  a0, s5, v2")
w("    a.vread   v3, a0, s5")
for lane in (0, 5, 15):
    w(f"    .assert_lane v3, #{lane}, #0x{PAT[lane]:08x}, #{nid()}")
w("    // a different row must be untouched")
w("    .li       s7, #4")
w("    a.vread   v4, a0, s7")
w(f"    .assert_lane v4, #0, #0x00000000, #{nid()}")
w("")
w("    // a.mul.row: one rounding, not a multiply then an add")
w(f"    .li       s8, #0x{f2b(3.0):08x}       // 3.0f")
w("    a.mul.row a0, s5, s8")
w("    a.vread   v3, a0, s5")
for lane in (0, 5, 15):
    e = fma_ref(PAT[lane], f2b(3.0), 0, mul_only=True)
    w(f"    .assert_lane v3, #{lane}, #0x{e:08x}, #{nid()}")
w("")
w("    // a.fma.row: acc = fma(acc, scale, Vx)")
w("    v.ld.w    v5, [s6, #64]")
w(f"    .li       s9, #0x{f2b(-0.5):08x}      // -0.5f")
w("    a.fma.row a0, s5, v5, s9")
w("    a.vread   v3, a0, s5")
PAT2 = [f2b(rng.uniform(-50.0, 50.0)) for _ in range(N)]
for lane in (0, 5, 15):
    prev = fma_ref(PAT[lane], f2b(3.0), 0, mul_only=True)
    e = fma_ref(prev, f2b(-0.5), PAT2[lane])
    w(f"    .assert_lane v3, #{lane}, #0x{e:08x}, #{nid()}")
w("")
w("    // masked accumulator write leaves inactive lanes alone")
w("    a.zero    a2")
w("    v.iota    v6")
w("    v.cmpi.lt p1, v6, #8")
w("    @p1 a.vwrite a2, s5, v2")
w("    a.vread   v7, a2, s5")
w(f"    .assert_lane v7, #3, #0x{PAT[3]:08x}, #{nid()}")
w(f"    .assert_lane v7, #11, #0x00000000, #{nid()}")
w("")

# ---- matrix ----------------------------------------------------------------
w("    // ---- m.mma.async: C = A.B, completion through a barrier ----")
w(f"    .li       s10, #{A_BASE}")
for i in range(8):
    w(f"    v.ld.w    v{32+i}, [s10, #{i*64}]")
w(f"    .li       s11, #{B_BASE}")
for i in range(8):
    w(f"    v.ld.w    v{40+i}, [s11, #{i*64}]")
w("    m.zero    a1")
w("    mb.init   b1")
w("    mb.arm    s12, b1, #0, #1     // one asynchronous operation")
w("    m.mma.async a1, v32, v40, s12")
w("    mb.wait   s12                 // sleeps until the engine signals")
w("")
CHECK_ROWS = [0, 1, 7, 14, 15]
for r in CHECK_ROWS:
    w(f"    .li       s13, #{r}")
    w(f"    a.vread   v8, a1, s13")
    for c in (0, 1, 8, 15):
        w(f"    .assert_lane v8, #{c}, #0x{C[r*N+c]:08x}, #{nid()}")
w("")
w("    // A second MMA accumulates onto the same C: 2*A.B")
w("    mb.arm    s12, b1, #0, #1")
w("    m.mma.async a1, v32, v40, s12")
w("    mb.wait   s12")
C2 = mma_ref(A, B, C, M, N, K)
for r in (0, 9):
    w(f"    .li       s13, #{r}")
    w(f"    a.vread   v8, a1, s13")
    for c in (0, 15):
        w(f"    .assert_lane v8, #{c}, #0x{C2[r*N+c]:08x}, #{nid()}")
w("")
w("    exit")
w("")

# ---- data ------------------------------------------------------------------
def emit_words(label, addr, words):
    w(f".org 0x{addr:x}")
    w(f"{label}:")
    for k in range(0, len(words), 8):
        w("    .word " + ", ".join(f"0x{v:08x}" for v in words[k:k+8]))


# FP16 pairs packed into 32-bit words, low half first: exactly the flat layout
# the fragment addressing in ISA sec 9C.2 describes.
def pack(h):
    return [(h[2*i+1] << 16) | h[2*i] for i in range(len(h)//2)]


emit_words("a_frag", A_BASE, pack(A))
emit_words("b_frag", B_BASE, pack(B))
emit_words("pat", P_BASE, PAT + PAT2)

path = os.path.join(HERE, 't11_matrix.s')
with open(path, 'w') as fh:
    fh.write("\n".join(out) + "\n")
print(f"{tid[0]} checks -> {path}")
