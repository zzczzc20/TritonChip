#!/usr/bin/env python3
"""
Generate tb/core/progs/t38_wbfreeze.s -- a dependent vector chain run while
the transfer engine streams into the same register banks (R39-00, B1).

On the banked register file the transfer engine wins a bank it writes, and
the writeback stage holds its payload and retries (vrf_wb_freeze). If the
scoreboard released the destination in the refused cycle, a consumer could
fetch the register before the retried write landed and carry the old value
into execute. Two refusals in a row are what expose it: the bank's own
write-first bypass covers a read in the cycle the retry lands, not one in a
cycle it is refused again. The engine writes a window register two lanes per
cycle, eight cycles per register, so a box of sixteen f32 rows keeps each
bank busy eight cycles at a time -- and a chain that walks v0..v3 (one per
bank) keeps a writeback pending in whichever bank the engine is on.

The chain is checked at the end (every lane holds its length), and so is
every lane of the window. The core also asserts, in simulation, that no
operand read is issued for a register whose writeback is being held.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from gen_t33_tdesc import Case, Mem, tensormap, box_elements  # noqa: E402

DESC = 0xC000
DATA = 0xD000
WIN_BASE = 32
ROUNDS = 4          # transfers, each with its own chain
LINKS = 96          # chain steps per round (four registers, one per bank)


def main():
    mem = Mem()
    out = []
    w = out.append
    n = [0]

    def nid():
        n[0] += 1
        return n[0]

    c = Case('rank2 f32 16x16', 'f32', [16, 16], [16, 1], [16, 16], [0, 0])
    c.base = DATA
    mem.fill_pattern(DATA - 16, DATA + 16 * 16 * 4 + 16)
    mem.put_words(DESC, tensormap(c.base, c.extents, c.strides, c.block, c.dtype, c.pad))
    win = []
    for idx in box_elements(c.block):
        win += c.element(mem, idx)[0]

    w("// t38_wbfreeze -- generated by gen_t38_wbfreeze.py; do not edit by hand.")
    w("// A dependent chain across all four banks while the transfer engine streams.")
    w(".org 0")
    w("start:")
    w("    mb.init   b0")
    w(f"    .li       s1, #{DESC}")
    w("    td.load   d1, [s1]")
    w(f"    w.def     w1, #{WIN_BASE}, #16")
    w("    v.movi    v0, #0")
    total = 0
    for r in range(ROUNDS):
        w(f"    // ---- round {r}: start the transfer, then run the chain under it ----")
        w("    mb.arm    s3, b0, #0, #1")
        w("    .li       s10, #0")
        w("    .li       s11, #0")
        w("    t.ld.async.w w1, d1, s10, s3")
        regs = ['v0', 'v1', 'v2', 'v3']
        prev = 'v0'
        for k in range(LINKS):
            dst = regs[(k + 1) % 4]
            w(f"    v.addi    {dst}, {prev}, #1")
            prev = dst
        total += LINKS
        w("    mb.wait   s3")
        for lane in (0, 7, 15):
            w(f"    .assert_lane {prev}, #{lane}, #{total:#x}, #{nid()}")
        for li in range(0, len(win) // 4, 5):
            val = int.from_bytes(bytes(win[4 * li:4 * li + 4]), 'little')
            w(f"    .assert_lane v{WIN_BASE + li // 16}, #{li % 16}, #{val:#010x}, #{nid()}")
        # The next round's chain starts from where this one ended.
        if prev != 'v0':
            w(f"    v.addi    v0, {prev}, #0")
    w("    w.release w1")
    w("    td.release d1")
    w("    exit")
    w("")
    mem.emit(w)
    path = os.path.join(HERE, 't38_wbfreeze.s')
    open(path, 'w').write('\n'.join(out) + '\n')
    print(f"wrote {path}: {n[0]} checks")


if __name__ == '__main__':
    main()
