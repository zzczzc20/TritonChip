#!/usr/bin/env python3
"""
Generate tb/core/progs/t18_squash.s -- a taken branch must squash what follows.

A taken branch has to kill the younger instructions of its own Role Context.
When the front end was stalled, the entry held in decode was killed on the
basis of which context the FETCH stage was selecting rather than the context
of the entry actually held. With one Role Context those two always coincide,
so every single-role test passed. With two they do not, and about half the
time a taken branch left a younger instruction alive.

The shape that exposed it -- a loop branch immediately followed by a trap --
is what a compiler emits for a bounded spin, so it arrived via milestone C4
rather than from RTL testing. Role 1 loops; the trap after its loop branch
must never execute. Role 0 runs concurrently, because a single role cannot
reproduce this.
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))

ITERS = 40
FLAG = 0x8000

out = []
w = out.append
w("// t18_squash -- generated by gen_t18_squash.py; do not edit by hand.")
w("//")
w("// A taken branch must squash the instruction after it. Needs two Role")
w("// Contexts: with one, the fetch selection and the held entry's context")
w("// always agree and the bug is invisible. Run with +allroles.")
w(".org 0")
w("start:")
w("    s.rdspecial s60, role_id")
w("    br.nz     s60, role1")
w("")
w("// ---------------------------------------------------------------- role 0")
w("// Present only to make the front end stall and the fetch selection")
w("// alternate. What it computes does not matter.")
w("role0:")
w(f"    .li       s1, #{FLAG}")
w("    .li       s2, #0")
w("    .li       s3, #64")
w("r0loop:")
w("    s.ld.d    s4, [s1, #0]")
w("    s.add     s2, s2, s4")
w("    s.addi    s3, s3, #-1")
w("    br.nz     s3, r0loop")
w("    exit")
w("")
w("// ---------------------------------------------------------------- role 1")
w("role1:")
w(f"    .li       s1, #{FLAG}")
w(f"    .li       s2, #{ITERS}")
w("    .li       s4, #0")
w("loop:")
w("    s.ld.d    s3, [s1, #0]          // a load, to stall the front end")
w("    s.addi    s4, s4, #1")
w("    s.addi    s2, s2, #-1")
w("    br.nz     s2, loop")
w("    // Falling through here is correct once the count is exhausted. The")
w("    // bug made it happen while the branch was TAKEN, so the counter check")
w("    // below is what catches it: the loop body ran fewer times than the")
w("    // branch said it should.")
w("after:")
w(f"    .assert_eq s4, #{ITERS}, #1   // the loop ran exactly {ITERS} times")
w("    .assert_eq s2, #0, #2")
w("    exit")
w("")
w(f".org {FLAG:#x}")
w("flag:")
w("    .dword 0")
w("")

path = os.path.join(HERE, 't18_squash.s')
open(path, 'w').write('\n'.join(out) + '\n')
print(f"wrote {path}")
