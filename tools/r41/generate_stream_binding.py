#!/usr/bin/env python3
"""Generate the fixed 32-PC stream CU binding and its packaging metadata."""
from pathlib import Path
import argparse
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[2]
# Direction is relative to the CU; widths match tnca_stream_bank.
FIELDS = [('awvalid','output',1),('awready','input',1),('awaddr','output',64),
 ('awid','output',1),('awlen','output',8),('awsize','output',3),('awburst','output',2),
 ('wvalid','output',1),('wready','input',1),('wdata','output',512),('wstrb','output',64),('wlast','output',1),
 ('bvalid','input',1),('bready','output',1),('bid','input',1),('bresp','input',2),
 ('arvalid','output',1),('arready','input',1),('araddr','output',64),('arid','output',1),
 ('arlen','output',8),('arsize','output',3),('arburst','output',2),
 ('rvalid','input',1),('rready','output',1),('rdata','input',512),('rid','input',1),('rresp','input',2),('rlast','input',1)]
CONTROL = [('awvalid','input',1),('awready','output',1),('awaddr','input',12),
 ('wvalid','input',1),('wready','output',1),('wdata','input',32),('wstrb','input',4),
 ('arvalid','input',1),('arready','output',1),('araddr','input',12),
 ('rvalid','output',1),('rready','input',1),('rdata','output',32),('rresp','output',2),
 ('bvalid','output',1),('bready','input',1),('bresp','output',2)]


def declaration(direction, width, name):
    return f' {direction} wire ' + (f'[{width-1}:0] ' if width > 1 else '') + name


def rtl():
    ports = [' input wire ap_clk,ap_rst_n']
    ports += [declaration(d,w,'s_axi_tnca_'+n) for n,d,w in CONTROL]
    ports += [declaration(d,w,f'm_axi_pc{p}_{n}') for p in range(32) for n,d,w in FIELDS]
    text = ['// Generated by tools/r41/generate_stream_binding.py; edit its source.',
            '// All stream masters are pinned to their named physical PC.',
            '`default_nettype none', 'module tnca_stream_hbm_xo(', ',\n'.join(ports), ');',
            ' (* ASYNC_REG="TRUE" *) reg [1:0] reset_sync=0;',
            ' always @(posedge ap_clk or negedge ap_rst_n)begin',
            "  if(!ap_rst_n)reset_sync<=0;else reset_sync<={reset_sync[0],1'b1};", ' end',
            ' wire rst_n=reset_sync[1];',
            ' wire [11:0] reg_addr;wire [63:0] reg_wdata,reg_rdata;wire reg_we,reg_re;',
            ' tnca_axi_lite #(.ADDR_BITS(12),.S_AXI_ADDR_W(12)) registers(',
            '  .s_axi_aclk(ap_clk),.s_axi_aresetn(rst_n),.reg_clk(ap_clk),.reg_rst_n(rst_n),',
            '  .reg_addr(reg_addr),.reg_wdata(reg_wdata),.reg_we(reg_we),.reg_re(reg_re),.reg_rdata(reg_rdata),']
    text += [',\n'.join(f'  .s_axi_{n}(s_axi_tnca_{n})' for n,_,_ in CONTROL), ' );']
    text += [f' wire [{32*w-1}:0] bank_{n};' for n,_,w in FIELDS]
    for p in range(32):
        for name, direction, width in FIELDS:
            bank = f'bank_{name}[{p*width}+:{width}]'
            port = f'm_axi_pc{p}_{name}'
            text.append(f' assign {port if direction=="output" else bank}={bank if direction=="output" else port};')
    text += [' tnca_stream_bank #(.LANES(32)) stream_bank(',
             '  .clk(ap_clk),.rst_n(rst_n),.reg_addr(reg_addr),.reg_wdata(reg_wdata),',
             '  .reg_we(reg_we),.reg_rdata(reg_rdata),.busy(),.fault(),']
    text += [',\n'.join(f'  .m_{n}(bank_{n})' for n,_,_ in FIELDS), ' );', 'endmodule', '`default_nettype wire', '']
    return '\n'.join(text)


def kernel_xml():
    root = ET.Element('root', versionMajor='1', versionMinor='6')
    kernel = ET.SubElement(root, 'kernel', name='tnca_stream', language='ip_c',
        vlnv='tnca.com:kernel:tnca_stream:1.0', attributes='', preferredWorkGroupSizeMultiple='0',
        workGroupSize='1', interrupt='false', hwControlProtocol='ap_ctrl_none')
    ports = ET.SubElement(kernel, 'ports')
    ET.SubElement(ports, 'port', name='s_axi_tnca', mode='slave', range='0x1000', dataWidth='32', portType='addressable', base='0x0')
    for p in range(32):
        ET.SubElement(ports, 'port', name=f'm_axi_pc{p}', mode='master', range='0xFFFFFFFFFFFFFFFF',
                      dataWidth='512', portType='addressable', base='0x0')
    args = ET.SubElement(kernel, 'args')
    for p in range(32):
        # XRT uses these argument bindings for connectivity metadata. Addresses
        # are fixed per PC in RTL; the IP is driven through its command map.
        ET.SubElement(args, 'arg', name=f'pc{p}', addressQualifier='1', id=str(p), port=f'm_axi_pc{p}',
                      size='0x8', offset=hex(0x200+p*8), hostOffset='0x0', hostSize='0x8', type='void*')
    ET.indent(root, space='  ')
    return '<?xml version="1.0" encoding="UTF-8"?>\n'+ET.tostring(root, encoding='unicode')+'\n'


def connectivity():
    return ('# Generated by tools/r41/generate_stream_binding.py.\n[connectivity]\n'
            'nk=tnca_u50:1:tnca_u50_1\nnk=tnca_stream:1:tnca_stream_1\n'
            + ''.join(f'sp=tnca_u50_1.hbm{p}:HBM[0:31]\n' for p in range(3))
            + ''.join(f'sp=tnca_stream_1.pc{p}:HBM[{p}]\n' for p in range(32)))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    outputs = {'rtl/board/tnca_stream_hbm_xo.v': rtl(),
               'fpga/kernel_stream_hbm.xml': kernel_xml(),
               'fpga/u280_multicore_stream.cfg': connectivity()}
    for name, text in outputs.items():
        path = ROOT/name
        if args.check:
            if not path.is_file() or path.read_text() != text:
                raise SystemExit(f'generated stream binding differs: {name}')
        else:
            path.write_text(text)
    print('Stream CU binding metadata matches' if args.check else 'Generated stream CU binding metadata')


if __name__ == '__main__':
    main()
